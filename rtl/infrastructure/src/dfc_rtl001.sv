  output logic         dri_rsp_valid_o,
  input  logic         dri_rsp_ready_i,
  output logic [31:0]  dri_rsp_rdata_o,
  output logic [2:0]   dri_rsp_code_o,

  // REAL cross-module register bus for RTL-002 (System Control Logic) --
  // replaces the tie-off stubs this project previously had for SYS_STATUS/
  // SUBSYS_READY/SUBSYS_FAULT/RESET_STATUS/RESET_DIAGNOSTIC (status side)
