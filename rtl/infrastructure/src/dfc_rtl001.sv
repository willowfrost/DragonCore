  output logic [dfc_types_pkg::DFC_RTL007_CONTROL_WIDTH-1:0] rtl007_control_o,
  input  logic [dfc_types_pkg::DFC_RTL007_STATUS_WIDTH-1:0]  rtl007_status_i,

  // REAL cross-module register bus for RTL-008 (Engine RPM Monitor) -- same
  // treatment as RTL-002/003/004/005/006/007 above, generated by reggen.py
  // v4 from tools/reggen/rtl008_field_map.json. Replaces the individual
  // stub-tied engine_status_status_i/engine_rpm_status_i/
  // engine_period_ticks_status_i/rtl008_evt_overflow_status_status_i ports
  // this module previously had.
  output logic [dfc_types_pkg::DFC_RTL008_CONTROL_WIDTH-1:0] rtl008_control_o,
  input  logic [dfc_types_pkg::DFC_RTL008_STATUS_WIDTH-1:0]  rtl008_status_i,

  // REAL cross-module register bus for RTL-009 (Pulse/Frequency
  // Measurement) -- same treatment as RTL-002/003/004/005/006/007/008
  // above, generated by reggen.py v4 from
  // tools/reggen/rtl009_field_map.json. Replaces the individual stub-tied
  // pulse0_status_status_i/pulse0_freq_q17_15_status_i/
  // pulse0_period_ticks_status_i/pulse1_status_status_i/
  // pulse1_freq_q17_15_status_i/pulse1_period_ticks_status_i/
  // rtl009_evt_overflow_status_status_i ports this module previously had.
  output logic [dfc_types_pkg::DFC_RTL009_CONTROL_WIDTH-1:0] rtl009_control_o,
  input  logic [dfc_types_pkg::DFC_RTL009_STATUS_WIDTH-1:0]  rtl009_status_i,

  // REAL cross-module register bus for RTL-010 (Sensor Monitor Interface)
  // -- same treatment as RTL-002/003/004/005/006/007/008/009 above,
  // generated by reggen.py v4 from tools/reggen/rtl010_field_map.json.
  // Replaces the individual stub-tied sensor_status_status_i/
  // sensor0_value_status_i/sensor0_status_status_i/
  // sensor0_current_age_ms_status_i/sensor1_value_status_i/
  // sensor1_status_status_i/sensor1_current_age_ms_status_i/
  // rtl010_evt_overflow_status_status_i/sensor0_meta_status_i/
  // sensor1_meta_status_i ports this module previously had.
  output logic [dfc_types_pkg::DFC_RTL010_CONTROL_WIDTH-1:0] rtl010_control_o,
  input  logic [dfc_types_pkg::DFC_RTL010_STATUS_WIDTH-1:0]  rtl010_status_i,

  // REAL cross-module register bus for RTL-011 (System Health Monitor) --
  // same treatment as RTL-002 through RTL-010 above, generated by
  // reggen.py v4 from tools/reggen/rtl011_field_map.json. Replaces the
  // individual stub-tied health_raw_in_status_i/health_sync_in_status_i/
  // health_qual_in_status_i/health_active_status_i/health_sticky_status_i/
  // rtl011_evt_overflow_status_status_i/health_qualification_status_i/
  // health_status_status_i ports this module previously had.
  output logic [dfc_types_pkg::DFC_RTL011_CONTROL_WIDTH-1:0] rtl011_control_o,
  input  logic [dfc_types_pkg::DFC_RTL011_STATUS_WIDTH-1:0]  rtl011_status_i,

  // REAL cross-module register bus for RTL-012 (Watchdog Manager) -- same
  // treatment as RTL-002 through RTL-011 above, generated by reggen.py v4
  // from tools/reggen/rtl012_field_map.json. Replaces the individual
  // stub-tied wdog_status_status_i/wdog_elapsed_us_status_i/
  // rtl012_evt_overflow_status_status_i ports this module previously had.
  output logic [dfc_types_pkg::DFC_RTL012_CONTROL_WIDTH-1:0] rtl012_control_o,
  input  logic [dfc_types_pkg::DFC_RTL012_STATUS_WIDTH-1:0]  rtl012_status_i,

  // REAL cross-module register bus for RTL-013 (Fault Manager) -- same
  // treatment as RTL-002 through RTL-012 above, generated by reggen.py v4
  // from tools/reggen/rtl013_field_map.json. Replaces the individual
  // stub-tied fault_status_status_i/fault_class_status_i/
  // degraded_status_status_i/fault_active_source_status_i/
  // fault_latched_source_status_i/rtl013_evt_overflow_status_status_i ports
  // this module previously had.
  output logic [dfc_types_pkg::DFC_RTL013_CONTROL_WIDTH-1:0] rtl013_control_o,
  input  logic [dfc_types_pkg::DFC_RTL013_STATUS_WIDTH-1:0]  rtl013_status_i,

  // REAL cross-module register bus for RTL-014 (Interlock Engine) --
  // generated by reggen.py v5 from tools/reggen/rtl014_field_map.json,
  // including the selector-indexed eight-entry staging bank (complete bank
  // forwarded in rtl014_control_o). Replaces the eight individual stub-tied
  // ilock_status/ilock_active_result/rtl014_evt_overflow_status/
  // ilock_active_terms/_logic/_guard/_enable/_response status_i ports.
  output logic [dfc_types_pkg::DFC_RTL014_CONTROL_WIDTH-1:0] rtl014_control_o,
  input  logic [dfc_types_pkg::DFC_RTL014_STATUS_WIDTH-1:0]  rtl014_status_i,

  // RTL-001's OWN real status_o (dfc_rtl001_status_t, 19 bits: ready,
  // fault, event_overflow, event_drop_count[15:0] -- ARCH-002 Appendix
  // B.5). Added this session, closing a real, previously-disclosed gap:
  // this port genuinely did not exist before, and RTL-002's
  // module_ready_i[0]/module_fault_i[0] (which this port feeds, via
  // dfc_rtl024.sv) were tied to a permanent placeholder regardless of
  // RTL-001's real condition.
  //
  // ready: REAL. RTL-001 has no complex startup sequence of its own (no
  // module_reset_i at all -- Appendix D.1, system/external-reset-only)
  // and no mandatory precondition beyond being released from reset, so
  // ready is unconditionally 1'b1 once out of reset.
  // fault: DISCLOSED GAP, not silently invented as 0. ARCH-RTL001-001
  // implies fault should reflect CONFIG_ERROR_STATUS-class conditions
  // (INVALID_ADDRESS/UNALIGNED/ACCESS_ERROR/PROTECTED_ERROR/
  // ENDPOINT_ERROR/TIMEOUT/CRC_OR_FRAME/MULTIPLE), but this module does
  // not yet implement CONFIG_ERROR_STATUS/CONFIG_ERROR_ADDR/
  // CONFIG_ERROR_DATA capture at all (reggen.py's own "internal_capture"
  // class is reset-value-only, not yet hand-authored here) -- tied to
  // 1'b0 until that's real. Log in OPEN_ISSUES.md.
  // event_overflow/event_drop_count: DISCLOSED GAP -- RTL-001's own event
  // generation is not implemented either (a separate scope from RTL-002's,
  // which this session did implement); tied to 0.
  output logic [dfc_types_pkg::DFC_RTL001_STATUS_WIDTH-1:0] status_o,

  // Formal-verification observability port -- NOT a stub, NOT a
  // temporary termination, a real, permanently-connected output that
  // remains in the final design. Added specifically because a formal
  // harness (verification/formal/rtl-001/dri_one_outstanding_formal.sv)
  // needs to check that a register-bank write commit only ever happens
  // in the same cycle as an OK response, and two other mechanisms for
  // observing this internal signal from that harness were confirmed
  // broken: a hierarchical reference (Yosys's frontend parses
  // "instance.signal" as a bogus escaped identifier rather than
  // resolving into the instance -- confirmed via a real run reporting it
  // as an undriven wire) and SystemVerilog `bind` (confirmed to compile
  // with zero errors but silently produce zero cells -- the checker
  // never actually gets bound at all, which is worse than an explicit
  // error). Exposing this as a real port sidesteps both toolchain gaps
  // entirely -- it becomes an ordinary signal, no special mechanism
  // needed. RTLSTD-MOD-014's general prohibition on exposing internal
  // state governs ordinary production interfaces; this is a deliberate,
  // documented exception for formal-verification observability, not a
  // violation of it.
  output logic         dbg_regbank_write_en_o
);

  // RTLSTD-LANG-008 prohibits wildcard imports; confirmed via real Yosys
  // synthesis that this construct fails to parse regardless of version.
  // Every cross-package symbol below is fully qualified at its use site
  // instead -- no import statement is emitted.

  // ---- DRI response codes (ARCH-DRI-008) ----
  localparam logic [2:0] RSP_OK              = 3'b000;
  localparam logic [2:0] RSP_DECODE_ERROR    = 3'b001;
  localparam logic [2:0] RSP_ACCESS_ERROR    = 3'b010;
  localparam logic [2:0] RSP_PROTECTED_ERROR = 3'b011;
  // ENDPOINT_ERROR (100), TIMEOUT (101), BUSY (110) are not produced by
  // this first implementation -- see SCOPE note above.

  // ---- FSM ----
  typedef enum logic [1:0] { S_IDLE, S_RESPOND } state_e;
  state_e state_q, state_d;

  logic [31:0] req_addr_q, req_wdata_q;
  logic        req_write_q;
  logic [2:0]  rsp_code_q;

  // one-outstanding (ARCH-002 SS7.1): only accept in S_IDLE
  assign dri_req_ready_o = (state_q == S_IDLE);
  wire   req_accept = dri_req_valid_i && dri_req_ready_o;

  // ---- regbank instance: addr_i muxed by FSM state (see file header) ----
  logic [31:0] regbank_addr;
  logic [31:0] regbank_rdata;
  logic        regbank_decode_hit, regbank_write_illegal, regbank_protected;
  logic        regbank_write_en;

  assign regbank_addr = (state_q == S_IDLE) ? dri_req_addr_i : req_addr_q;

  // ---- protection / authorization (REG-002 SS4) ----
  typedef enum logic [1:0] { P_IDLE, P_KEY1_SEEN, P_ARMED } prot_state_e;
  prot_state_e prot_state_q, prot_state_d;
  logic [31:0] prot_timeout_q;
  wire         key1_write = req_accept && dri_req_write_i &&
                            (dri_req_addr_i == dfc_registers_pkg::DFC_ADDR_PROTECT_KEY) &&
                            (dri_req_wdata_i == dfc_constants_pkg::DFC_PROTECT_KEY1);
  wire         key2_write = req_accept && dri_req_write_i &&
                            (dri_req_addr_i == dfc_registers_pkg::DFC_ADDR_PROTECT_KEY) &&
                            (dri_req_wdata_i == dfc_constants_pkg::DFC_PROTECT_KEY2);
  wire         protect_key_write = req_accept && dri_req_write_i &&
                            (dri_req_addr_i == dfc_registers_pkg::DFC_ADDR_PROTECT_KEY);
  wire         authorized = (prot_state_q == P_ARMED);

  always_comb begin
    prot_state_d = prot_state_q;
    unique case (prot_state_q)
      P_IDLE:      if (key1_write) prot_state_d = P_KEY1_SEEN;
      P_KEY1_SEEN: begin
        if (key2_write) prot_state_d = P_ARMED;
        else if (protect_key_write) prot_state_d = P_IDLE;  // bad second key
      end
      P_ARMED: begin
        // consumed by exactly one accepted protected write, or by timeout
        if (protect_key_write) prot_state_d = P_IDLE;  // re-keying clears arm
        else if (req_accept && dri_req_write_i && regbank_protected &&
                 regbank_decode_hit && !regbank_write_illegal &&
                 (dri_req_wstrb_i == 4'b1111))
          prot_state_d = P_IDLE;  // consumed this cycle
        else if (prot_timeout_q == 32'd0)
          prot_state_d = P_IDLE;  // timeout
      end
      default: prot_state_d = P_IDLE;
    endcase
  end

  always_ff @(posedge core_clk_i or negedge core_rst_n_i) begin
    if (!core_rst_n_i) begin
      prot_state_q   <= P_IDLE;
      prot_timeout_q <= '0;
    end else begin
      prot_state_q <= prot_state_d;
      if (prot_state_d == P_ARMED && prot_state_q != P_ARMED)
        prot_timeout_q <= dfc_constants_pkg::DFC_PROTECT_TIMEOUT_CYCLES[31:0];
      else if (prot_state_q == P_ARMED && prot_timeout_q != 32'd0)
        prot_timeout_q <= prot_timeout_q - 32'd1;
    end
  end

  // ---- validation (ARCH-REG-001 order: alignment, decode, access class, ----
  // ---- write-strobe/full-word, protection) computed in S_IDLE for the ----
  // ---- incoming request ----
  logic [2:0] validate_code;
  always_comb begin
    if (dri_req_addr_i[1:0] != 2'b00)
      validate_code = RSP_ACCESS_ERROR;  // REG-GEN-001: 4-byte aligned;
                                          // REG-GEN-009 expects the SPI/DRI
                                          // bridge to reject unaligned before
                                          // DRI, but RTL-001 checks defensively
    else if (!regbank_decode_hit)
      validate_code = RSP_DECODE_ERROR;  // REG-GEN-009
    else if (dri_req_write_i && regbank_write_illegal)
      validate_code = RSP_ACCESS_ERROR;
    else if (dri_req_write_i && dri_req_wstrb_i != 4'b1111)
      validate_code = RSP_ACCESS_ERROR;  // REG-GEN-002: full-word writes only
    else if (dri_req_write_i && regbank_protected && !authorized)
      validate_code = RSP_PROTECTED_ERROR;
    else
      validate_code = RSP_OK;
  end

  // ---- FSM sequencing ----
  always_comb begin
    state_d = state_q;
    unique case (state_q)
      S_IDLE:    if (req_accept) state_d = S_RESPOND;
      S_RESPOND: if (dri_rsp_valid_o && dri_rsp_ready_i) state_d = S_IDLE;
      default:   state_d = S_IDLE;
    endcase
  end

  always_ff @(posedge core_clk_i or negedge core_rst_n_i) begin
    if (!core_rst_n_i) begin
      state_q     <= S_IDLE;
      req_addr_q  <= '0;
      req_wdata_q <= '0;
      req_write_q <= 1'b0;
      rsp_code_q  <= RSP_OK;
    end else begin
      state_q <= state_d;
      if (req_accept) begin
        req_addr_q  <= dri_req_addr_i;
        req_wdata_q <= dri_req_wdata_i;
        req_write_q <= dri_req_write_i;
        rsp_code_q  <= validate_code;
      end
    end
  end

  // ---- response + same-cycle write commit (ARCH-REG-002/RTLSTD-DRI-012) ----
  assign dri_rsp_valid_o  = (state_q == S_RESPOND);
  assign dri_rsp_code_o   = rsp_code_q;
  assign dbg_regbank_write_en_o = regbank_write_en;

  // RTL-001's own real status_o -- see the port's own header comment for
  // exactly what's real (ready) vs disclosed gap (fault, event_overflow,
  // event_drop_count). Packed MSB-first per dfc_rtl001_status_t's real
  // field order: event_drop_count[18:3], event_overflow[2], fault[1],
  // ready[0].
  assign status_o = {
    16'd0,   // event_drop_count -- disclosed gap, event generation not implemented
    1'b0,    // event_overflow -- disclosed gap
    1'b0,    // fault -- disclosed gap, CONFIG_ERROR_STATUS not implemented
    1'b1     // ready -- REAL: no complex startup, no module_reset_i, always ready once out of reset
  };
  assign dri_rsp_rdata_o  = req_write_q ? 32'h0 : regbank_rdata;
  assign regbank_write_en = (state_q == S_RESPOND) && req_write_q &&
                            (rsp_code_q == RSP_OK);

  // Module renamed to match its filename (dfc_config_regbank_regs.sv),
  // fixing a real, pre-existing RTLSTD-ORG-001 mismatch found this
  // session (reggen.py used to derive the module name from unrelated
  // slice metadata, independent of the actual output filename) -- see
  // reggen.py's own emit_regbank() comment for the full account.
  dfc_config_regbank_regs regbank (
    .clk_i           (core_clk_i),
    .rst_ni          (core_rst_n_i),
    .addr_i          (regbank_addr),
    .wdata_i         (req_wdata_q),
    .write_en_i      (regbank_write_en),
    .rdata_o         (regbank_rdata),
    .decode_hit_o    (regbank_decode_hit),
    .write_illegal_o (regbank_write_illegal),
    .protected_o     (regbank_protected),

