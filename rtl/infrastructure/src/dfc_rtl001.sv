  output logic [dfc_types_pkg::DFC_RTL005_CONTROL_WIDTH-1:0] rtl005_control_o,
  input  logic [dfc_types_pkg::DFC_RTL005_STATUS_WIDTH-1:0]  rtl005_status_i,

  // REAL cross-module register bus for RTL-006 (GPIO Controller) -- same
  // treatment as RTL-002/003/004/005 above, generated by reggen.py v4
  // from tools/reggen/rtl006_field_map.json. Replaces the individual
  // stub-tied gpio_raw_in_status_i/gpio_sync_in_status_i/
  // gpio_qual_in_status_i/gpio_event_status_status_i/
  // rtl006_evt_overflow_status_status_i/gpio_status_status_i ports this
  // module previously had.
  output logic [dfc_types_pkg::DFC_RTL006_CONTROL_WIDTH-1:0] rtl006_control_o,
  input  logic [dfc_types_pkg::DFC_RTL006_STATUS_WIDTH-1:0]  rtl006_status_i,

  // REAL cross-module register bus for RTL-007 (Rotor RPM Monitor) -- same
  // treatment as RTL-002/003/004/005/006 above, generated by reggen.py v4
  // from tools/reggen/rtl007_field_map.json. Replaces the individual
