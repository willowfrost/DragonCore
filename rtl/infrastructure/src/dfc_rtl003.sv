// dfc_rtl003.sv -- RTL-003 Interrupt Controller. Hand-authored (not
// generated); sole aggregator of the 32 fixed interrupt-source positions
// (24 assigned, 8 reserved, ARCH-002 Appendix C.4) into a single active-high
// aggregate-pending output. Implements ARCH-002 SS8.1's RAW/LATCH/PENDING/
// ACKED equations and RTL-003 spec SS3/SS4 (REG-002 0x0100-0x011C).
//
// Controlling documents: docs/rtl_specs/RTL-003_RevA.md, RCA-DFC-ARCH-002
// SS8.1/Appendix C.4/Appendix F.1 ARCH-RTL003-001/Appendix F.3, RCA-DFC-
// REG-002 0x0100-0x011C (+ 0x0610 TEST_IRQ_INJECT, owner "RTL-024 / RTL-003").
//
// RTLSTD-LANG-008 prohibits wildcard imports; every cross-package symbol
// below is fully qualified at its use site -- no import statement is
// emitted anywhere in this file.
//
// ============================================================================
// SPEC CONFLICT, RESOLVED IN FAVOR OF THE OWNING DOCUMENT (CHTR-DOC-003):
// RTL-003_RevA.md SS2 describes this module's own aggregate output as if it
// were literally named/owned as `host_irq_n_o`, "ultimately the host_irq_n_o
// external pad". ARCH-002's own formal port catalog (the actual owner of
// internal-interface facts, SS3.1) names RTL-003's real 16th port
// `aggregate_pending_o` (active-high level, producer RTL-003, consumer
// RTL-024.aggregate_pending_i) -- confirmed by cross-checking both the
// "RTL-003 -- Interrupt Controller (16 ports)" table AND the separate
// "RTL-024 -- Dragon Core Top-Level Integration" table, where `host_irq_n_o`
// is RTL-024's OWN external pad ("High in reset or with no enabled pending
// source"), fed by `aggregate_pending_i`, not a port RTL-003 itself owns.
// Per CHTR-DOC-003/CHTR-DOC-006, ARCH-002 (owns internal interfaces/module
// allocation) governs over RTL-003_RevA.md's restated claim (a derived
// artifact, not itself a source of new fact). This file therefore
// implements the ARCH-002-named port (`aggregate_pending_o`, active-high);
// `dfc_rtl024.sv` performs the final active-low inversion into the real
// `host_irq_n_o` pad. Logged in OPEN_ISSUES.md as a genuine module-spec vs.
// architecture inconsistency, not silently resolved without a paper trail.
// ============================================================================
//
// SCOPE OF THIS FIRST IMPLEMENTATION -- read before trusting this for
// anything beyond first HIL bring-up alongside RTL-001/RTL-002:
//
// IMPLEMENTED:
//   - RAW/LATCH/PENDING/ACKED equations exactly per ARCH-002 SS8.1 /
//     ARCH-RTL003-001, for all 24 assigned source bits: new RAW dominates a
//     simultaneous CLEAR; CLEAR dominates ACK for an inactive source
//     (ACKED[i]_next's `!(CLEAR[i] & !RAW[i])` term). Reserved bits 24-31
//     have RAW/LATCH/PENDING/ACKED permanently tied zero.
//   - VECTOR_VALID/VECTOR_SOURCE (lowest-numbered set PENDING bit, priority
//     0 upward) and the aggregate active-high pending output, gated by
//     `global_irq_enable_i` (RTL-002.global_irq_enable_o).
//   - IRQ_ENABLE/IRQ_RAW_STATUS/IRQ_PENDING/IRQ_ACK/IRQ_ACKED/IRQ_CLEAR/
//     IRQ_VECTOR/RTL003_EVT_OVERFLOW_STATUS real cross-module forwarding via
//     `control_i`/`status_o`, generated by reggen.py v4 from
//     tools/reggen/rtl003_field_map.json.
//   - TEST_IRQ_INJECT (REG-0610, protected, owner "RTL-024 / RTL-003"):
//     `injected_i[23:0]` sourced directly from `control_i`'s one-cycle
//     `test_irq_inject__source_mask` pulse, ORed into RAW per SS3 -- "the
//     production-test injection path... bounded, never a functional
//     source."
//   - Illegal reserved-source-bit-activity detection (Appendix F.3 RTL-003
//     condition-mask bit 0): any of IRQ_ENABLE/IRQ_ACK/IRQ_CLEAR/
//     TEST_IRQ_INJECT's reserved bits 31:24 nonzero on `control_i` sets a
//     sticky fault (this module's only fault source, per spec SS3 "fault is
//     reserved/internal illegal-state evidence only") and, gated by
//     `event_condition_enable_i[0]`, schedules this module's own diagnostic
//     event 0x0008 (source index 2, ARCH-002 Appendix C.5) via a real
//     one-deep pending-record slot -- same shape as dfc_rtl002.sv's already-
//     verified event mechanism (real counted overflow: event_overflow/
//     event_drop_count, not hardcoded).
//   - Ready is unconditional 1'b1 once released from reset/module_reset --
//     RTL-003 spec SS3: "Ready is high after vector initialization"; this
//     module has no multi-cycle startup sequence, so vector-initialization
//     and reset release are the same instant.
//
// NOT YET IMPLEMENTED / DISCLOSED INTERPRETATIONS -- real, disclosed gaps,
// not silent no-ops:
//   - `irq_condition_enable_i` (a real port per the Architecture catalog) is
//     intentionally unused: RTL-003 spec SS3/Appendix F.3 both state "RTL-003
//     generates no self-interrupt" -- there is no ordinary per-condition IRQ
//     request of RTL-003's own to gate with it (RTL-003 IS the interrupt
//     aggregator; its "output" is the aggregate itself, computed directly
//     from the LATCH/ENABLE equations, not from this mask). Tied off in the
//     module's own unused-signal sink below, not silently dropped.
//   - Per ARCH-EVT-002 ("RTL-005 first services pending event-store overflow
//     0x007F, then source overflow 0x007E..."), this implementation reads
//     0x007E as RTL-005's OWN synthesized event (built from every producer's
//     status_o.event_overflow/EVT_DROP_SOURCE bit, once RTL-005 is real) --
//     NOT a record RTL-003 emits itself through its own single one-deep
//     slot (which would be self-contradictory: the slot that is overflowing
//     cannot simultaneously accept a new record announcing that fact). This
//     matches dfc_rtl002.sv's identical, already-verified precedent (RTL-002
//     also never self-emits 0x007E): this module tracks event_overflow/
//     event_drop_count as real, counted STATUS evidence only. If this
//     reading is wrong, only RTL-005 (not yet real) and this file's overflow
//     bookkeeping need revisiting -- not the whole event architecture.
//   - "Illegal reserved-source activity" is edge-qualified for the 0x0008
//     EVENT record (rising edge of the condition only), not level-repeated
//     every cycle the condition persists -- IRQ_ENABLE's reserved bits, once
//     set, are a continuously-HELD register value (not a pulse), and RTL-001
//     does not yet implement per-field reserved-bit write masking (a
//     separate, already-disclosed project-wide gap -- see dfc_rtl001.sv's
//     own header), so a level-triggered event would otherwise re-fire every
//     single cycle for as long as the illegal value remains stored. The
//     STICKY FAULT bit itself is level-based (asserts and remains asserted
//     while the condition is live, consistent with "fault... internal
//     illegal-state evidence"), only the discrete EVENT record is edge-
//     qualified. This is a disclosed engineering interpretation, not a
//     cited spec fact -- log as an open item if a bit-exact alternative is
//     later specified.
//   - IRQ_CLEAR (REG-0114)'s "reads current retained value" (REG-GEN-013)
//     is implemented as a direct echo of `control_i`'s own one-cycle
//     `irq_clear__clear` pulse into `status_o.irq_clear__clear` -- i.e. a
//     host read shortly after an accepted CLEAR write can observe which
//     mask was just applied, decaying to zero the following cycle. This is
//     a disclosed interpretation: REG-002/ARCH-002 define a status-struct
//     member distinct from `irq_raw_status__raw_status` for this field (so
//     it cannot simply mirror the LATCH readback) but do not spell out its
//     exact retained-value semantics beyond REG-GEN-013's generic W1C text.
//   - RTL-001's own per-field reserved-bit/legal-range write validation
//     (REG-ENC-001 through 019) does not exist yet (already disclosed in
//     dfc_rtl001.sv) -- a write setting IRQ_ENABLE/IRQ_ACK/IRQ_CLEAR/
//     TEST_IRQ_INJECT bits 24-31 is accepted by RTL-001's DRI path rather
//     than rejected before ever reaching `control_i`. This module defends
//     itself (reserved state is always tied zero, illegal activity is
//     detected and faulted/eventable as above) but the real, spec-correct
//     fix belongs in RTL-001, not here -- logged in OPEN_ISSUES.md.
//   - Per ARCH-002 Appendix C.4, only source bits 0-23 have real producers;
//     until RTL-004 through RTL-023 exist, `irq_source_i[23:1]` (all but
//     bit 0, RTL-002.irq_req_o) are driven by disclosed stub tie-offs in
//     `dfc_rtl024.sv`, per RTL-003_RevA.md SS6's own disclosed dependency
//     gap. This file itself is producer-agnostic and requires no change as
//     each real producer comes online.
//
// Log anything this reveals as a genuine spec gap -- not a coding mistake
// -- in OPEN_ISSUES.md per CLAUDE.md's working rules.
// ============================================================================

module dfc_rtl003 (
  input  logic core_clk_i,
  input  logic core_rst_n_i,
  input  logic module_reset_i,             // RTL-002.module_reset_o[2]

  // TOOLCHAIN-DRIVEN DEVIATION (confirmed real on the person's production
  // Yosys build, see dfc_rtl002.sv's header for the full account): a
  // package-scoped type cannot be a port's declared type on this exact
  // toolchain. Every such port here is a plain `logic [W-1:0]` vector sized
  // via generated `dfc_types_pkg::DFC_*_WIDTH` VALUE constants instead.
  input  logic [dfc_types_pkg::DFC_RTL003_CONTROL_WIDTH-1:0] control_i,
  output logic [dfc_types_pkg::DFC_RTL003_STATUS_WIDTH-1:0]  status_o,

  input  logic [63:0] timestamp_i,
  output logic         evt_valid_o,
  input  logic         evt_ready_i,
  output logic [dfc_types_pkg::DFC_EVENT_RECORD_WIDTH-1:0] evt_record_o,

  input  logic [31:0] irq_source_i,        // Appendix C.4: bits 0-23 real
                                            // producers, bits 31:24 constant
                                            // zero (reserved)
  output logic         aggregate_pending_o, // see header SPEC CONFLICT note --
                                            // ARCH-002's real port name, not
                                            // `host_irq_n_o`

  input  logic [dfc_types_pkg::DFC_OPERATING_STATE_WIDTH-1:0] operating_state_i,
  input  logic         observational_mode_i,
  input  logic         global_irq_enable_i, // RTL-002.global_irq_enable_o

  input  logic [63:0] event_condition_enable_i,  // Appendix F.3: bit 0 used
                                                   // (illegal reserved-source
                                                   // activity); bit 1
                                                   // (event-slot overflow)
                                                   // intentionally unused --
                                                   // see header note
  input  logic [63:0] irq_condition_enable_i      // real port, intentionally
                                                   // unused -- see header note
                                                   // ("no self-interrupt")
);

  // ---- control_i field extraction (bit-slice wires, generated _HI/_LO
  // constants -- same confirmed-safe pattern as dfc_rtl002.sv) ----
  wire [31:0] ctl_irq_enable =
    control_i[dfc_types_pkg::DFC_RTL003_CONTROL__IRQ_ENABLE__ENABLE_HI:dfc_types_pkg::DFC_RTL003_CONTROL__IRQ_ENABLE__ENABLE_LO];
  wire [31:0] ctl_irq_ack_pulse =
    control_i[dfc_types_pkg::DFC_RTL003_CONTROL__IRQ_ACK__ACK_SET_HI:dfc_types_pkg::DFC_RTL003_CONTROL__IRQ_ACK__ACK_SET_LO];
  wire [31:0] ctl_irq_clear_pulse =
    control_i[dfc_types_pkg::DFC_RTL003_CONTROL__IRQ_CLEAR__CLEAR_HI:dfc_types_pkg::DFC_RTL003_CONTROL__IRQ_CLEAR__CLEAR_LO];
  wire [31:0] ctl_test_inject_pulse =
    control_i[dfc_types_pkg::DFC_RTL003_CONTROL__TEST_IRQ_INJECT__SOURCE_MASK_HI:dfc_types_pkg::DFC_RTL003_CONTROL__TEST_IRQ_INJECT__SOURCE_MASK_LO];

  // ---- reserved-bit (24-31) defensive masking -- SS3: "Reserved bits 24
  // through 31 have RAW, LATCH, PENDING, and ACKED tied zero; writes
  // selecting them are rejected." RTL-001 does not yet enforce the
  // "rejected" half (disclosed gap above); this module enforces the "tied
  // zero" half unconditionally regardless of what arrives on control_i. ----
  wire [23:0] enable_masked       = ctl_irq_enable[23:0];
  wire [23:0] ack_pulse_masked    = ctl_irq_ack_pulse[23:0];
  wire [23:0] clear_pulse_masked  = ctl_irq_clear_pulse[23:0];
  wire [23:0] inject_pulse_masked = ctl_test_inject_pulse[23:0];

  wire illegal_reserved_activity =
    (|ctl_irq_enable[31:24])       || (|ctl_irq_ack_pulse[31:24]) ||
    (|ctl_irq_clear_pulse[31:24])  || (|ctl_test_inject_pulse[31:24]);

  // ==========================================================================
  // Core equations (ARCH-002 SS8.1 / ARCH-RTL003-001), sources 0-23 only.
  // ==========================================================================
  logic [23:0] latch_q;
  logic [23:0] acked_q;

  wire [23:0] raw          = irq_source_i[23:0] | inject_pulse_masked;
  wire [23:0] latch_next   = raw | (latch_q & ~clear_pulse_masked);
  wire [23:0] pending      = enable_masked & latch_q;
  wire [23:0] acked_next   = (acked_q | ack_pulse_masked) & ~(clear_pulse_masked & ~raw);

  wire vector_valid = |pending;

  // Lowest-numbered set PENDING bit -- priority order bit 0 upward, per
  // SS3/REG-0118 ("SOURCE... 0-23 when VALID=1; 0 when VALID=0").
  logic [4:0] vector_source;
  always_comb begin
    vector_source = 5'd0;
    if      (pending[0])  vector_source = 5'd0;
    else if (pending[1])  vector_source = 5'd1;
    else if (pending[2])  vector_source = 5'd2;
    else if (pending[3])  vector_source = 5'd3;
    else if (pending[4])  vector_source = 5'd4;
    else if (pending[5])  vector_source = 5'd5;
    else if (pending[6])  vector_source = 5'd6;
    else if (pending[7])  vector_source = 5'd7;
    else if (pending[8])  vector_source = 5'd8;
    else if (pending[9])  vector_source = 5'd9;
    else if (pending[10]) vector_source = 5'd10;
    else if (pending[11]) vector_source = 5'd11;
    else if (pending[12]) vector_source = 5'd12;
    else if (pending[13]) vector_source = 5'd13;
    else if (pending[14]) vector_source = 5'd14;
    else if (pending[15]) vector_source = 5'd15;
    else if (pending[16]) vector_source = 5'd16;
    else if (pending[17]) vector_source = 5'd17;
    else if (pending[18]) vector_source = 5'd18;
    else if (pending[19]) vector_source = 5'd19;
    else if (pending[20]) vector_source = 5'd20;
    else if (pending[21]) vector_source = 5'd21;
    else if (pending[22]) vector_source = 5'd22;
    else if (pending[23]) vector_source = 5'd23;
  end

  // SS3: `host_irq_n = !(GLOBAL_IRQ_ENABLE & VECTOR_VALID)` -- expressed
  // here in the active-high sense per ARCH-002's real port contract
  // ("active-high level"); dfc_rtl024.sv performs the final inversion onto
  // the real active-low external pad (see header SPEC CONFLICT note).
  assign aggregate_pending_o = global_irq_enable_i & vector_valid;

  // ==========================================================================
  // Sequential state
  // ==========================================================================
  logic fault_q;
  logic illegal_reserved_activity_prev_q;

  always_ff @(posedge core_clk_i or negedge core_rst_n_i) begin
    if (!core_rst_n_i) begin
      latch_q                          <= 24'h0;
      acked_q                          <= 24'h0;
      fault_q                          <= 1'b0;
      illegal_reserved_activity_prev_q <= 1'b0;
    end else if (module_reset_i) begin
      latch_q                          <= 24'h0;
      acked_q                          <= 24'h0;
      fault_q                          <= 1'b0;
      illegal_reserved_activity_prev_q <= 1'b0;
    end else begin
      latch_q <= latch_next;
      acked_q <= acked_next;
      if (illegal_reserved_activity) fault_q <= 1'b1;  // sticky -- see header
      illegal_reserved_activity_prev_q <= illegal_reserved_activity;
    end
  end

  // ==========================================================================
  // Event generation (RTL-003 is event source index 2, event ID 0x0008;
  // ARCH-002 Appendix C.5) -- real implementation, same one-deep pending-
  // record shape already proven in dfc_rtl002.sv. See header note for why
  // this module never self-emits 0x007E.
  // ==========================================================================
  localparam logic [15:0] EVT_ID_ILLEGAL_RESERVED_SOURCE = 16'h0008;
  localparam logic [7:0]  EVT_SOURCE_INDEX_RTL003 = 8'd2;  // ARCH-002 C.5 index 2

  wire illegal_reserved_activity_rising =
    illegal_reserved_activity && !illegal_reserved_activity_prev_q;
  wire evt_candidate_valid = illegal_reserved_activity_rising && event_condition_enable_i[0];

  logic [dfc_types_pkg::DFC_EVENT_RECORD_WIDTH-1:0] evt_candidate;
  always_comb begin
    evt_candidate = '0;
    evt_candidate[dfc_types_pkg::DFC_EVENT_RECORD__TIMESTAMP_HI:dfc_types_pkg::DFC_EVENT_RECORD__TIMESTAMP_LO] = timestamp_i;
    evt_candidate[dfc_types_pkg::DFC_EVENT_RECORD__SOURCE_ID_HI:dfc_types_pkg::DFC_EVENT_RECORD__SOURCE_ID_LO] = EVT_SOURCE_INDEX_RTL003;
    evt_candidate[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_ID_HI:dfc_types_pkg::DFC_EVENT_RECORD__EVENT_ID_LO] = EVT_ID_ILLEGAL_RESERVED_SOURCE;
    // Detail: which of the four reserved-bit fields carried the illegal
    // activity this cycle, one flag bit each -- a disclosed, locally-chosen
    // encoding (REG-002/ARCH-002 do not give this event's detail-field
    // bit-exact layout), same basis as dfc_rtl002.sv's own disclosed detail
    // packing.
    evt_candidate[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO +: 4] = {
      (|ctl_test_inject_pulse[31:24]), (|ctl_irq_clear_pulse[31:24]),
      (|ctl_irq_ack_pulse[31:24]),     (|ctl_irq_enable[31:24])
    };
  end

  logic                                              evt_pending_q;
  logic [dfc_types_pkg::DFC_EVENT_RECORD_WIDTH-1:0]  evt_record_q;
  logic                                              event_overflow_q;
  logic [15:0]                                       event_drop_count_q;

  always_ff @(posedge core_clk_i or negedge core_rst_n_i) begin
    if (!core_rst_n_i) begin
      evt_pending_q      <= 1'b0;
      evt_record_q       <= '0;
      event_overflow_q   <= 1'b0;
      event_drop_count_q <= 16'd0;
    end else if (module_reset_i) begin
      evt_pending_q      <= 1'b0;
      evt_record_q       <= '0;
      event_overflow_q   <= 1'b0;
      event_drop_count_q <= 16'd0;
    end else begin
      if (evt_pending_q && evt_ready_i) evt_pending_q <= 1'b0;  // handshake clears record

      if (evt_candidate_valid) begin
        if (!evt_pending_q || (evt_pending_q && evt_ready_i)) begin
          evt_pending_q <= 1'b1;
          evt_record_q  <= evt_candidate;
        end else begin
          // slot still occupied -- a real, counted overflow (see header:
          // this module's own status evidence only, no self-emitted 0x007E).
          if (event_drop_count_q != 16'hFFFF) event_drop_count_q <= event_drop_count_q + 16'd1;
          event_overflow_q <= 1'b1;
        end
      end
    end
  end

  assign evt_valid_o  = evt_pending_q;
  assign evt_record_o = evt_record_q;

  // ==========================================================================
  // status_o packing (dfc_rtl003_status_t, 153 bits, ARCH-002 Appendix B).
  // status_comb is a plain flat vector, not the package struct type -- same
  // reasoning as dfc_rtl002.sv's status_comb (declared-type toolchain
  // limitation). Each field written via its exact bit index/range, sliced
  // using generated `dfc_types_pkg::DFC_RTL003_STATUS__<FIELD>_HI`/`_LO`
  // constants.
  // ==========================================================================
  logic [dfc_types_pkg::DFC_RTL003_STATUS_WIDTH-1:0] status_comb;

  always_comb begin
    status_comb = '0;

    status_comb[dfc_types_pkg::DFC_RTL003_STATUS__READY_HI] = 1'b1;  // SS3: ready
                                                                       // high after
                                                                       // vector init
                                                                       // (trivial here)
    status_comb[dfc_types_pkg::DFC_RTL003_STATUS__FAULT_HI] = fault_q;
    status_comb[dfc_types_pkg::DFC_RTL003_STATUS__EVENT_OVERFLOW_HI] = event_overflow_q;

    status_comb[dfc_types_pkg::DFC_RTL003_STATUS__IRQ_RAW_STATUS__RAW_STATUS_HI:dfc_types_pkg::DFC_RTL003_STATUS__IRQ_RAW_STATUS__RAW_STATUS_LO]
      = {8'h0, latch_q};
    status_comb[dfc_types_pkg::DFC_RTL003_STATUS__IRQ_PENDING__PENDING_HI:dfc_types_pkg::DFC_RTL003_STATUS__IRQ_PENDING__PENDING_LO]
      = {8'h0, pending};
    status_comb[dfc_types_pkg::DFC_RTL003_STATUS__IRQ_ACKED__ACKED_HI:dfc_types_pkg::DFC_RTL003_STATUS__IRQ_ACKED__ACKED_LO]
      = {8'h0, acked_q};
    // IRQ_CLEAR readback -- see header disclosed-interpretation note: a
    // direct echo of the one-cycle accepted CLEAR pulse, not the LATCH
    // state (which IRQ_RAW_STATUS already exposes separately).
    status_comb[dfc_types_pkg::DFC_RTL003_STATUS__IRQ_CLEAR__CLEAR_HI:dfc_types_pkg::DFC_RTL003_STATUS__IRQ_CLEAR__CLEAR_LO]
      = {8'h0, clear_pulse_masked};
    status_comb[dfc_types_pkg::DFC_RTL003_STATUS__IRQ_VECTOR__SOURCE_HI:dfc_types_pkg::DFC_RTL003_STATUS__IRQ_VECTOR__SOURCE_LO]
      = vector_source;
    status_comb[dfc_types_pkg::DFC_RTL003_STATUS__IRQ_VECTOR__VALID_HI] = vector_valid;

    status_comb[dfc_types_pkg::DFC_RTL003_STATUS__EVENT_DROP_COUNT_HI:dfc_types_pkg::DFC_RTL003_STATUS__EVENT_DROP_COUNT_LO]
      = event_drop_count_q;
  end

  assign status_o = status_comb;

  // ---- unused-port sink (RTLSTD-MOD-009): operating_state_i/
  // observational_mode_i/irq_condition_enable_i/event_condition_enable_i[63:1]
  // are real ports per the Architecture catalog with no functional
  // consumer in this first implementation (RTL-003 has no state-dependent
  // behavior, no self-interrupt, and no ordinary-event condition beyond
  // bit 0 -- see header notes). Intentionally consumed here, not silently
  // dropped. ----
  logic unused_stub_sink;
  assign unused_stub_sink = (^operating_state_i) ^ observational_mode_i ^
                            (|irq_condition_enable_i) ^ (|event_condition_enable_i[63:1]);

endmodule : dfc_rtl003
