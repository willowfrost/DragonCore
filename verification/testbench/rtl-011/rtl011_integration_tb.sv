// rtl011_integration_tb.sv -- REAL end-to-end round-trip test: real host
// writes through RTL-001's real address-decode path must actually change
// RTL-011's real behavior across all 8 channels, and real simulated
// external transitions on health_i must produce correct real synchronized/
// qualified/sticky-latched results read back through the real register
// bus -- same template and purpose as rtl002 through rtl010_integration_
// tb.sv, targeting the RTL-001<->RTL-011 register bus specifically
// (HEALTH_CONTROL/HEALTH_POLARITY/HEALTH_FAULT_ENABLE/HEALTH_EVENT_ENABLE/
// HEALTH_IRQ_ENABLE/HEALTH_QUAL_0_3/_4_7/HEALTH_STICKY/RTL011_EVT_OVERFLOW_
// STATUS control forwarding; HEALTH_RAW_IN/HEALTH_SYNC_IN/HEALTH_QUAL_IN/
// HEALTH_ACTIVE/HEALTH_STICKY/RTL011_EVT_OVERFLOW_STATUS/HEALTH_
// QUALIFICATION/HEALTH_STATUS status forwarding), generated by reggen.py
// v4 + tools/reggen/rtl011_field_map.json.
//
// ADDITIONALLY (per this module's own real, distinguishing requirements):
//   - Part 3 exercises the qualification stability timer exactly like
//     RTL-006's own precedent: a genuinely-too-short transition (held well
//     under one full ms sample) is correctly rejected (no commit), and a
//     genuinely-qualifying transition (held a full simulated multi-ms
//     window) is correctly accepted.
//   - Part 4 is RTL-011_RevA.md SS5's own explicitly named dedicated case:
//     force active -> sticky (asserted) sets -> force inactive -> confirm
//     recovered pulses (HEALTH_STICKY.RECOVERED sets) AND
//     HEALTH_STICKY.ASSERTED remains set until an explicit host clear --
//     the "recovery does not clear sticky" contract, the exact detail the
//     spec itself warns is easy to implement wrong. The "pulses exactly
//     once, not a level" claim is confirmed indirectly but rigorously: the
//     RECOVERED bit is cleared via a real host W1C write while health_i
//     stays continuously inactive, and is then confirmed to STAY clear --
//     a level-driven (rather than edge-pulsed) implementation would
//     immediately re-assert it the very next cycle.
//   - Part 5 is polarity (ACTIVE_HIGH=0): confirms `active = qualified XOR
//     !ACTIVE_HIGH` inverts correctly, not just passes through.
//   - Part 6 is the aggregate fault equation (ARCH-RTL011-001): a channel
//     with FAULT_ENABLE clear can be active/sticky without contributing to
//     HEALTH_STATUS.AGGREGATE_FAULT/fault_req_o; a channel with
//     FAULT_ENABLE set does contribute, and the aggregate is live (not
//     sticky) -- it clears the instant the contributing channel goes
//     inactive again.
//   - Part 7 is real event/irq generation (event ID 0x0034, source index
//     10): a real asserted-transition and a real recovery-transition each
//     produce a real, bit-exact event record (subtype/channel index/
//     active+sticky detail-field packing, per this module's own disclosed
//     C.7 interpretation), and irq_req_o genuinely asserts.
//   - Part 8 is the tenth real instance of this project's own
//     EVENT_OVERFLOW-clear-field gap class, proven exactly like items 2/7/
//     8/12/20/24/28/32/36 before it: a genuine, forced overflow (handshake
//     withheld) sets event_overflow_q, and a real host CLEAR write through
//     RTL-001's real DRI path genuinely clears it.
//   - Part 9 is illegal-configuration/ready/fault (this module's own
//     generic module_status bits, ARCH-VAL-011's "qualification is
//     0-100 ms" range): a qualification time of 150 ms on one channel
//     alone faults the whole module (status_o.ready low, status_o.fault
//     high) even while every other channel remains legally configured --
//     and fixing it clears the fault. Deliberately distinct from Part 6's
//     own HEALTH_STATUS.AGGREGATE_FAULT/fault_req_o, per dfc_rtl011.sv's
//     own header note on why these are two independent signals.
//
// NOT EXERCISED, disclosed rather than silently skipped -- see
// dfc_rtl011.sv's own header for the full derivation: a genuine, externally
// triggered HEALTH_STICKY.QUALIFICATION_FAILURE assertion is mathematically
// unreachable for this module's real 1-bit-per-channel input via any drive
// pattern (a continuously-disagreeing 1-bit channel always commits at or
// before its own attempt window closes, for every legal Q). The mechanism
// itself (both counters, the clear-request field, the F.3 gating, and the
// HEALTH_QUALIFICATION.IN_PROGRESS live readback) is still real and
// provably correct by construction -- just not something this testbench
// can force to actually fire, same class of disclosed reachability gap as
// RTL-010's own untestable routed-commit half of VP-MON-007 (item 38).
//
// RTL-002 through RTL-010 are out of this test's scope (same isolation
// choice every prior module-specific integration testbench already makes
// for sibling modules not under test): `module_enable_i` is driven directly
// by this testbench as a plain constant, and `timestamp_i` is a
// free-running testbench counter, not RTL-004's real broadcast.
//
// CLOCKING-DISCIPLINE NOTE (same lesson as every other testbench in this
// project): every strobe is held for a full clock and deasserted with a
// #1 settle delay after the sampling edge, never in the same delta.

