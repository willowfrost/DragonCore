  int errors = 0, checks = 0;
  task automatic check(string what, logic [31:0] got, logic [31:0] expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got 0x%08h, expected 0x%08h", what, got, expected);
    end else $display("PASS: %s -- 0x%08h", what, got);
  endtask
  task automatic check_bit(string what, logic got, logic expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got %b, expected %b", what, got, expected);
    end else $display("PASS: %s", what);
  endtask

  task automatic dri_write(input logic [31:0] addr, input logic [31:0] data,
                            output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_wdata_i = data;
    dri_req_wstrb_i = 4'hF;
    dri_req_write_i = 1'b1;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    code = dri_rsp_code_o;
  endtask

  task automatic dri_read(input logic [31:0] addr, output logic [31:0] data,
                           output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_write_i = 1'b0;
    dri_req_wstrb_i = 4'h0;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    data = dri_rsp_rdata_o;
    code = dri_rsp_code_o;
  endtask

  // MS_TICK_CYCLES = 50,000 (nominal 50 MHz CORE_CLK, dfc_rtl011.sv's own
  // disclosed assumption). wait_cycles(N) is a plain clock-cycle wait, used
  // to build ms-scale waits relative to that constant.
  task automatic wait_cycles(input int n);
    repeat (n) @(posedge core_clk_i);
  endtask

  logic [2:0]  code;
  logic [31:0] rdata;

  initial begin
    core_rst_n_i = 0;
    repeat (4) @(posedge core_clk_i);
    core_rst_n_i = 1;
    repeat (2) @(posedge core_clk_i);

    // ==========================================================================
    // Part 1: HEALTH_CONTROL/HEALTH_POLARITY/HEALTH_FAULT_ENABLE/
    // HEALTH_EVENT_ENABLE/HEALTH_IRQ_ENABLE/HEALTH_QUAL_0_3/_4_7
    // configuration writes reach RTL-011's real control_i (bit-exact real
    // register bus, not a fabricated white-box force).
    // ==========================================================================
    dri_write(DFC_ADDR_HEALTH_CONTROL, 32'h1, code);  // ENABLE
    check("HEALTH_CONTROL write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_HEALTH_CONTROL, rdata, code);
    check("HEALTH_CONTROL reads back real value just written", rdata, 32'h1);

    dri_write(DFC_ADDR_HEALTH_QUAL_0_3, {8'd0, 8'd0, 8'd0, 8'd2}, code);  // ch0=2ms, ch1-3=0
    check("HEALTH_QUAL_0_3 write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_HEALTH_QUAL_0_3, rdata, code);
    check("HEALTH_QUAL_0_3 reads back real value just written", rdata, {8'd0,8'd0,8'd0,8'd2});

    dri_write(DFC_ADDR_HEALTH_QUAL_4_7, 32'h0, code);  // ch4-7=0ms (pass-through)
    dri_write(DFC_ADDR_HEALTH_POLARITY, 32'hFF & ~(8'h02), code);  // channel 1 active-low, rest active-high
    check("HEALTH_POLARITY write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_HEALTH_POLARITY, rdata, code);
    check("HEALTH_POLARITY reads back real value just written", rdata, 32'hFD);

    // HEALTH_FAULT_ENABLE is REG-002-protected ("Protection: Yes") -- the
    // real two-key PROTECT_KEY sequence must arm it first, same discipline
    // as every other protected register write in this project
    // (rtl024_skeleton_tb.sv's own SUBSYS_ENABLE/GPIO_DIR writes).
    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY1, code);
    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY2, code);
    dri_write(DFC_ADDR_HEALTH_FAULT_ENABLE, 32'h10, code);   // channel 4 only
    check("HEALTH_FAULT_ENABLE protected write with valid auth -> OK", {29'h0,code}, 32'h0);
    dri_write(DFC_ADDR_HEALTH_EVENT_ENABLE, 32'hFF, code);
    dri_write(DFC_ADDR_HEALTH_IRQ_ENABLE,   32'hFF, code);
    check("HEALTH_IRQ_ENABLE write accepted (RSP_OK)", {29'h0,code}, 32'h0);

    // HEALTH_POLARITY's own write above changes several channels' ACTIVE_HIGH
    // bit away from its reset-default (0, active-low) -- since qual_value_q
    // itself is still 0 (health_i untouched so far) at this point, that
    // default-active-low polarity genuinely reads as ACTIVE for every
    // channel whose polarity isn't being changed to active-high yet, and
    // the write itself then genuinely flips several channels inactive
    // (a real active-to-inactive transition, correctly setting their real
    // sticky ASSERTED/RECOVERED evidence per ARCH-MON-008 -- this is not a
    // bug, reconfiguration-caused transitions are still real transitions).
    // Clear that real, but incidental, Part-1-induced sticky evidence here
    // so every later part starts from a clean, known baseline.
    dri_write(DFC_ADDR_HEALTH_STICKY, 32'h00FF_FFFF, code);

    // ==========================================================================
    // Part 2: real simulated external transitions genuinely reach
    // HEALTH_RAW_IN/HEALTH_SYNC_IN through the real two-flop synchronizer,
    // independently per channel.
    // ==========================================================================
    tb_health_i = 8'b0000_0000;
    wait_cycles(5);
    dri_read(DFC_ADDR_HEALTH_RAW_IN, rdata, code);
    check("HEALTH_RAW_IN starts at 0", rdata, 32'h0);

    tb_health_i = 8'b1010_1010;
    wait_cycles(3);  // real pad -> raw_in_q registration
    dri_read(DFC_ADDR_HEALTH_RAW_IN, rdata, code);
    check("HEALTH_RAW_IN genuinely tracks the real external pin pattern", rdata, 32'hAA);
    wait_cycles(3);  // real two-flop synchronizer settle
    dri_read(DFC_ADDR_HEALTH_SYNC_IN, rdata, code);
    check("HEALTH_SYNC_IN genuinely reflects the same pattern after real synchronization", rdata, 32'hAA);

    tb_health_i = 8'h00;
    wait_cycles(5);

    // ==========================================================================
    // Part 3: qualification stability timer (ARCH-MON-008) -- channel 0,
    // Q=2 ms. A genuinely-too-short transition is correctly rejected; a
    // genuinely-qualifying transition is correctly accepted, matching
    // RTL-006's own precedent test discipline.
    // ==========================================================================
    tb_health_i[0] = 1'b1;
    wait_cycles(25_000);              // well under one full 50,000-cycle ms sample
    tb_health_i[0] = 1'b0;
    wait_cycles(5);
    dri_read(DFC_ADDR_HEALTH_QUAL_IN, rdata, code);
    check_bit("channel 0: too-short transition correctly REJECTED (no commit)", rdata[0], 1'b0);

    tb_health_i[0] = 1'b1;
    wait_cycles(2 * 50_000 + 5_000);  // comfortably more than 2 full ms samples
    dri_read(DFC_ADDR_HEALTH_QUAL_IN, rdata, code);
    check_bit("channel 0: genuinely-qualifying transition correctly ACCEPTED (commits)", rdata[0], 1'b1);
    dri_read(DFC_ADDR_HEALTH_ACTIVE, rdata, code);
    check_bit("channel 0: active follows the real qualified commit (ACTIVE_HIGH=1)", rdata[0], 1'b1);

    tb_health_i[0] = 1'b0;
    wait_cycles(2 * 50_000 + 5_000);  // let it qualify back down too, for later parts

    // ==========================================================================
    // Part 4: RTL-011_RevA.md SS5's own dedicated case -- force active,
    // confirm sticky (asserted) sets, force inactive, confirm recovered
    // pulses AND sticky (asserted) remains set until an explicit clear.
    // Channel 2, Q=0 (pass-through), ACTIVE_HIGH=1.
    // ==========================================================================
    tb_health_i[2] = 1'b1;
    wait_cycles(5);
    dri_read(DFC_ADDR_HEALTH_ACTIVE, rdata, code);
    check_bit("channel 2 genuinely active (Q=0 pass-through)", rdata[2], 1'b1);
    dri_read(DFC_ADDR_HEALTH_STICKY, rdata, code);
    check_bit("channel 2 sticky ASSERTED genuinely sets on real active", rdata[0+2], 1'b1);
    check_bit("channel 2 sticky RECOVERED not yet set (still active)", rdata[8+2], 1'b0);

    tb_health_i[2] = 1'b0;
    wait_cycles(5);
    dri_read(DFC_ADDR_HEALTH_ACTIVE, rdata, code);
    check_bit("channel 2 genuinely inactive now", rdata[2], 1'b0);
    dri_read(DFC_ADDR_HEALTH_STICKY, rdata, code);
    check_bit("channel 2 sticky RECOVERED genuinely sets on the active-to-inactive transition", rdata[8+2], 1'b1);
    check_bit("channel 2 sticky ASSERTED REMAINS SET -- recovery does not clear it", rdata[0+2], 1'b1);

    // Clear RECOVERED via a real host W1C write while health_i[2] stays
    // continuously inactive -- confirms the bit is genuinely pulse-driven,
    // not level-driven (a level-driven bug would immediately re-set it).
    dri_write(DFC_ADDR_HEALTH_STICKY, 32'h0000_0400, code);  // clear RECOVERED[2] only (bit 10)
    dri_read(DFC_ADDR_HEALTH_STICKY, rdata, code);
    check_bit("channel 2 sticky RECOVERED genuinely clears via the real host write", rdata[8+2], 1'b0);
    wait_cycles(20);
    dri_read(DFC_ADDR_HEALTH_STICKY, rdata, code);
    check_bit("channel 2 sticky RECOVERED stays clear -- confirms it was a real pulse, not a level", rdata[8+2], 1'b0);
    check_bit("channel 2 sticky ASSERTED still set (untouched by the RECOVERED-only clear)", rdata[0+2], 1'b1);

    // Now clear ASSERTED for real too (new active dominates clear: this
    // only succeeds because health_i[2] is genuinely inactive right now).
    dri_write(DFC_ADDR_HEALTH_STICKY, 32'h0000_0004, code);  // clear ASSERTED[2] only (bit 2)
    dri_read(DFC_ADDR_HEALTH_STICKY, rdata, code);
    check_bit("channel 2 sticky ASSERTED genuinely clears via the real host write", rdata[0+2], 1'b0);

    // New active dominates a simultaneous clear (ARCH-RTL011-001): force
    // active back on the SAME cycle a clear request would otherwise apply.
    tb_health_i[2] = 1'b1;
    dri_write(DFC_ADDR_HEALTH_STICKY, 32'h0000_0004, code);  // clear ASSERTED[2] again, but now active
    dri_read(DFC_ADDR_HEALTH_STICKY, rdata, code);
    check_bit("new active dominates a simultaneous clear -- ASSERTED stays set", rdata[0+2], 1'b1);
    tb_health_i[2] = 1'b0;
    wait_cycles(5);
    dri_write(DFC_ADDR_HEALTH_STICKY, 32'h0000_0404, code);  // clear both, now safely inactive
    wait_cycles(5);

    // ==========================================================================
    // Part 5: polarity (ACTIVE_HIGH=0, channel 1) -- active = qualified XOR
    // !ACTIVE_HIGH genuinely inverts, not just passes through.
    // ==========================================================================
    tb_health_i[1] = 1'b0;  // channel 1's raw/qualified input is LOW
    wait_cycles(5);
    dri_read(DFC_ADDR_HEALTH_ACTIVE, rdata, code);
    check_bit("channel 1 (ACTIVE_HIGH=0): LOW input genuinely reads ACTIVE (inverted polarity)", rdata[1], 1'b1);

    tb_health_i[1] = 1'b1;
    wait_cycles(5);
    dri_read(DFC_ADDR_HEALTH_ACTIVE, rdata, code);
    check_bit("channel 1 (ACTIVE_HIGH=0): HIGH input genuinely reads INACTIVE", rdata[1], 1'b0);
    tb_health_i[1] = 1'b0;
    wait_cycles(5);
    dri_write(DFC_ADDR_HEALTH_STICKY, 32'h0000_0202, code);  // clear channel-1 sticky bits, tidy for later parts
    wait_cycles(5);

    // ==========================================================================
    // Part 6: aggregate fault (ARCH-RTL011-001) -- channel 3 (FAULT_ENABLE
    // clear) can be active/sticky without contributing; channel 4
    // (FAULT_ENABLE set, per Part 1) does contribute, and the aggregate is
    // live, not sticky.
    // ==========================================================================
    dri_read(DFC_ADDR_HEALTH_STATUS, rdata, code);
    check_bit("HEALTH_STATUS.AGGREGATE_FAULT genuinely clear at baseline", rdata[0], 1'b0);
    check_bit("fault_req_o genuinely clear at baseline", rtl011_fault_req, 1'b0);

    tb_health_i[3] = 1'b1;  // FAULT_ENABLE clear for channel 3
    wait_cycles(5);
    dri_read(DFC_ADDR_HEALTH_ACTIVE, rdata, code);
    check_bit("channel 3 genuinely active", rdata[3], 1'b1);
    dri_read(DFC_ADDR_HEALTH_STATUS, rdata, code);
    check_bit("channel 3 active but FAULT_ENABLE clear -- AGGREGATE_FAULT genuinely stays clear", rdata[0], 1'b0);
    check_bit("fault_req_o genuinely stays clear (channel 3 doesn't contribute)", rtl011_fault_req, 1'b0);

    tb_health_i[4] = 1'b1;  // FAULT_ENABLE set for channel 4
    wait_cycles(5);
    dri_read(DFC_ADDR_HEALTH_STATUS, rdata, code);
    check_bit("channel 4 active AND FAULT_ENABLE set -- AGGREGATE_FAULT genuinely asserts", rdata[0], 1'b1);
    check_bit("fault_req_o genuinely asserts (real aggregate, same signal)", rtl011_fault_req, 1'b1);

    tb_health_i[4] = 1'b0;
    wait_cycles(5);
    dri_read(DFC_ADDR_HEALTH_STATUS, rdata, code);
    check_bit("AGGREGATE_FAULT is genuinely LIVE, not sticky -- clears the instant channel 4 goes inactive", rdata[0], 1'b0);
    check_bit("fault_req_o genuinely clears too", rtl011_fault_req, 1'b0);
    tb_health_i[3] = 1'b0;
    wait_cycles(5);
    dri_write(DFC_ADDR_HEALTH_STICKY, 32'h0000_1818, code);  // tidy channel 3/4 sticky bits
    wait_cycles(5);

    // ==========================================================================
    // Part 7: real event/irq generation (event ID 0x0034, source index 10)
    // -- channel 5, real asserted-transition and real recovery-transition,
    // each producing a real, bit-exact event record.
    // ==========================================================================
    clear_capture();
    clear_irq_seen();
    tb_health_i[5] = 1'b1;
    wait_cycles(5);
    check_bit("captured a real event on channel 5's asserted transition", captured_valid, 1'b1);
    check("event ID is the real 0x0034 (Health/discrete)",
          captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_ID_HI:dfc_types_pkg::DFC_EVENT_RECORD__EVENT_ID_LO], 32'h0034);
    check("source ID is the real ARCH-002 C.5 index 10",
          {24'h0, captured_record[dfc_types_pkg::DFC_EVENT_RECORD__SOURCE_ID_HI:dfc_types_pkg::DFC_EVENT_RECORD__SOURCE_ID_LO]}, 32'd10);
    check("subtype is 0 (asserted)",
          {24'h0, captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO +: 8]}, 32'd0);
    check("channel index is 5",
          {24'h0, captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO+8 +: 8]}, 32'd5);
    check_bit("event_data active-mask bit 5 genuinely set",
              captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO+16+5], 1'b1);
    check_bit("event_data sticky-asserted-mask bit 5 genuinely set",
              captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO+24+5], 1'b1);
    check_bit("irq_req_o genuinely pulsed on the same real transition", tb_irq_seen, 1'b1);
    check_bit("irq_req_o is not stuck high afterward (a real one-cycle pulse)", rtl011_irq_req, 1'b0);

    clear_capture();
    clear_irq_seen();
    tb_health_i[5] = 1'b0;
    wait_cycles(5);
    check_bit("captured a real event on channel 5's recovery transition", captured_valid, 1'b1);
    check("subtype is 3 (recovery) -- see dfc_rtl011.sv's own disclosed subtype-selection note",
          {24'h0, captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO +: 8]}, 32'd3);
    check("channel index is still 5",
          {24'h0, captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO+8 +: 8]}, 32'd5);
    check_bit("irq_req_o genuinely pulses again on the recovery transition too", tb_irq_seen, 1'b1);
    dri_write(DFC_ADDR_HEALTH_STICKY, 32'h0000_2020, code);  // tidy channel 5 sticky bits
    wait_cycles(5);

    // ==========================================================================
    // Part 8: EVENT_OVERFLOW clear-field -- the tenth real instance of this
    // project's own gap class (items 2/7/8/12/20/24/28/32/36), proven the
    // same way: withhold the event handshake to force a genuine overflow,
    // then a real host CLEAR write.
    // ==========================================================================
    dri_write(DFC_ADDR_RTL011_EVT_OVERFLOW_STATUS, 32'h1, code);
    rtl011_evt_ready = 1'b0;
    dri_read(DFC_ADDR_RTL011_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("event_overflow starts clear before this part's own forced overflow", rdata[0], 1'b0);
    tb_health_i[6] = 1'b1;   // event #1 -- captured into the one slot
    wait_cycles(5);
    tb_health_i[6] = 1'b0;   // event #2 -- slot still occupied, genuinely dropped
    wait_cycles(5);
    dri_read(DFC_ADDR_RTL011_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("a real, genuine overflow (handshake withheld) set EVENT_OVERFLOW", rdata[0], 1'b1);
    dri_write(DFC_ADDR_RTL011_EVT_OVERFLOW_STATUS, 32'h1, code);
    check("RTL011_EVT_OVERFLOW_STATUS clear write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_RTL011_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("the real host write above actually cleared EVENT_OVERFLOW", rdata[0], 1'b0);
    rtl011_evt_ready = 1'b1;
    wait_cycles(5);
    dri_write(DFC_ADDR_HEALTH_STICKY, 32'h0000_4040, code);  // tidy channel 6 sticky bits
    wait_cycles(5);

    // ==========================================================================
    // Part 9: illegal configuration / ready / fault (this module's own
    // generic module_status bits, ARCH-VAL-011's "qualification is
    // 0-100 ms") -- deliberately distinct from Part 6's HEALTH_STATUS.
    // AGGREGATE_FAULT/fault_req_o (see dfc_rtl011.sv's own header).
    // ==========================================================================
    check_bit("status_o.ready set before any illegal configuration",
              rtl011_status[dfc_types_pkg::DFC_RTL011_STATUS__READY_HI], 1'b1);
    check_bit("status_o.fault clear before any illegal configuration",
              rtl011_status[dfc_types_pkg::DFC_RTL011_STATUS__FAULT_HI], 1'b0);
    dri_write(DFC_ADDR_HEALTH_QUAL_4_7, {8'd0, 8'd0, 8'd0, 8'd150}, code);  // ch4=150ms, illegal (>100)
    wait_cycles(5);
    check_bit("status_o.fault genuinely asserts on a real illegal (>100ms) qualification configuration",
              rtl011_status[dfc_types_pkg::DFC_RTL011_STATUS__FAULT_HI], 1'b1);
    check_bit("status_o.ready genuinely deasserts on the same illegal configuration",
              rtl011_status[dfc_types_pkg::DFC_RTL011_STATUS__READY_HI], 1'b0);
    check_bit("fault_req_o (the health-domain aggregate) is UNAFFECTED by this module-level illegal config",
              rtl011_fault_req, 1'b0);
    dri_write(DFC_ADDR_HEALTH_QUAL_4_7, 32'h0, code);  // restore legal (0ms)
    wait_cycles(5);
    check_bit("status_o.fault genuinely clears once the configuration is fixed",
              rtl011_status[dfc_types_pkg::DFC_RTL011_STATUS__FAULT_HI], 1'b0);
    check_bit("status_o.ready genuinely returns once the configuration is fixed",
              rtl011_status[dfc_types_pkg::DFC_RTL011_STATUS__READY_HI], 1'b1);

    $display("");
    $display("rtl011_integration_tb: %0d checks, %0d failures", checks, errors);
    if (errors == 0) $display("TEST PASSED"); else $display("TEST FAILED");
    $finish;
  end

endmodule
