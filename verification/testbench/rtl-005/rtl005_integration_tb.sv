// rtl005_integration_tb.sv -- REAL end-to-end round-trip test: a host-style
// register write through RTL-001's real address-decode path must actually
// change RTL-005's real behavior, and RTL-005's real internal state must
// actually reach back to a host register read through RTL-001. Same
// template and purpose as rtl002/003/004_integration_tb.sv, targeting the
// RTL-001<->RTL-005 register bus specifically (EVT_CONTROL/EVT_SOURCE_ENABLE/
// EVT_SNAPSHOT/EVT_POP/EVT_CLEAR control forwarding; EVT_STATUS/EVT_COUNT/
// EVT_OVERFLOW_COUNT/EVT_DATA0-3/EVT_DROP_SOURCE/EVT_ARB_STATUS/
// EVT_POP_ERROR_COUNT status forwarding), generated by reggen.py v4 +
// tools/reggen/rtl005_field_map.json.
//
// ADDITIONALLY (per this module's own real, distinguishing requirement):
// RTL-005 is the real store/arbiter for every other module's own events.
// This file instantiates a real RTL-004 alongside RTL-001/RTL-005
// specifically so a real, genuinely-generated RTL-004 event (SNAPSHOT
// complete, event ID 0x0009) actually reaches RTL-005's real store and is
// actually host-readable via EVT_DATA0-3/EVT_POP -- not a fabricated or
// injected value. RTL-002/RTL-003 are out of this test's scope (same
// isolation choice rtl002/003/004_integration_tb.sv already make for
// sibling modules not under test).
//
// DISCLOSED TEST-SCOPE SIMPLIFICATION: RTL-005's own self-loop
// (evt_valid_o -> evt_valid_i[4], evt_ready_o[4] -> evt_ready_i,
// evt_record_o -> evt_record_i[4] in the real dfc_rtl024.sv integration --
// see dfc_rtl005.sv's own header) is NOT wired as a literal loop in this
// testbench. Instead, `rtl005_self_evt_ready` directly drives evt_ready_i
// as a plain, testbench-controlled signal (default 1, forced to 0 only in
// Part 6) -- the same class of simplification rtl004_integration_tb.sv
// already uses for its own event handshake (`rtl004_evt_ready`). This
// exercises RTL-005's own one-deep self-generation layer
// (self_evt_pending_q/self_evt_overflow_q/self_evt_drop_count_q) directly
// without needing the external loop's slot-4 arbitration round trip. Real
// 24-way arbitration fairness (evt_valid_i[4]'s actual competition against
// the other 23 producers) is the disclosed "known dependency gap" already
// stated in RTL-005_RevA.md SS6 -- not meaningfully testable until more
// producer modules are real, and out of this integration test's scope.
//
// CLOCKING-DISCIPLINE NOTE (same lesson as every other testbench in this
// project): every strobe is held for a full clock and deasserted with a
// #1 settle delay after the sampling edge, never in the same delta.

`timescale 1ns/1ps

