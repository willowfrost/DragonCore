  logic [dfc_types_pkg::DFC_RTL002_STATUS_WIDTH-1:0]  rtl002_status_stub = '0;
  logic [dfc_types_pkg::DFC_RTL003_CONTROL_WIDTH-1:0] rtl003_control_unused;
  logic [dfc_types_pkg::DFC_RTL003_STATUS_WIDTH-1:0]  rtl003_status_stub = '0;
  // RTL-006 likewise out of this test's scope -- same disclosed-stub
  // pattern, added during RTL-006's own integration session.
  logic [dfc_types_pkg::DFC_RTL006_CONTROL_WIDTH-1:0] rtl006_control_unused;
  logic [dfc_types_pkg::DFC_RTL006_STATUS_WIDTH-1:0]  rtl006_status_stub = '0;
  // RTL-007 likewise out of this test's scope -- same disclosed-stub
  // pattern, added during RTL-007's own integration session.
  logic [dfc_types_pkg::DFC_RTL007_CONTROL_WIDTH-1:0] rtl007_control_unused;
  logic [dfc_types_pkg::DFC_RTL007_STATUS_WIDTH-1:0]  rtl007_status_stub = '0;

  logic [63:0] rtl004_timestamp;

  logic rtl004_evt_valid, rtl004_evt_ready;
  logic [dfc_types_pkg::DFC_EVENT_RECORD_WIDTH-1:0] rtl004_evt_record;

  logic [23:0]  rtl005_evt_valid_i;
  logic [23:0]  rtl005_evt_ready_o;
  logic [24*dfc_types_pkg::DFC_EVENT_RECORD_WIDTH-1:0] rtl005_evt_record_i;

  // Real producer index 3 (RTL-004); every other index disclosed stub-zero
  // (same as the real dfc_rtl024.sv integration for not-yet-real modules).
  assign rtl005_evt_valid_i  = {20'h0, rtl004_evt_valid, 3'h0};
  assign rtl004_evt_ready    = rtl005_evt_ready_o[3];
  assign rtl005_evt_record_i = {2560'h0, rtl004_evt_record, 384'h0};

  // See file header -- own self-loop simplification, not the real
  // evt_valid_i[4] arbitration path.
  logic rtl005_self_evt_ready = 1'b1;
  logic rtl005_self_evt_valid;
  logic [dfc_types_pkg::DFC_EVENT_RECORD_WIDTH-1:0] rtl005_self_evt_record;

  always #10 core_clk_i = ~core_clk_i;

  dfc_rtl001 u_rtl001 (
    .core_clk_i             (core_clk_i),
    .core_rst_n_i           (core_rst_n_i),
    .dri_req_valid_i        (dri_req_valid_i),
    .dri_req_ready_o        (dri_req_ready_o),
    .dri_req_write_i        (dri_req_write_i),
    .dri_req_addr_i         (dri_req_addr_i),
    .dri_req_wdata_i        (dri_req_wdata_i),
    .dri_req_wstrb_i        (dri_req_wstrb_i),
    .dri_rsp_valid_o        (dri_rsp_valid_o),
    .dri_rsp_ready_i        (dri_rsp_ready_i),
    .dri_rsp_rdata_o        (dri_rsp_rdata_o),
    .dri_rsp_code_o         (dri_rsp_code_o),
    .rtl002_control_o       (rtl002_control_unused),
    .rtl002_status_i        (rtl002_status_stub),
    .rtl003_control_o       (rtl003_control_unused),
    .rtl003_status_i        (rtl003_status_stub),
    .rtl004_control_o       (rtl004_control),
    .rtl004_status_i        (rtl004_status),
    .rtl005_control_o       (rtl005_control),
    .rtl005_status_i        (rtl005_status),
    .rtl006_control_o       (rtl006_control_unused),
    .rtl006_status_i        (rtl006_status_stub),
    .rtl007_control_o       (rtl007_control_unused),
    .rtl007_status_i        (rtl007_status_stub),
    .status_o               (),
    .dbg_regbank_write_en_o (dbg_regbank_write_en_o)
  );

  dfc_rtl004 u_rtl004 (
    .core_clk_i               (core_clk_i),
    .core_rst_n_i             (core_rst_n_i),
    .module_reset_i           (1'b0),
    .control_i                (rtl004_control),
    .status_o                 (rtl004_status),
    .evt_valid_o              (rtl004_evt_valid),
    .evt_ready_i              (rtl004_evt_ready),
    .evt_record_o             (rtl004_evt_record),
    .timestamp_o              (rtl004_timestamp),
    .operating_state_i        (dfc_types_pkg::NORMAL),
    .observational_mode_i     (1'b0),
    // All bits enabled -- this test targets the RTL-001<->RTL-005 register
    // bus and the real cross-module event delivery specifically, same
    // isolation choice already made in rtl004_integration_tb.sv.
    .event_condition_enable_i (64'hFFFF_FFFF_FFFF_FFFF),
    .irq_condition_enable_i   (64'h0)
  );

  dfc_rtl005 u_rtl005 (
    .core_clk_i               (core_clk_i),
    .core_rst_n_i             (core_rst_n_i),
    .module_reset_i           (1'b0),
    .control_i                (rtl005_control),
    .status_o                 (rtl005_status),
    .evt_valid_o              (rtl005_self_evt_valid),
    .evt_ready_i              (rtl005_self_evt_ready),
    .evt_record_o             (rtl005_self_evt_record),
    .timestamp_i              (rtl004_timestamp),
    .irq_req_o                (),
    .fault_req_o              (),
    .evt_valid_i              (rtl005_evt_valid_i),
    .evt_ready_o              (rtl005_evt_ready_o),
    .evt_record_i             (rtl005_evt_record_i),
    .operating_state_i        (dfc_types_pkg::NORMAL),
    .observational_mode_i     (1'b0),
    .global_event_enable_i    (1'b1),
    .event_condition_enable_i (64'hFFFF_FFFF_FFFF_FFFF),
    .irq_condition_enable_i   (64'h0)
  );

  int errors = 0, checks = 0;
  task automatic check(string what, logic [31:0] got, logic [31:0] expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got 0x%08h, expected 0x%08h", what, got, expected);
    end else $display("PASS: %s -- 0x%08h", what, got);
  endtask
  task automatic check_bit(string what, logic got, logic expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got %b, expected %b", what, got, expected);
    end else $display("PASS: %s", what);
  endtask

  task automatic dri_write(input logic [31:0] addr, input logic [31:0] data,
                            output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_wdata_i = data;
    dri_req_wstrb_i = 4'hF;
    dri_req_write_i = 1'b1;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    code = dri_rsp_code_o;
  endtask

  task automatic dri_read(input logic [31:0] addr, output logic [31:0] data,
                           output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_write_i = 1'b0;
    dri_req_wstrb_i = 4'h0;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    data = dri_rsp_rdata_o;
    code = dri_rsp_code_o;
  endtask

  // EVT_CLEAR (0x032C) is protected (REG-002, contract REG-032C) -- same
  // real PROTECT_KEY two-key authorization sequence as every other
  // protected register in this project, consumed by exactly one accepted
  // protected write.
  task automatic authorize_protected_write();
    logic [2:0] auth_code;
    dri_write(DFC_ADDR_PROTECT_KEY, dfc_constants_pkg::DFC_PROTECT_KEY1, auth_code);
    dri_write(DFC_ADDR_PROTECT_KEY, dfc_constants_pkg::DFC_PROTECT_KEY2, auth_code);
  endtask

  logic [2:0]  code;
  logic [31:0] rdata, rdata2, rdata3;

  initial begin
    dri_req_valid_i = 1'b0;
    dri_req_write_i = 1'b0;
    dri_req_addr_i  = '0;
    dri_req_wdata_i = '0;
    dri_req_wstrb_i = '0;

    core_rst_n_i = 1'b0;
    repeat (4) @(posedge core_clk_i);
    core_rst_n_i = 1'b1;
    @(posedge core_clk_i); #1;

    // ------------------------------------------------------------------
    // Part 1 (CONTROL direction, RW forwarding): a real host write to
    // EVT_SOURCE_ENABLE via RTL-001's real DRI path must actually change
    // RTL-005's real control_i -- the exact connection that would be
    // disconnected without reggen.py v4 + rtl005_field_map.json.
    // ------------------------------------------------------------------
    dri_read(DFC_ADDR_EVT_CONTROL, rdata, code);
    check({"EVT_CONTROL reads its real REG-002 reset value before any write ",
           "(LOGGER_ENABLE=1, OVERWRITE_OLDEST=1)"}, rdata, 32'h0000_0003);

    dri_read(DFC_ADDR_EVT_SOURCE_ENABLE, rdata, code);
    check({"EVT_SOURCE_ENABLE reads its real REG-002 reset value (all 24 ",
           "sources enabled)"}, rdata, 32'h00FF_FFFF);

    dri_write(DFC_ADDR_EVT_SOURCE_ENABLE, 32'h0000_0008, code);  // only source 3
    check("EVT_SOURCE_ENABLE write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    dri_read(DFC_ADDR_EVT_SOURCE_ENABLE, rdata, code);
    check("EVT_SOURCE_ENABLE reads back the real value just written",
          rdata, 32'h0000_0008);

    dri_write(DFC_ADDR_EVT_SOURCE_ENABLE, 32'h00FF_FFFF, code);  // restore
    check("EVT_SOURCE_ENABLE restored to all-enabled (RSP_OK)", {29'h0, code}, 32'h0);

    // ------------------------------------------------------------------
    // Part 2 (real cross-module event delivery, ARCH-EVT-001/002/004/005):
    // a real RTL-004 SNAPSHOT-complete event (0x0009, subtype 2) must
    // genuinely reach RTL-005's real store through its own producer slot 3
    // -- not a fabricated record.
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_TIME_SNAPSHOT, 32'h0000_0001, code);  // real RTL-004 event trigger
    check("TIME_SNAPSHOT write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    repeat (4) @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_EVT_STATUS, rdata, code);
    check_bit({"host-readable EVT_STATUS.NOT_EMPTY set by the real, genuinely ",
               "delivered RTL-004 event"}, rdata[0], 1'b1);

    dri_read(DFC_ADDR_EVT_COUNT, rdata, code);
    check("host-readable EVT_COUNT reflects exactly one real stored record",
          rdata, 32'h0000_0001);

    // CAPTURE_OLDEST (unprotected WO-CMD) snapshots the real record into
    // EVT_DATA0-3 without removing it.
    dri_write(DFC_ADDR_EVT_SNAPSHOT, 32'h0000_0001, code);
    check("EVT_SNAPSHOT (CAPTURE_OLDEST) write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_EVT_STATUS, rdata, code);
    check_bit("host-readable EVT_STATUS.SNAPSHOT_VALID set by the real capture",
              rdata[2], 1'b1);

    dri_read(DFC_ADDR_EVT_DATA2, rdata, code);
    check({"host-readable EVT_DATA2.EVENT_ID/SOURCE_ID genuinely match RTL-004's ",
           "real SNAPSHOT event (0x0009, source index 3) -- not a fabricated value"},
          rdata, 32'h0003_0009);

    dri_read(DFC_ADDR_EVT_DATA3, rdata, code);
    check({"host-readable EVT_DATA3.EVENT_DATA matches RTL-004's real subtype 2 ",
           "(snapshot complete)"}, rdata, 32'h0000_0002);

    // POP removes exactly one record and invalidates the snapshot (REG-002's
    // own EVT_POP text).
    dri_write(DFC_ADDR_EVT_POP, 32'h0000_0001, code);
    check("EVT_POP write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_EVT_COUNT, rdata, code);
    check("host-readable EVT_COUNT genuinely returns to zero after the real POP",
          rdata, 32'h0000_0000);
    dri_read(DFC_ADDR_EVT_STATUS, rdata, code);
    check_bit("host-readable EVT_STATUS.NOT_EMPTY cleared by the real POP",
              rdata[0], 1'b0);
    check_bit({"host-readable EVT_STATUS.SNAPSHOT_VALID invalidated by the real ",
               "POP (REG-002's own documented side effect)"}, rdata[2], 1'b0);

    // ------------------------------------------------------------------
    // Part 3 (pop-error + COUNTER-CLR, ARCH-EVT-006/ARCH-VAL-005): POP on an
    // already-empty store is genuinely rejected and counted.
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_EVT_POP, 32'h0000_0001, code);  // store already empty
    check({"EVT_POP write on an empty store is still RSP_OK (the reject is ",
           "internal, not a DRI-level error)"}, {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_EVT_STATUS, rdata, code);
    check_bit({"host-readable EVT_STATUS.POP_ERROR set by the real, genuine ",
               "rejected-empty-POP condition"}, rdata[5], 1'b1);
    dri_read(DFC_ADDR_EVT_POP_ERROR_COUNT, rdata, code);
    check("host-readable EVT_POP_ERROR_COUNT incremented by the real rejection",
          rdata, 32'h0000_0001);

    dri_write(DFC_ADDR_EVT_STATUS, 32'h0000_0020, code);  // W1C clear POP_ERROR
    check("EVT_STATUS.POP_ERROR clear write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    dri_write(DFC_ADDR_EVT_POP_ERROR_COUNT, 32'hFFFF_FFFF, code);  // COUNTER-CLR
    check("EVT_POP_ERROR_COUNT clear-pulse write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_EVT_STATUS, rdata, code);
    check_bit({"the real host clear write above actually cleared EVT_STATUS.",
               "POP_ERROR"}, rdata[5], 1'b0);
    dri_read(DFC_ADDR_EVT_POP_ERROR_COUNT, rdata, code);
    check({"the real host clear-pulse write above actually cleared ",
           "EVT_POP_ERROR_COUNT"}, rdata, 32'h0000_0000);

    // ------------------------------------------------------------------
    // Part 4 (CLEAR_ALL, ARCH-EVT-006 priority): push one more real record,
    // then genuinely clear the whole store.
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_TIME_SNAPSHOT, 32'h0000_0001, code);
    repeat (4) @(posedge core_clk_i); #1;
    dri_read(DFC_ADDR_EVT_COUNT, rdata, code);
    check("a second real record genuinely reached the store before CLEAR_ALL",
          rdata, 32'h0000_0001);

    authorize_protected_write();
    dri_write(DFC_ADDR_EVT_CLEAR, 32'h0000_0001, code);  // CLEAR_ALL
    check("EVT_CLEAR (CLEAR_ALL) write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_EVT_COUNT, rdata, code);
    check("EVT_COUNT genuinely returns to zero after the real CLEAR_ALL",
          rdata, 32'h0000_0000);
    dri_read(DFC_ADDR_EVT_STATUS, rdata, code);
    check_bit("EVT_STATUS.CLEAR_COMPLETE set by the real accepted CLEAR_ALL",
              rdata[6], 1'b1);

    dri_write(DFC_ADDR_EVT_STATUS, 32'h0000_0040, code);  // W1C clear CLEAR_COMPLETE
    check("EVT_STATUS.CLEAR_COMPLETE clear write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;
    dri_read(DFC_ADDR_EVT_STATUS, rdata, code);
    check_bit({"the real host clear write above actually cleared ",
               "EVT_STATUS.CLEAR_COMPLETE"}, rdata[6], 1'b0);

    // ------------------------------------------------------------------
    // Part 5 (SNAPSHOT_VALID W1C clear -- validates THIS session's own
    // ARCH-002 fix, approved before this module was implemented: closes
    // the gap where dfc_rtl005_control_t had no clear-request field for
    // EVT_STATUS.SNAPSHOT_VALID at all).
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_TIME_SNAPSHOT, 32'h0000_0001, code);
    repeat (4) @(posedge core_clk_i); #1;
    dri_write(DFC_ADDR_EVT_SNAPSHOT, 32'h0000_0001, code);  // CAPTURE_OLDEST
    @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_EVT_STATUS, rdata, code);
    check_bit("EVT_STATUS.SNAPSHOT_VALID set by a real capture", rdata[2], 1'b1);

    dri_write(DFC_ADDR_EVT_STATUS, 32'h0000_0004, code);  // W1C clear SNAPSHOT_VALID
    check({"EVT_STATUS.SNAPSHOT_VALID clear write accepted (RSP_OK, was ",
           "structurally impossible before this session's own ARCH-002 fix)"},
          {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_EVT_STATUS, rdata, code);
    check_bit({"the real host clear write above -- using the field this ",
               "session's ARCH-002 fix added -- actually cleared ",
               "EVT_STATUS.SNAPSHOT_VALID"}, rdata[2], 1'b0);

    dri_write(DFC_ADDR_EVT_POP, 32'h0000_0001, code);  // drain the record
    @(posedge core_clk_i); #1;

    // ------------------------------------------------------------------
    // Part 6 (self-generation overflow, generic status_o.event_overflow/
    // event_drop_count -- own one-deep pending layer, same shape every
    // prior module uses for its own event generation). DISCLOSED, GENUINE
    // GAP, logged in OPEN_ISSUES.md: unlike RTL-002/003/004, REG-002 owns
    // no RTL005_EVT_OVERFLOW_STATUS-equivalent register for this generic
    // pair at all (RTL-005's 15 owned registers are exhaustively the ones
    // this test already exercises) -- so this check is white-box against
    // status_o directly, not through any host-visible register, and there
    // is no host-clear path for it either. This differs from
    // EVT_DROP_SOURCE[4]/EVT_STATUS.SOURCE_DROP (the ARBITER's own,
    // separately real and host-visible per-producer-slot-4 evidence,
    // exercised implicitly by Part 2 above) -- see dfc_rtl005.sv's header
    // for why these are two distinct, non-redundant layers.
    // ------------------------------------------------------------------
    rtl005_self_evt_ready = 1'b0;
    @(posedge core_clk_i); #1;

    check_bit({"RTL-005's own generic event_overflow starts clear before any ",
               "overflow is forced"},
              rtl005_status[dfc_types_pkg::DFC_RTL005_STATUS__EVENT_OVERFLOW_HI], 1'b0);

    authorize_protected_write();
    dri_write(DFC_ADDR_EVT_CLEAR, 32'h0000_0001, code);  // 1st self-event (CLEAR_COMPLETE)
    check("first EVT_CLEAR write is still RSP_OK", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;  // 1st candidate now occupies the one-deep pending slot

    authorize_protected_write();
    dri_write(DFC_ADDR_EVT_CLEAR, 32'h0000_0001, code);  // 2nd self-event
    check("second EVT_CLEAR write is still RSP_OK", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;  // 2nd candidate lands on the still-occupied slot -- overflow

    check_bit({"a real, genuine overflow condition (two real CLEAR_ALL-",
              "triggered self-events, handshake withheld) actually set ",
              "RTL-005's own generic event_overflow -- not a fabricated value"},
              rtl005_status[dfc_types_pkg::DFC_RTL005_STATUS__EVENT_OVERFLOW_HI], 1'b1);
    check("RTL-005's own generic event_drop_count genuinely incremented",
          {16'h0, rtl005_status[dfc_types_pkg::DFC_RTL005_STATUS__EVENT_DROP_COUNT_HI:dfc_types_pkg::DFC_RTL005_STATUS__EVENT_DROP_COUNT_LO]},
          32'h0000_0001);

