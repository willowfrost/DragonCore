// rtl003_integration_tb.sv -- REAL end-to-end round-trip test: a host-style
// register write through RTL-001's real address-decode path must actually
// change RTL-003's real behavior, and RTL-003's real internal state must
// actually reach back to a host register read through RTL-001. Same
// template and purpose as rtl002_integration_tb.sv, targeting the
// RTL-001<->RTL-003 register bus specifically (IRQ_ENABLE/IRQ_ACK/
// IRQ_CLEAR/TEST_IRQ_INJECT control forwarding; IRQ_RAW_STATUS/IRQ_PENDING/
// IRQ_ACKED/IRQ_CLEAR/IRQ_VECTOR/RTL003_EVT_OVERFLOW_STATUS status
// forwarding), generated by reggen.py v4 + tools/reggen/rtl003_field_map.json.
//
// SCOPE: this test isolates the RTL-001<->RTL-003 connection itself, NOT
// the full RTL-002->RTL-003 interrupt-aggregation chain (that end-to-end
// path -- RTL-002's real irq_req_o through RTL-003's real aggregation to
// the real host_irq_n_o pad -- is covered by rtl024_skeleton_tb.sv, which
// instantiates the full system). Here, `irq_source_i`/`global_irq_enable_i`/
// `operating_state_i`/etc. are driven directly by this testbench (as
// RTL-002 would drive them), same isolation choice rtl002_integration_tb.sv
// already makes for module_ready_i/module_fault_i.
//
// CLOCKING-DISCIPLINE NOTE (same lesson as every other testbench in this
// project): every strobe is held for a full clock and deasserted with a
// #1 settle delay after the sampling edge, never in the same delta.

