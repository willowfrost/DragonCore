  int errors = 0, checks = 0;
  task automatic check(string what, logic [31:0] got, logic [31:0] expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got 0x%08h, expected 0x%08h", what, got, expected);
    end else $display("PASS: %s -- 0x%08h", what, got);
  endtask
  task automatic check_bit(string what, logic got, logic expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got %b, expected %b", what, got, expected);
    end else $display("PASS: %s", what);
  endtask

  task automatic dri_write(input logic [31:0] addr, input logic [31:0] data,
                            output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_wdata_i = data;
    dri_req_wstrb_i = 4'hF;
    dri_req_write_i = 1'b1;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    code = dri_rsp_code_o;
  endtask

  task automatic dri_read(input logic [31:0] addr, output logic [31:0] data,
                           output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_write_i = 1'b0;
    dri_req_wstrb_i = 4'h0;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    data = dri_rsp_rdata_o;
    code = dri_rsp_code_o;
  endtask

  // RTL006_EVT_OVERFLOW_STATUS (0x0434) is unprotected (REG-002); no
  // PROTECT_KEY sequence needed for it. GPIO_DIR (0x0404) IS protected
  // (REG-0404, "Protection: Yes") -- confirmed directly against REG-002's
  // own table, not assumed.
  task automatic authorize_protected_write();
    logic [2:0] auth_code;
    dri_write(DFC_ADDR_PROTECT_KEY, dfc_constants_pkg::DFC_PROTECT_KEY1, auth_code);
    dri_write(DFC_ADDR_PROTECT_KEY, dfc_constants_pkg::DFC_PROTECT_KEY2, auth_code);
  endtask

  logic [2:0]  code;
  logic [31:0] rdata;

  initial begin
    dri_req_valid_i = 1'b0;
    dri_req_write_i = 1'b0;
    dri_req_addr_i  = '0;
    dri_req_wdata_i = '0;
    dri_req_wstrb_i = '0;

    core_rst_n_i = 1'b0;
    repeat (4) @(posedge core_clk_i);
    core_rst_n_i = 1'b1;
    @(posedge core_clk_i); #1;

    // ------------------------------------------------------------------
    // Part 1 (CONTROL direction, RW forwarding + real output path): a
    // real host write to GPIO_DIR/GPIO_OUT/GPIO_CONTROL via RTL-001's
    // real DRI path must actually change RTL-006's real behavior -- the
    // exact connection that would be disconnected without reggen.py v4 +
    // rtl006_field_map.json.
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_GPIO_CONTROL, 32'h0000_0003, code);  // ENABLE|QUALIFICATION_ENABLE
    check("GPIO_CONTROL write accepted (RSP_OK)", {29'h0, code}, 32'h0);

    authorize_protected_write();  // GPIO_DIR is protected (REG-0404)
    dri_write(DFC_ADDR_GPIO_DIR, 32'h0000_0001, code);  // channel 0 = output, rest input
    check("GPIO_DIR write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    dri_read(DFC_ADDR_GPIO_DIR, rdata, code);
    check("GPIO_DIR reads back the real value just written", rdata, 32'h0000_0001);

    dri_write(DFC_ADDR_GPIO_OUT, 32'h0000_0001, code);  // channel 0 = 1
    check("GPIO_OUT write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    check_bit({"the real host write above actually reached RTL-006's real ",
               "gpio_oe_o[0] (direction=output, module_enable/effective_",
               "operational_enable both real-true in this test)"},
              gpio_oe_o[0], 1'b1);
    check_bit("the real host write above actually drove RTL-006's real gpio_o[0]",
              gpio_o[0], 1'b1);

    dri_read(DFC_ADDR_GPIO_STATUS, rdata, code);
    check({"host-readable GPIO_STATUS.COMMANDED_OUTPUT/EFFECTIVE_OUTPUT/",
           "DIRECTION all genuinely reflect the real write above (channel 0 ",
           "only)"}, rdata, 32'h0001_0101);

    dri_write(DFC_ADDR_GPIO_OUT, 32'h0000_0000, code);  // restore
    @(posedge core_clk_i); #1;
    check_bit("gpio_o[0] genuinely returns low once the real commanded value clears",
              gpio_o[0], 1'b0);

    // ------------------------------------------------------------------
    // Part 2 (STATUS direction, real simulated external pin -> real host
    // read): a real transition on the testbench-driven gpio_i pin must
    // genuinely reach GPIO_RAW_IN/GPIO_SYNC_IN through RTL-006's real
    // two-flop synchronizer -- channel 1 is configured as an input
    // (GPIO_DIR bit 1 = 0, already the case).
    // ------------------------------------------------------------------
    gpio_i[1] = 1'b1;
    @(posedge core_clk_i); #1;
    dri_read(DFC_ADDR_GPIO_RAW_IN, rdata, code);
    check_bit("GPIO_RAW_IN genuinely mirrors the real gpio_i[1] pin transition",
              rdata[1], 1'b1);

    repeat (2) @(posedge core_clk_i); #1;  // 2-flop synchronizer latency
    dri_read(DFC_ADDR_GPIO_SYNC_IN, rdata, code);
    check_bit({"GPIO_SYNC_IN genuinely reflects the real gpio_i[1] transition ",
               "through RTL-006's own two-flop synchronizer"}, rdata[1], 1'b1);

    // GPIO_QUAL_0_3.CH1_MS is still 0 (reset value) -- qualification value
    // zero passes through without delay (spec's own text), so GPIO_QUAL_IN
    // should already show the same real transition.
    dri_read(DFC_ADDR_GPIO_QUAL_IN, rdata, code);
    check_bit({"GPIO_QUAL_IN genuinely passes the real transition through ",
               "immediately when this channel's qualification time is zero"},
              rdata[1], 1'b1);

    gpio_i[1] = 1'b0;
    repeat (3) @(posedge core_clk_i); #1;

    // ------------------------------------------------------------------
    // Part 3 (millisecond-scale qualification timer, ARCH-MON-001/
    // ARCH-VAL-006): channel 2 gets a real, nonzero qualification time.
    // A transition SHORTER than the configured time must be genuinely
    // rejected (GPIO_QUAL_IN never changes); a transition held long
    // enough must be genuinely accepted.
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_GPIO_QUAL_0_3, 32'h0000_0100, code);  // CH2_MS = 1 (bits 23:16)
    check("GPIO_QUAL_0_3 (CH2_MS=1) write accepted (RSP_OK)", {29'h0, code}, 32'h0);

    dri_read(DFC_ADDR_GPIO_STATUS, rdata, code);
    check_bit({"GPIO_STATUS.QUALIFICATION_IN_PROGRESS[2] starts clear (channel ",
               "2 currently agrees with its own qualified value)"},
              rdata[24+2], 1'b0);

    // A short pulse -- well under one full 1ms qualification sample --
    // must be genuinely rejected: GPIO_QUAL_IN[2] never commits to 1.
    gpio_i[2] = 1'b1;
    repeat (1000) @(posedge core_clk_i);  // 20us, far short of the real 1ms sample
    gpio_i[2] = 1'b0;
    repeat (1000) @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_GPIO_QUAL_IN, rdata, code);
    check_bit({"a genuinely too-short transition on gpio_i[2] was correctly ",
               "rejected by the real qualification counter -- GPIO_QUAL_IN[2] ",
               "never committed"}, rdata[2], 1'b0);

    // A transition held for a full real millisecond (50,000 CORE_CLK
    // cycles at this project's nominal 50 MHz) must be genuinely accepted.
    gpio_i[2] = 1'b1;
    repeat (50_100) @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_GPIO_QUAL_IN, rdata, code);
    check_bit({"a genuinely qualifying transition (held a full real 1ms sample) ",
               "on gpio_i[2] was correctly accepted -- GPIO_QUAL_IN[2] committed"},
              rdata[2], 1'b1);

    gpio_i[2] = 1'b0;
    repeat (50_100) @(posedge core_clk_i); #1;
    dri_write(DFC_ADDR_GPIO_QUAL_0_3, 32'h0000_0000, code);  // restore CH2_MS = 0

    // ------------------------------------------------------------------
    // Part 4 (real rising-edge event generation, event ID 0x0010, source
    // index 5): channel 3, F.3 condition-mask bit 3 (rising).
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_GPIO_RISE_ENABLE, 32'h0000_0008, code);  // channel 3
    dri_write(DFC_ADDR_GPIO_EVENT_ENABLE, 32'h0000_0008, code);  // channel 3
    tb_event_condition_enable = 64'h0000_0000_0000_0008;  // F.3 bit 3 = rising ch3

    // evt_ready withheld so the real one-deep pending slot stays
    // genuinely observable (it self-clears the very next cycle once
    // accepted, per the same handshake shape every prior module's own
    // event generation uses) -- not a race against an exact cycle count.
    rtl006_evt_ready = 1'b0;
    gpio_i[3] = 1'b1;
    repeat (5) @(posedge core_clk_i); #1;  // sync-stage latency only (qual time 0)

    check_bit("a real, genuinely qualified rising edge on channel 3 asserted evt_valid_o",
              rtl006_evt_valid, 1'b1);
    check({"the real event record's EVENT_ID/SOURCE_ID genuinely match RTL-006's ",
           "own event (0x0010, source index 5) -- not a fabricated value"},
          {rtl006_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__SOURCE_ID_HI:dfc_types_pkg::DFC_EVENT_RECORD__SOURCE_ID_LO],
           rtl006_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_ID_HI:dfc_types_pkg::DFC_EVENT_RECORD__EVENT_ID_LO]},
          32'h0005_0010);
    check({"the real event record's detail bytes genuinely show subtype=0 ",
           "(rising) and channel index=3"},
          rtl006_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO+15:dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO],
          16'h0300);

    dri_read(DFC_ADDR_GPIO_EVENT_STATUS, rdata, code);
    check_bit({"the real sticky GPIO_EVENT_STATUS.EVENT[3] evidence was ",
               "genuinely set by the same qualified rising edge"}, rdata[3], 1'b1);

    dri_write(DFC_ADDR_GPIO_EVENT_STATUS, 32'h0000_0008, code);  // W1C clear channel 3
    @(posedge core_clk_i); #1;
    dri_read(DFC_ADDR_GPIO_EVENT_STATUS, rdata, code);
    check_bit("the real host clear write above actually cleared GPIO_EVENT_STATUS.EVENT[3]",
              rdata[3], 1'b0);

    // Same channel, now the falling-edge subcondition (GPIO_FALL_ENABLE,
    // F.3 bit 11 = 8+3 falling ch3) -- a real, genuinely qualified
    // falling edge must produce subtype=1.
    dri_write(DFC_ADDR_GPIO_FALL_ENABLE, 32'h0000_0008, code);  // channel 3
    tb_event_condition_enable = 64'h0000_0000_0000_0800;  // F.3 bit 11 = falling ch3
    // Drain the still-occupied one-deep slot from the rising-edge test
    // above before withholding evt_ready again -- otherwise the next
    // candidate lands on an already-occupied slot and is counted as a
    // real overflow instead of accepted.
    rtl006_evt_ready = 1'b1;
    @(posedge core_clk_i); #1;
    rtl006_evt_ready = 1'b0;
    gpio_i[3] = 1'b0;
    repeat (5) @(posedge core_clk_i); #1;

    check_bit("a real, genuinely qualified falling edge on channel 3 asserted evt_valid_o",
              rtl006_evt_valid, 1'b1);
    check({"the real event record's detail bytes genuinely show subtype=1 ",
           "(falling) and channel index=3"},
          rtl006_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO+15:dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO],
          16'h0301);

    rtl006_evt_ready = 1'b1;
    dri_write(DFC_ADDR_GPIO_FALL_ENABLE, 32'h0000_0000, code);  // restore
    repeat (5) @(posedge core_clk_i); #1;
    tb_event_condition_enable = 64'h0;

    // ------------------------------------------------------------------
    // Part 5 (real active-high-level irq generation): channel 4, F.3
    // condition-mask bit 20 (active-high level, ch4 = bit 16+4).
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_GPIO_IRQ_ENABLE, 32'h0000_0010, code);  // channel 4
    tb_irq_condition_enable = 64'h0000_0000_0010_0000;  // F.3 bit 20 = active-high ch4

    gpio_i[4] = 1'b1;
    repeat (5) @(posedge core_clk_i); #1;

    check_bit({"a real, genuinely qualified active-high level on channel 4 ",
               "asserted RTL-006's real irq_req_o"}, rtl006_irq_req, 1'b1);

    gpio_i[4] = 1'b0;
    repeat (5) @(posedge core_clk_i); #1;
    check_bit("irq_req_o genuinely deasserts once the real level condition clears",
              rtl006_irq_req, 1'b0);
    tb_irq_condition_enable = 64'h0;

    // ------------------------------------------------------------------
    // Part 6 (RTL006_EVT_OVERFLOW_STATUS -- REAL HOST READ, closing the
    // gap this session found in RTL-002/003/004's own identical registers:
    // this is a genuine host REGISTER READ of EVENT_OVERFLOW/DROP_COUNT,
    // not a white-box inspection of status_o directly -- see
    // dfc_rtl006.sv's own header for the full account of why this differs
    // from its three older siblings).
    // ------------------------------------------------------------------
    rtl006_evt_ready = 1'b0;
    dri_write(DFC_ADDR_GPIO_RISE_ENABLE, 32'h0000_0008, code);
    dri_write(DFC_ADDR_GPIO_EVENT_ENABLE, 32'h0000_0008, code);
    tb_event_condition_enable = 64'h0000_0000_0000_0008;

    dri_read(DFC_ADDR_RTL006_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit({"RTL006_EVT_OVERFLOW_STATUS.EVENT_OVERFLOW reads clear via a real ",
               "host READ before any overflow is forced"}, rdata[0], 1'b0);

    gpio_i[3] = 1'b1;
    repeat (5) @(posedge core_clk_i); #1;  // 1st candidate occupies the one-deep slot
    gpio_i[3] = 1'b0;
    repeat (5) @(posedge core_clk_i); #1;
    gpio_i[3] = 1'b1;
    repeat (5) @(posedge core_clk_i); #1;  // 2nd candidate lands on the still-occupied slot

    dri_read(DFC_ADDR_RTL006_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit({"a real, genuine overflow condition (two real qualified rising ",
               "edges, evt_ready withheld) is genuinely readable via a real ",
               "host REGISTER READ of RTL006_EVT_OVERFLOW_STATUS.EVENT_OVERFLOW ",
               "-- the exact register-readback path RTL-002/003/004's own ",
               "identical registers are still missing"}, rdata[0], 1'b1);
    check_bit({"RTL006_EVT_OVERFLOW_STATUS.DROP_COUNT is genuinely nonzero via ",
               "the same real host read"}, (rdata[23:8] != 16'h0), 1'b1);

    dri_write(DFC_ADDR_RTL006_EVT_OVERFLOW_STATUS, 32'h0000_0001, code);  // W1C clear
    check("RTL006_EVT_OVERFLOW_STATUS clear write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_RTL006_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit({"the real host clear write above actually cleared EVENT_OVERFLOW, ",
               "confirmed via a real host READ, not white-box inspection"},
              rdata[0], 1'b0);

    gpio_i[3] = 1'b0;
    rtl006_evt_ready = 1'b1;
    tb_event_condition_enable = 64'h0;
    repeat (3) @(posedge core_clk_i); #1;

    // ------------------------------------------------------------------
    // Part 7 (illegal configuration -> fault, ARCH-VAL-006/ARCH-RTL006-001):
    // a channel's qualification time exceeding the real 0-100ms legal
    // range is genuinely detected -- RTL-001 has no per-field range
    // validation yet (OPEN_ISSUES.md item 4), so this value genuinely
    // reaches control_i and RTL-006 must defend itself.
    // ------------------------------------------------------------------
    check_bit("RTL-006 reports ready (no illegal configuration yet)",
              rtl006_status[dfc_types_pkg::DFC_RTL006_STATUS__READY_HI], 1'b1);
    check_bit("RTL-006 reports no fault before any illegal configuration",
              rtl006_status[dfc_types_pkg::DFC_RTL006_STATUS__FAULT_HI], 1'b0);

    dri_write(DFC_ADDR_GPIO_QUAL_4_7, 32'h0000_0096, code);  // CH4_MS = 150 (> 100, illegal)
    @(posedge core_clk_i); #1;

    check_bit({"a genuinely illegal qualification value (150ms, RTL-001 does ",
               "not yet reject it) was detected by RTL-006 itself -- fault set"},
              rtl006_status[dfc_types_pkg::DFC_RTL006_STATUS__FAULT_HI], 1'b1);
    check_bit("RTL-006 correctly reports not-ready while illegal configuration persists",
              rtl006_status[dfc_types_pkg::DFC_RTL006_STATUS__READY_HI], 1'b0);

    dri_write(DFC_ADDR_GPIO_QUAL_4_7, 32'h0000_0000, code);  // restore legal value
    @(posedge core_clk_i); #1;

    check_bit("RTL-006 genuinely returns to ready/no-fault once the illegal value clears",
              rtl006_status[dfc_types_pkg::DFC_RTL006_STATUS__READY_HI], 1'b1);
    check_bit("fault genuinely clears alongside it",
              rtl006_status[dfc_types_pkg::DFC_RTL006_STATUS__FAULT_HI], 1'b0);

    $display("");
    $display("rtl006_integration_tb: %0d checks, %0d failures", checks, errors);
    if (errors != 0) begin
      $display("TEST FAILED");
      $finish(1);
    end else begin
      $display("TEST PASSED");
      $finish(0);
    end
  end

endmodule : rtl006_integration_tb
