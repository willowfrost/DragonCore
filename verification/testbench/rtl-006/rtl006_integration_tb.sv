// rtl006_integration_tb.sv -- REAL end-to-end round-trip test: a host-style
// register write through RTL-001's real address-decode path must actually
// change RTL-006's real behavior, and RTL-006's real internal state
// (including a real, simulated external pin transition) must actually
// reach back to a host register read through RTL-001. Same template and
// purpose as rtl002/003/004/005_integration_tb.sv, targeting the
// RTL-001<->RTL-006 register bus specifically (GPIO_CONTROL/GPIO_DIR/
// GPIO_OUT/GPIO_RISE_ENABLE/GPIO_FALL_ENABLE/GPIO_EVENT_ENABLE/
// GPIO_IRQ_ENABLE/GPIO_EVENT_STATUS/GPIO_QUAL_0_3/GPIO_QUAL_4_7/
// RTL006_EVT_OVERFLOW_STATUS control forwarding; GPIO_RAW_IN/GPIO_SYNC_IN/
// GPIO_QUAL_IN/GPIO_EVENT_STATUS/RTL006_EVT_OVERFLOW_STATUS/GPIO_STATUS
// status forwarding), generated by reggen.py v4 + tools/reggen/
// rtl006_field_map.json.
//
// ADDITIONALLY (per this module's own real, distinguishing requirement --
// the first Infrastructure module with real external I/O): `gpio_i` is
// driven here as a genuinely simulated external pin, not a register write
// -- a real transition on this testbench-driven input must reach
// GPIO_SYNC_IN/GPIO_QUAL_IN via RTL-006's real two-flop synchronizer plus
// millisecond-scale qualification counter, including a real test that a
// too-short transition is rejected and a long-enough one is accepted.
//
// RTL-002/RTL-004/RTL-005 are out of this test's scope (same isolation
// choice rtl004/005_integration_tb.sv already make for sibling modules not
// under test): `module_enable_i`/`effective_operational_enable_i` (real
// RTL-002 ports per dfc_rtl006.sv's own header) are driven directly by
// this testbench as plain constants, and `timestamp_i` is a free-running
// testbench counter, not RTL-004's real broadcast.
//
// DISCLOSED TEST-SCOPE LIMIT: this file exercises representative rising/
// falling/active-high/active-low subconditions on a small number of
// channels, not the full 8-channel x 5-subcondition cross product
// VP-INF-013 calls for -- the same class of disclosed, optional hardening
// gap RTL-001's own coverage note already accepts project-wide (see
// PROJECT_CONTINUITY.md Section 4). Every subcondition TYPE is exercised
// at least once for real.
//
// CLOCKING-DISCIPLINE NOTE (same lesson as every other testbench in this
// project): every strobe is held for a full clock and deasserted with a
// #1 settle delay after the sampling edge, never in the same delta.

