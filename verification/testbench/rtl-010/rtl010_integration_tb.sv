// rtl010_integration_tb.sv -- REAL end-to-end round-trip test: a host-style
// register write through RTL-001's real address-decode path must actually
// change RTL-010's real behavior (signed thresholds/hysteresis/max-age, per
// channel), and a real staged host commit through SENSOR_UPDATE_SELECT/
// _VALUE/_META/_COMMIT must atomically produce a real, correct value/valid/
// source/sequence/age readback and real signed threshold/stale/invalid
// evidence -- same template and purpose as rtl002 through rtl009_
// integration_tb.sv, targeting the RTL-001<->RTL-010 register bus
// specifically (SENSOR_CONTROL/SENSOR_UPDATE_*/SENSOR0_*/SENSOR1_*/
// RTL010_EVT_OVERFLOW_STATUS control forwarding; SENSOR_STATUS/SENSOR0_*/
// SENSOR1_*/RTL010_EVT_OVERFLOW_STATUS status forwarding), generated by
// reggen.py v4 + tools/reggen/rtl010_field_map.json.
//
// ADDITIONALLY (per this module's own real, distinguishing requirements):
//   - Part 3/4 exercise VP-MOD-010's real channel-independence obligation:
//     committing channel 1 must not disturb channel 0's already-committed
//     state, and vice versa -- checked in both directions.
//   - Part 5 exercises VP-MON-006's "complete signed representation"
//     requirement directly: negative, zero, positive, and the true
//     INT32_MIN/INT32_MAX boundary values are committed and checked against
//     real signed LOW/HIGH comparison, not unsigned intuition.
//   - Part 6 exercises the hysteresis ENTER/EXIT dead-band exactly at its
//     real boundary (">=" for low-exit, "<=" for high-exit), same boundary-
//     exactness discipline as rtl009_integration_tb.sv's own PULSE0_STATUS.
//     LOW/HIGH checks.
//   - Part 7 is VP-MON-007's own "atomic replace, no mixed record"
//     obligation: a single COMMIT is checked to atomically update
//     value/valid/source/sequence/age together in the one cycle it is
//     accepted -- ARCH-002's own 16-port catalog gives RTL-010 no real port
//     for a ROUTED commit yet (see dfc_rtl010.sv's own header for this
//     disclosed, logged gap), so the "host wins a same-cycle conflict
//     against a routed commit" half of VP-MON-007 cannot be exercised for
//     real in this integration -- only the atomicity half is testable here.
//   - Part 8 is REG-2314's own disclosed accept/reject precondition
//     (module must be `active`): a COMMIT issued while SENSOR_CONTROL.
//     ENABLE is 0 is genuinely rejected (SENSOR_STATUS.UPDATE_REJECTED
//     sets, no channel state changes) rather than silently accepted.
//   - Part 9 is the age/stale model (ARCH-MON-007): a real, live 1 ms tick
//     generator is allowed to run for genuinely elapsed simulation time
//     (not white-box-forced) to prove SENSOR0_CURRENT_AGE_MS advances and
//     SENSOR0_STATUS.STALE asserts once age exceeds a real, nonzero
//     MAX_AGE_MS -- and that MAX_AGE_MS=0 genuinely disables staleness
//     checking entirely (not "stale after 0 ms", the misreading
//     RTL-010_RevA.md SS3 explicitly warns against).
//   - Part 10 is the ninth real instance of this project's own
//     EVENT_OVERFLOW-clear-field gap class, proven exactly like items 2/7/
//     8/12/20/24/28/32 before it: a genuine, forced overflow (handshake
//     withheld) sets event_overflow_q, and a real host CLEAR write through
//     RTL-001's real DRI path genuinely clears it.
//   - Part 11 is illegal-configuration/ready/fault (ARCH-VAL-010): a
//     LOW>HIGH configuration on channel 0 alone is confirmed to fault the
//     whole module (ready low, fault_req_o high) even while channel 1
//     remains legally configured -- and fixing it clears the fault.
//
// RTL-002 through RTL-009 are out of this test's scope (same isolation
// choice every prior module-specific integration testbench already makes
// for sibling modules not under test): `module_enable_i` is driven directly
// by this testbench as a plain constant, and `timestamp_i` is a
// free-running testbench counter, not RTL-004's real broadcast.
//
// CLOCKING-DISCIPLINE NOTE (same lesson as every other testbench in this
// project): every strobe is held for a full clock and deasserted with a
// #1 settle delay after the sampling edge, never in the same delta.

