  int errors = 0, checks = 0;
  task automatic check(string what, logic [31:0] got, logic [31:0] expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got 0x%08h, expected 0x%08h", what, got, expected);
    end else $display("PASS: %s -- 0x%08h", what, got);
  endtask
  task automatic check_bit(string what, logic got, logic expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got %b, expected %b", what, got, expected);
    end else $display("PASS: %s", what);
  endtask

  task automatic dri_write(input logic [31:0] addr, input logic [31:0] data,
                            output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_wdata_i = data;
    dri_req_wstrb_i = 4'hF;
    dri_req_write_i = 1'b1;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    code = dri_rsp_code_o;
  endtask

  task automatic dri_read(input logic [31:0] addr, output logic [31:0] data,
                           output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_write_i = 1'b0;
    dri_req_wstrb_i = 4'h0;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    data = dri_rsp_rdata_o;
    code = dri_rsp_code_o;
  endtask

  // Stages and commits one sensor update via the real SENSOR_UPDATE_SELECT/
  // _VALUE/_META/_COMMIT registers -- the only real path this module
  // accepts a new value through.
  task automatic host_commit(input logic ch, input logic [31:0] value,
                              input logic valid, input logic [6:0] source,
                              input logic [23:0] seq, output logic [2:0] commit_code);
    logic [2:0] c;
    dri_write(DFC_ADDR_SENSOR_UPDATE_SELECT, {31'h0, ch}, c);
    dri_write(DFC_ADDR_SENSOR_UPDATE_VALUE, value, c);
    dri_write(DFC_ADDR_SENSOR_UPDATE_META, {seq, source, valid}, c);
    dri_write(DFC_ADDR_SENSOR_UPDATE_COMMIT, 32'h1, commit_code);
    @(posedge core_clk_i); #1;  // settle: commit is a one-cycle pulse
  endtask

  logic [2:0]  code;
  logic [31:0] rdata;

  initial begin
    core_rst_n_i = 0;
    repeat (4) @(posedge core_clk_i);
    core_rst_n_i = 1;
    repeat (2) @(posedge core_clk_i);

    // ==========================================================================
    // Part 1: SENSOR_CONTROL/SENSOR0_*/SENSOR1_* configuration writes reach
    // RTL-010's real control_i (bit-exact real register bus, not a
    // fabricated white-box force).
    // ==========================================================================
    dri_write(DFC_ADDR_SENSOR_CONTROL, 32'h7, code);  // ENABLE|EVENT_ENABLE|IRQ_ENABLE
    check("SENSOR_CONTROL write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_SENSOR_CONTROL, rdata, code);
    check("SENSOR_CONTROL reads back real value just written", rdata, 32'h7);

    dri_write(DFC_ADDR_SENSOR0_THRESH_LOW,  32'hFFFF_FC18, code);   // -1000
    dri_write(DFC_ADDR_SENSOR0_THRESH_HIGH, 32'h0000_03E8, code);   // +1000
    dri_write(DFC_ADDR_SENSOR0_HYSTERESIS,  32'd100, code);
    dri_write(DFC_ADDR_SENSOR0_MAX_AGE_MS,  32'd0, code);           // staleness disabled for now
    dri_write(DFC_ADDR_SENSOR0_EVENT_IRQ_CFG, 32'hFF, code);        // EVENT_ENABLE|IRQ_ENABLE = 0xF each
    check("SENSOR0_EVENT_IRQ_CFG write accepted (RSP_OK)", {29'h0,code}, 32'h0);

    dri_write(DFC_ADDR_SENSOR1_THRESH_LOW,  32'hFFFF_FE0C, code);   // -500
    dri_write(DFC_ADDR_SENSOR1_THRESH_HIGH, 32'h0000_01F4, code);   // +500
    dri_write(DFC_ADDR_SENSOR1_HYSTERESIS,  32'd50, code);
    dri_write(DFC_ADDR_SENSOR1_MAX_AGE_MS,  32'd0, code);
    dri_write(DFC_ADDR_SENSOR1_EVENT_IRQ_CFG, 32'hFF, code);
    check("SENSOR1_EVENT_IRQ_CFG write accepted (RSP_OK)", {29'h0,code}, 32'h0);

    dri_read(DFC_ADDR_SENSOR0_THRESH_LOW, rdata, code);
    check("SENSOR0_THRESH_LOW reads back real value just written", rdata, 32'hFFFF_FC18);
    dri_read(DFC_ADDR_SENSOR1_THRESH_HIGH, rdata, code);
    check("SENSOR1_THRESH_HIGH reads back real value just written", rdata, 32'h0000_01F4);

    // ==========================================================================
    // Part 2: real staged host commit atomically produces a real,
    // host-readable value/valid/source/sequence for channel 0.
    // ==========================================================================
    host_commit(1'b0, 32'd500, 1'b1, 7'd5, 24'd100, code);
    check("channel 0 COMMIT accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_SENSOR0_VALUE, rdata, code);
    check("SENSOR0_VALUE reads the real just-committed value", rdata, 32'd500);
    dri_read(DFC_ADDR_SENSOR0_STATUS, rdata, code);
    check_bit("SENSOR0_STATUS.VALID set after commit", rdata[0], 1'b1);
    check_bit("SENSOR0_STATUS.LOW clear (500 is within [-1000,1000])", rdata[2], 1'b0);
    check_bit("SENSOR0_STATUS.HIGH clear (500 is within [-1000,1000])", rdata[3], 1'b0);
    dri_read(DFC_ADDR_SENSOR0_META, rdata, code);
    check("SENSOR0_META.SOURCE/SEQUENCE match the real staged commit", rdata, {1'b0, 24'd100, 7'd5});
    dri_read(DFC_ADDR_SENSOR_STATUS, rdata, code);
    check_bit("SENSOR_STATUS.UPDATED set (module-wide, real commit accepted)", rdata[5], 1'b1);

    // ==========================================================================
    // Part 3: channel 1 commit does not disturb channel 0's already-
    // committed real state (VP-MOD-010 channel independence, direction 1).
    // ==========================================================================
    host_commit(1'b1, -32'd600, 1'b1, 7'd10, 24'd200, code);
    check("channel 1 COMMIT accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_SENSOR1_VALUE, rdata, code);
    check("SENSOR1_VALUE reads the real just-committed value", rdata, -32'd600);
    dri_read(DFC_ADDR_SENSOR1_STATUS, rdata, code);
    check_bit("SENSOR1_STATUS.LOW set (-600 < -500)", rdata[2], 1'b1);
    dri_read(DFC_ADDR_SENSOR0_VALUE, rdata, code);
    check("SENSOR0_VALUE UNCHANGED by the channel-1 commit (independence)", rdata, 32'd500);
    dri_read(DFC_ADDR_SENSOR0_STATUS, rdata, code);
    check_bit("SENSOR0_STATUS.LOW still clear (independence)", rdata[2], 1'b0);

    // ==========================================================================
    // Part 4: channel 0 commit does not disturb channel 1's already-
    // committed real state (independence, direction 2).
    // ==========================================================================
    host_commit(1'b0, 32'd1500, 1'b1, 7'd6, 24'd101, code);
    dri_read(DFC_ADDR_SENSOR0_STATUS, rdata, code);
    check_bit("SENSOR0_STATUS.HIGH set (1500 > 1000)", rdata[3], 1'b1);
    dri_read(DFC_ADDR_SENSOR1_VALUE, rdata, code);
    check("SENSOR1_VALUE UNCHANGED by the channel-0 commit (independence)", rdata, -32'd600);
    dri_read(DFC_ADDR_SENSOR1_STATUS, rdata, code);
    check_bit("SENSOR1_STATUS.LOW still set (independence)", rdata[2], 1'b1);

    // ==========================================================================
    // Part 5: VP-MON-006 -- the complete signed representation. Negative,
    // zero, positive, and the true INT32_MIN/INT32_MAX boundary values, all
    // against channel 0's real signed [-1000,1000] window.
    // ==========================================================================
    host_commit(1'b0, 32'h8000_0000, 1'b1, 7'd0, 24'd0, code);  // INT32_MIN
    dri_read(DFC_ADDR_SENSOR0_STATUS, rdata, code);
    check_bit("INT32_MIN genuinely reads LOW (signed, not unsigned-huge)", rdata[2], 1'b1);
    check_bit("INT32_MIN is not also HIGH", rdata[3], 1'b0);

    host_commit(1'b0, 32'h7FFF_FFFF, 1'b1, 7'd0, 24'd0, code);  // INT32_MAX
    dri_read(DFC_ADDR_SENSOR0_STATUS, rdata, code);
    check_bit("INT32_MAX genuinely reads HIGH (signed, not unsigned-huge)", rdata[3], 1'b1);
    check_bit("INT32_MAX is not also LOW", rdata[2], 1'b0);

    host_commit(1'b0, 32'd0, 1'b1, 7'd0, 24'd0, code);  // zero
    dri_read(DFC_ADDR_SENSOR0_STATUS, rdata, code);
    check_bit("zero is neither LOW nor HIGH", rdata[2], 1'b0);
    check_bit("zero is neither LOW nor HIGH (high)", rdata[3], 1'b0);

    // ==========================================================================
    // Part 6: hysteresis ENTER/EXIT dead-band, exact boundary
    // (">=" low-exit, "<=" high-exit) -- same boundary-exactness discipline
    // as rtl009_integration_tb.sv's own PULSE0_STATUS.LOW/HIGH checks.
    // Channel 0: LOW=-1000, HYST=100 -> low-exit bound = -900.
    // ==========================================================================
    host_commit(1'b0, -32'd1500, 1'b1, 7'd0, 24'd0, code);  // enter LOW
    dri_read(DFC_ADDR_SENSOR0_STATUS, rdata, code);
    check_bit("channel 0 enters LOW (-1500 < -1000)", rdata[2], 1'b1);

    host_commit(1'b0, -32'd950, 1'b1, 7'd0, 24'd0, code);   // still inside hysteresis band
    dri_read(DFC_ADDR_SENSOR0_STATUS, rdata, code);
    check_bit("channel 0 genuinely stays LOW (-950 < -900 exit bound)", rdata[2], 1'b1);

    host_commit(1'b0, -32'd900, 1'b1, 7'd0, 24'd0, code);   // exactly at exit bound
    dri_read(DFC_ADDR_SENSOR0_STATUS, rdata, code);
    check_bit("channel 0 genuinely exits LOW at the exact -900 boundary (>=)", rdata[2], 1'b0);

    // ==========================================================================
    // Part 7: VP-MON-007 atomicity -- a single COMMIT replaces value, valid,
    // source, and sequence together, in the one cycle it is accepted (no
    // mixed record observable). See file header for why the routed-commit
    // half of this obligation cannot be exercised here.
    // ==========================================================================
    host_commit(1'b1, 32'd42, 1'b1, 7'd99, 24'd777, code);
    dri_read(DFC_ADDR_SENSOR1_VALUE, rdata, code);
    check("atomic commit: VALUE landed", rdata, 32'd42);
    dri_read(DFC_ADDR_SENSOR1_STATUS, rdata, code);
    check_bit("atomic commit: VALID landed in the same commit", rdata[0], 1'b1);
    dri_read(DFC_ADDR_SENSOR1_META, rdata, code);
    check("atomic commit: SOURCE/SEQUENCE landed in the same commit", rdata, {1'b0, 24'd777, 7'd99});

    // ==========================================================================
    // Part 8: REG-2314's disclosed accept/reject precondition -- a COMMIT
    // issued while the module is disabled is genuinely rejected, not
    // silently accepted, and SENSOR_STATUS.UPDATE_REJECTED sets.
    // ==========================================================================
    dri_write(DFC_ADDR_SENSOR_CONTROL, 32'h0, code);  // disable
    host_commit(1'b0, 32'd12345, 1'b1, 7'd1, 24'd1, code);
    dri_write(DFC_ADDR_SENSOR_CONTROL, 32'h7, code);  // re-enable
    @(posedge core_clk_i); #1;
    dri_read(DFC_ADDR_SENSOR_STATUS, rdata, code);
    check_bit("SENSOR_STATUS.UPDATE_REJECTED set (commit while disabled)", rdata[4], 1'b1);
    dri_read(DFC_ADDR_SENSOR0_VALUE, rdata, code);
    check("channel 0 value stayed at its post-disable reset (0), not the rejected commit's 12345",
          rdata, 32'd0);
    // Clear the rejected-evidence bit for real, same W1C discipline as
    // every other sticky bit in this project.
    dri_write(DFC_ADDR_SENSOR_STATUS, 32'h10, code);
    dri_read(DFC_ADDR_SENSOR_STATUS, rdata, code);
    check_bit("SENSOR_STATUS.UPDATE_REJECTED genuinely clears via a real host W1C write", rdata[4], 1'b0);

    // ==========================================================================
    // Part 9: age/stale model (ARCH-MON-007) -- a real, live 1 ms tick is
    // allowed to run for genuinely elapsed simulation time. MS_TICK_CYCLES
    // = 50,000 (nominal 50 MHz CORE_CLK).
    // ==========================================================================
    host_commit(1'b0, 32'd7, 1'b1, 7'd2, 24'd2, code);       // fresh commit, age resets to 0
    dri_write(DFC_ADDR_SENSOR0_MAX_AGE_MS, 32'd0, code);      // zero: staleness DISABLED
    repeat (150_000) @(posedge core_clk_i);                    // ~3 ms elapsed
    dri_read(DFC_ADDR_SENSOR0_CURRENT_AGE_MS, rdata, code);
    check("SENSOR0_CURRENT_AGE_MS genuinely advanced (~3 ms elapsed)", rdata, 32'd3);
    dri_read(DFC_ADDR_SENSOR1_CURRENT_AGE_MS, rdata, code);
    check("SENSOR1_CURRENT_AGE_MS also genuinely advances, independently of channel 0", rdata, 32'd3);
    dri_read(DFC_ADDR_SENSOR0_STATUS, rdata, code);
    check_bit("MAX_AGE_MS=0 genuinely disables staleness (not stale even after 3 ms)", rdata[1], 1'b0);

    dri_write(DFC_ADDR_SENSOR0_MAX_AGE_MS, 32'd1, code);      // nonzero: staleness enabled at 1 ms
    host_commit(1'b0, 32'd7, 1'b1, 7'd2, 24'd3, code);        // fresh commit, age resets to 0 again
    repeat (150_000) @(posedge core_clk_i);                    // ~3 ms elapsed, > MAX_AGE_MS
    dri_read(DFC_ADDR_SENSOR0_STATUS, rdata, code);
    check_bit("nonzero MAX_AGE_MS genuinely asserts STALE once age exceeds it", rdata[1], 1'b1);

    // ==========================================================================
    // Part 10: EVENT_OVERFLOW clear-field -- the ninth real instance of this
    // project's own gap class (items 2/7/8/12/20/24/28/32), proven the same
    // way: withhold the event handshake to force a genuine overflow, then a
    // real host CLEAR write.
    //
    // Every real threshold-crossing commit in Parts 2-9 above ALSO tried to
    // emit its own module-wide "accepted" notification the same cycle --
    // this module's own shared-slot arbitration (see dfc_rtl010.sv's own
    // header) correctly, deliberately drops the lower-priority "accepted"
    // candidate whenever a channel's own transition wins the one pending
    // slot instead, which has already set EVENT_OVERFLOW for real several
    // times over by this point in the test (a genuine, disclosed consequence
    // of this module's real arbitration, not a bug -- see Part 6's own
    // enter/exit commits for concrete prior examples). A real host CLEAR
    // write establishes the known-clear starting state this part actually
    // needs, the same real mechanism Part 10 itself goes on to verify.
    // ==========================================================================
    dri_write(DFC_ADDR_RTL010_EVT_OVERFLOW_STATUS, 32'h1, code);
    rtl010_evt_ready = 1'b0;
    dri_read(DFC_ADDR_RTL010_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("event_overflow starts clear before this part's own forced overflow", rdata[0], 1'b0);
    host_commit(1'b0, 32'd8, 1'b1, 7'd3, 24'd4, code);   // event #1 -- captured into the one slot
    host_commit(1'b0, 32'd9, 1'b1, 7'd3, 24'd5, code);   // event #2 -- slot still occupied, genuinely dropped
    dri_read(DFC_ADDR_RTL010_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("a real, genuine overflow (handshake withheld) set EVENT_OVERFLOW", rdata[0], 1'b1);
    dri_write(DFC_ADDR_RTL010_EVT_OVERFLOW_STATUS, 32'h1, code);
    check("RTL010_EVT_OVERFLOW_STATUS clear write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_RTL010_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("the real host write above actually cleared EVENT_OVERFLOW", rdata[0], 1'b0);
    rtl010_evt_ready = 1'b1;
    @(posedge core_clk_i); #1;

    // ==========================================================================
    // Part 11: illegal configuration / ready / fault (ARCH-VAL-010) -- a
    // LOW>HIGH configuration on channel 0 alone faults the whole module even
    // while channel 1 remains legally configured.
    // ==========================================================================
    check_bit("fault_req_o clear before any illegal configuration", rtl010_fault_req, 1'b0);
    check_bit("status_o.ready set before any illegal configuration",
              rtl010_status[dfc_types_pkg::DFC_RTL010_STATUS__READY_HI], 1'b1);
    dri_write(DFC_ADDR_SENSOR0_THRESH_LOW,  32'h0000_03E8, code);  // LOW=1000
    dri_write(DFC_ADDR_SENSOR0_THRESH_HIGH, 32'hFFFF_FC18, code);  // HIGH=-1000 (LOW>HIGH, illegal)
    @(posedge core_clk_i); #1;
    check_bit("fault_req_o genuinely asserts on a real illegal (LOW>HIGH) configuration",
              rtl010_fault_req, 1'b1);
    check_bit("status_o.ready genuinely deasserts on the same illegal configuration",
              rtl010_status[dfc_types_pkg::DFC_RTL010_STATUS__READY_HI], 1'b0);
    dri_write(DFC_ADDR_SENSOR0_THRESH_LOW,  32'hFFFF_FC18, code);  // restore LOW=-1000
    dri_write(DFC_ADDR_SENSOR0_THRESH_HIGH, 32'h0000_03E8, code);  // restore HIGH=1000
    @(posedge core_clk_i); #1;
    check_bit("fault_req_o genuinely clears once the configuration is fixed", rtl010_fault_req, 1'b0);
    check_bit("status_o.ready genuinely returns once the configuration is fixed",
              rtl010_status[dfc_types_pkg::DFC_RTL010_STATUS__READY_HI], 1'b1);

    $display("");
    $display("rtl010_integration_tb: %0d checks, %0d failures", checks, errors);
    if (errors == 0) $display("TEST PASSED"); else $display("TEST FAILED");
    $finish;
  end

