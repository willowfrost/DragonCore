// rtl013_integration_tb.sv -- REAL end-to-end round-trip test: real host
// writes through RTL-001's real address-decode path must actually change
// RTL-013's real behavior, and RTL-013's real internal classification state
// must actually reach back to a host register read -- same template and
// purpose as rtl002 through rtl012_integration_tb.sv, targeting the
// RTL-001<->RTL-013 register bus specifically (FAULT_CONTROL/FAULT_STATUS/
// FAULT_RESPONSE/DEGRADED_STATUS/FAULT_LATCHED_SOURCE/
// RTL013_EVT_OVERFLOW_STATUS/TEST_FAULT_INJECT control forwarding;
// FAULT_STATUS/FAULT_CLASS/DEGRADED_STATUS/FAULT_ACTIVE_SOURCE/
// FAULT_LATCHED_SOURCE/RTL013_EVT_OVERFLOW_STATUS status forwarding),
// generated by reggen.py v4 + tools/reggen/rtl013_field_map.json.
//
// THE REAL, DISTINGUISHING REQUIREMENT for this module (per this session's
// own task instructions): fault conditions must be genuinely forced on
// already-real PRODUCER modules, not synthesized/injected directly at
// RTL-013's own fault_source_i boundary. This file instantiates two real
// producer modules alongside RTL-001/RTL-013 -- RTL-007 (Rotor RPM Monitor,
// fault_source_i[6], recoverable per ARCH-002 Appendix C.6) and RTL-011
// (System Health Monitor, fault_source_i[4], the ONLY currently-real
// NONRECOVERABLE producer) -- and drives each one's own real external
// stimulus (rotor_i / health_i) to genuinely trigger its own real
// fault_req_o, proving RTL-013 actually observes and classifies real
// evidence through the real fault-source matrix, not a fabricated white-box
// force. Every other fault_source_i bit is tied to a disclosed stub (0),
// same reasoning as dfc_rtl024.sv's own real integration (their producer
// modules either don't exist yet or are out of this file's own scope --
// rtl024_skeleton_tb.sv is the one whole-system testbench that proves the
// COMPLETE real fault-source matrix, all seven currently-real bits at once).
//
// RTL-002/003/004/005/008/009/010/012 are out of this test's scope (same
// isolation choice every prior module-specific integration testbench
// already makes for sibling modules not under test): `timestamp_i` is a
// free-running testbench counter, not RTL-004's real broadcast;
// `operating_state_i` is a plain testbench register (driven to NORMAL/
// TEST_DEBUG directly) so the TEST_FAULT_INJECT gating test does not need a
// real RTL-002 instance; `degraded_req_o`/`faulted_req_o`/`response_req_o`/
// `safety_inhibit_o` are observed directly at RTL-013's own boundary since
// RTL-002/RTL-016 are not under this file's own test scope either.
//
// CLOCKING-DISCIPLINE NOTE (same lesson as every other testbench in this
// project): every strobe is held for a full clock and deasserted with a
// #1 settle delay after the sampling edge, never in the same delta.

