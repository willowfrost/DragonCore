    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY1, c);
    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY2, c);
    dri_write(addr, data, code);
  endtask

  logic [2:0]  code;
  logic [31:0] rdata;

  // Testbench-side observer (verification aid, not DUT logic): the
  // reserved-bit illegal-activity condition is deliberately a live,
  // one-CORE_CLK-cycle-wide pulse in this module's own design (see
  // dfc_rtl013.sv's own Part 2 note), gone long before a multi-cycle DRI
  // read could ever sample it directly -- this sticky testbench latch
  // catches it at the instant it's genuinely live, the same technique any
  // real logic analyzer would use on a single-cycle pulse.
  logic tb_saw_illegal_fault = 1'b0;
  always @(posedge core_clk_i) begin
    if (rtl013_status[dfc_types_pkg::DFC_RTL013_STATUS__FAULT_HI]) tb_saw_illegal_fault <= 1'b1;
  end

  initial begin
    core_rst_n_i = 0;
    repeat (4) @(posedge core_clk_i);
    core_rst_n_i = 1;
    repeat (2) @(posedge core_clk_i);

    // ==========================================================================
    // Part 1: real register bus round trip. FAULT_CONTROL/FAULT_RESPONSE
    // (both REG-002-protected) reach control_i for real; FAULT_RECOVERABLE_
    // MASK reads the real fixed 0x00017FEF constant (forwarded through the
    // real reggen.py CONST-forwarding fix -- see dfc_rtl013.sv's own
    // header) and genuinely rejects any write (REG-311C: "Any register
    // write is ACCESS_ERROR").
    // ==========================================================================
    dri_read(DFC_ADDR_FAULT_RECOVERABLE_MASK, rdata, code);
    check("FAULT_RECOVERABLE_MASK reads the real fixed architecture constant",
          rdata, 32'h0001_7FEF);
    dri_write(DFC_ADDR_FAULT_RECOVERABLE_MASK, 32'hFFFF_FFFF, code);
    check("FAULT_RECOVERABLE_MASK write genuinely rejected (RSP_ACCESS_ERROR)",
          {29'h0, code}, 32'h2);
    dri_read(DFC_ADDR_FAULT_RECOVERABLE_MASK, rdata, code);
    check("FAULT_RECOVERABLE_MASK unchanged after the rejected write",
          rdata, 32'h0001_7FEF);

    // FAULT_CONTROL.ENABLE=1 (bit0), SAFETY_OUTPUT_REQUEST_ENABLE left at
    // 0 for now (Part 4 sets it for the response-request test).
    protected_write(DFC_ADDR_FAULT_CONTROL, 32'h0000_0001, code);
    check("FAULT_CONTROL protected write (ENABLE=1) with valid auth -> OK",
          {29'h0, code}, 32'h0);
    dri_read(DFC_ADDR_FAULT_CONTROL, rdata, code);
    check("FAULT_CONTROL reads back the real value just written", rdata, 32'h0000_0001);

    // FAULT_RESPONSE: DEGRADED_ENABLE=1, SAFETY_RESPONSE_ENABLE=1,
    // EVENT_ON_CLEAR=0, LATCH_UNTIL_HOST_CLEAR=0 (level policy for now --
    // Part 6 flips this to test the latch policy), SAFETY_OUTPUT_REQUEST_
    // ENABLE=4'b0001 (bit 0, arbitrary legal channel selection).
    protected_write(DFC_ADDR_FAULT_RESPONSE, 32'h0000_0013, code);
    check("FAULT_RESPONSE protected write with valid auth -> OK", {29'h0, code}, 32'h0);
    dri_read(DFC_ADDR_FAULT_RESPONSE, rdata, code);
    check("FAULT_RESPONSE reads back the real value just written", rdata, 32'h0000_0013);

    dri_read(DFC_ADDR_FAULT_STATUS, rdata, code);
    check("FAULT_STATUS genuinely reads all-clear before any real fault evidence",
          rdata, 32'h0000_0000);
    check_bit("degraded_req_o genuinely inactive before any real evidence",
              rtl013_degraded_req, 1'b0);
    check_bit("faulted_req_o genuinely inactive before any real evidence",
              rtl013_faulted_req, 1'b0);

    // ==========================================================================
    // Part 2: TEST_FAULT_INJECT gated by qualified test-active
    // (ARCH-VAL-013), and the reserved-bit defense (bits 17-31 illegal).
    // Bit 2 (Lost-link condition, RTL-015 -- not real yet) used as the
    // injection target: safe, does not collide with the real RTL-007/
    // RTL-011 evidence exercised in later parts.
    // ==========================================================================
    // FAULT_LATCHED_SOURCE (sticky), not FAULT_ACTIVE_SOURCE (live), is the
    // real observable here -- TEST_FAULT_INJECT's own captured control_i
    // pulse is exactly one CORE_CLK cycle wide (this project's own
    // established WO-CMD pulse-capture mechanism), long gone by the time a
    // multi-cycle DRI read could ever observe it live, but genuinely
    // latched into STICKY the instant it was live, per SS10.1's own
    // STICKY[i]_next equation -- the same real mechanism a genuinely
    // asynchronous real-world fault source relies on.
    tb_operating_state = dfc_types_pkg::NORMAL;
    protected_write(DFC_ADDR_TEST_FAULT_INJECT, 32'h0000_0004, code);  // bit 2
    check("TEST_FAULT_INJECT (protected) write with valid auth -> OK", {29'h0, code}, 32'h0);
    wait_cycles(2);
    dri_read(DFC_ADDR_FAULT_LATCHED_SOURCE, rdata, code);
    check("TEST_FAULT_INJECT genuinely has NO effect outside qualified TEST_DEBUG",
          rdata, 32'h0000_0000);

    tb_operating_state = dfc_types_pkg::TEST_DEBUG;
    wait_cycles(2);
    protected_write(DFC_ADDR_TEST_FAULT_INJECT, 32'h0000_0004, code);  // bit 2
    wait_cycles(2);
    dri_read(DFC_ADDR_FAULT_LATCHED_SOURCE, rdata, code);
    check_bit("TEST_FAULT_INJECT genuinely reaches LATCHED_SOURCE bit 2 while TEST_DEBUG qualified",
              rdata[2], 1'b1);
    dri_read(DFC_ADDR_FAULT_CLASS, rdata, code);
    check("FAULT_CLASS.CLASS reflects the injected source's real class (0x03, Lost-link)",
          rdata[7:0], 8'h03);
    check("FAULT_CLASS.PRIMARY_SOURCE reflects the injected source", rdata[12:8], 5'd2);

    // Clear the injected evidence via CLEAR_ALL_REQ before real evidence
    // starts in Part 3 -- a clean, known baseline.
    protected_write(DFC_ADDR_FAULT_CONTROL, 32'h0000_0003, code);  // ENABLE=1, CLEAR_ALL_REQ=1
    wait_cycles(2);
    tb_operating_state = dfc_types_pkg::NORMAL;
    dri_read(DFC_ADDR_FAULT_ACTIVE_SOURCE, rdata, code);
    check("injected source bit 2 genuinely cleared once inactive", rdata, 32'h0);
    dri_read(DFC_ADDR_FAULT_LATCHED_SOURCE, rdata, code);
    check("latched evidence genuinely cleared too", rdata, 32'h0);

    // Reserved-bit illegal activity (ARCH-VAL-013: bits 0-16 only). Uses
    // the tb_saw_illegal_fault observer (see its own declaration comment)
    // since this condition is deliberately live-only, one CORE_CLK cycle
    // wide.
    tb_saw_illegal_fault = 1'b0;
    protected_write(DFC_ADDR_TEST_FAULT_INJECT, 32'h0002_0000, code);  // bit 17, reserved
    wait_cycles(3);
    check_bit("status_o.fault genuinely asserted (observed live) on illegal reserved-bit activity",
              tb_saw_illegal_fault, 1'b1);
    // A single-cycle WO-CMD pulse self-clears; confirm the illegal-activity
    // evidence is genuinely live (not sticky) and has cleared again by now.
    check_bit("illegal reserved-bit fault genuinely clears once the pulse passes",
              rtl013_status[dfc_types_pkg::DFC_RTL013_STATUS__FAULT_HI], 1'b0);

    // ==========================================================================
    // Part 3: REAL RTL-007 rotor timeout -> fault_source_i[6] active
    // (recoverable per Appendix C.6). No synthetic force at RTL-013's own
    // boundary -- rotor_i is simply never pulsed after a short real
    // ROTOR_TIMEOUT_US is configured, exactly the same real technique
    // rtl007_integration_tb.sv's own Part 9 already proved.
    // ==========================================================================
    dri_write(DFC_ADDR_ROTOR_CONTROL, 32'h0000_0003, code);  // ENABLE=1, RISING_EDGE=1
    dri_write(DFC_ADDR_ROTOR_TIMEOUT_US, 32'd100, code);      // 100us real timeout
    check("ROTOR_TIMEOUT_US write accepted (RSP_OK)", {29'h0, code}, 32'h0);

    repeat (6000) @(posedge core_clk_i); #1;  // real 100us + generous margin, no edges sent

    check_bit("RTL-007's own real fault_req_o genuinely asserts after the real timeout",
              rtl007_fault_req, 1'b1);
    dri_read(DFC_ADDR_FAULT_ACTIVE_SOURCE, rdata, code);
    check_bit("RTL-013 genuinely observes RTL-007's real evidence on fault_source_i[6]",
              rdata[6], 1'b1);
    dri_read(DFC_ADDR_FAULT_CLASS, rdata, code);
    check("FAULT_CLASS.CLASS reflects RTL-007's real class (0x02, RPM abnormal/error)",
          rdata[7:0], 8'h02);
    check("FAULT_CLASS.PRIMARY_SOURCE selects the real active source (6)", rdata[12:8], 5'd6);
    check_bit("FAULT_CLASS.MULTIPLE is genuinely clear (one real active source)",
              rdata[13], 1'b0);
    check_bit("degraded_req_o (level request) genuinely asserts for real recoverable-active evidence",
              rtl013_degraded_req, 1'b1);
    check_bit("faulted_req_o genuinely stays clear (no nonrecoverable evidence yet)",
              rtl013_faulted_req, 1'b0);
    check("safety_inhibit_o genuinely stays clear (recoverable-only evidence)",
          {28'h0, rtl013_safety_inhibit}, 32'h0);
    dri_read(DFC_ADDR_FAULT_STATUS, rdata, code);
    check_bit("FAULT_STATUS.FAULT_ACTIVE sticky genuinely sets on real active evidence",
              rdata[0], 1'b1);

    // SS10.1: "Clear is effective only when ACTIVE is zero" -- a real host
    // clear attempt against a still-active source must be silently
    // ineffective.
    dri_write(DFC_ADDR_FAULT_LATCHED_SOURCE, 32'h0000_0040, code);  // bit 6
    wait_cycles(2);
    dri_read(DFC_ADDR_FAULT_ACTIVE_SOURCE, rdata, code);
    check_bit("a host clear attempt against a STILL-ACTIVE source is genuinely ineffective",
              rdata[6], 1'b1);

    // ==========================================================================
    // Part 4: REAL RTL-011 health fault, forced WHILE RTL-007's real
    // evidence is still active -- fault_source_i[4] (nonrecoverable per
    // Appendix C.6, the only currently-real nonrecoverable producer).
    // Channel 0 left at its own real reset defaults (HEALTH_POLARITY reset
    // 0 = active-low, HEALTH_QUAL_0_3 reset 0 = passes through without
    // delay per dfc_rtl011.sv's own real qualification logic) -- driving
    // health_i[0] LOW is therefore the real "active" stimulus.
    // ==========================================================================
    dri_write(DFC_ADDR_HEALTH_CONTROL, 32'h0000_0001, code);             // ENABLE=1
    protected_write(DFC_ADDR_HEALTH_FAULT_ENABLE, 32'h0000_0001, code);  // channel 0 (protected)
    check("HEALTH_FAULT_ENABLE protected write with valid auth -> OK", {29'h0, code}, 32'h0);
    tb_health_i[0] = 1'b0;  // active-low default: LOW = active
    wait_cycles(10);

    check_bit("RTL-011's own real fault_req_o genuinely asserts",
              rtl011_fault_req, 1'b1);
    dri_read(DFC_ADDR_FAULT_ACTIVE_SOURCE, rdata, code);
    check_bit("RTL-013 genuinely observes RTL-011's real evidence on fault_source_i[4]",
              rdata[4], 1'b1);
    check_bit("RTL-007's own real evidence on bit 6 is still genuinely active",
              rdata[6], 1'b1);
    dri_read(DFC_ADDR_FAULT_CLASS, rdata, code);
    check("primary source genuinely re-selects the lowest active bit (4, System-health)",
          rdata[12:8], 5'd4);
    check("FAULT_CLASS.CLASS reflects the new primary's real class (0x06, health/discrete)",
          rdata[7:0], 8'h06);
    check_bit("FAULT_CLASS.MULTIPLE genuinely sets (two real active sources)",
              rdata[13], 1'b1);
    check_bit("faulted_req_o genuinely asserts (real nonrecoverable active evidence)",
              rtl013_faulted_req, 1'b1);
    check("safety_inhibit_o genuinely asserts, all four bits (real active nonrecoverable evidence)",
          {28'h0, rtl013_safety_inhibit}, 32'hF);
    check_bit("degraded_req_o genuinely stays asserted too (bit 6's own recoverable-active evidence persists)",
              rtl013_degraded_req, 1'b1);

    dri_read(DFC_ADDR_FAULT_STATUS, rdata, code);
    check_bit("FAULT_STATUS.MULTI_FAULT sticky genuinely sets on real simultaneous evidence",
              rdata[1], 1'b1);
    check_bit("FAULT_STATUS.RESPONSE_PENDING genuinely sets (SAFETY_RESPONSE_ENABLE was set in Part 1)",
              rdata[3], 1'b1);
    check("response_req_o.valid genuinely mirrors FAULT_STATUS.RESPONSE_PENDING",
          {31'h0, rtl013_response_req[dfc_types_pkg::DFC_SAFETY_RESPONSE_REQ__VALID_HI]}, 32'h1);
    check("response_req_o.response_mask genuinely forwards the real configured mask",
          {28'h0, rtl013_response_req[dfc_types_pkg::DFC_SAFETY_RESPONSE_REQ__RESPONSE_MASK_HI:dfc_types_pkg::DFC_SAFETY_RESPONSE_REQ__RESPONSE_MASK_LO]},
          32'h1);

    // ==========================================================================
    // Part 5: clear RTL-007's own real condition (disable rotor monitoring
    // -- dfc_rtl007.sv's own `active` gate deasserts timeout_now for real,
    // not a synthetic force) -- bit 6 exits ACTIVE but remains STICKY.
    // ==========================================================================
    dri_write(DFC_ADDR_ROTOR_CONTROL, 32'h0000_0000, code);  // ENABLE=0
    wait_cycles(5);
    check_bit("RTL-007's own real fault_req_o genuinely clears once disabled",
              rtl007_fault_req, 1'b0);
    dri_read(DFC_ADDR_FAULT_ACTIVE_SOURCE, rdata, code);
    check_bit("bit 6 genuinely leaves ACTIVE once the real condition clears",
              rdata[6], 1'b0);
    dri_read(DFC_ADDR_FAULT_LATCHED_SOURCE, rdata, code);
    check_bit("bit 6 genuinely remains STICKY (latched) after leaving ACTIVE",
              rdata[6], 1'b1);
    dri_read(DFC_ADDR_FAULT_CLASS, rdata, code);
    check_bit("FAULT_CLASS.MULTIPLE genuinely clears (only bit 4 is ACTIVE now)",
              rdata[13], 1'b0);
    check("primary source stays the real active bit (4)", rdata[12:8], 5'd4);
    check_bit("degraded_req_o (level request) genuinely deasserts once bit 6 leaves ACTIVE",
              rtl013_degraded_req, 1'b0);
    check_bit("faulted_req_o (latched request) genuinely stays asserted (bit 4 still real-active)",
              rtl013_faulted_req, 1'b1);

    // ==========================================================================
    // Part 6: clear RTL-011's own real condition too -- bit 4 exits ACTIVE
    // but remains STICKY. THE concrete, testable proof of this module's own
    // level-vs-latched distinction (see dfc_rtl013.sv's own header):
    // faulted_req_o (latched -- active-OR-sticky) must genuinely REMAIN
    // asserted via the sticky evidence, while safety_inhibit_o (live --
    // active-only) must genuinely CLEAR the same cycle.
    // ==========================================================================
    tb_health_i[0] = 1'b1;  // deassert (active-low: HIGH = inactive)
    wait_cycles(10);
    check_bit("RTL-011's own real fault_req_o genuinely clears", rtl011_fault_req, 1'b0);
    dri_read(DFC_ADDR_FAULT_ACTIVE_SOURCE, rdata, code);
    check("no real source is ACTIVE any longer", rdata, 32'h0);
    dri_read(DFC_ADDR_FAULT_LATCHED_SOURCE, rdata, code);
    check("both bit 4 and bit 6 genuinely remain STICKY", rdata, 32'h0000_0050);
    check_bit("faulted_req_o (latched) genuinely REMAINS asserted via sticky evidence alone",
              rtl013_faulted_req, 1'b1);
    check("safety_inhibit_o (live, active-only) genuinely CLEARS the same cycle",
          {28'h0, rtl013_safety_inhibit}, 32'h0);
    dri_read(DFC_ADDR_FAULT_CLASS, rdata, code);
    check("primary source falls back to the lowest STICKY bit (4)", rdata[12:8], 5'd4);
    check_bit("FAULT_STATUS.CLASS_VALID genuinely stays high (sticky evidence still present)",
              rtl013_status[dfc_types_pkg::DFC_RTL013_STATUS__FAULT_STATUS__CLASS_VALID_HI], 1'b1);

    // FAULT_RESPONSE.LATCH_UNTIL_HOST_CLEAR was left clear (level policy)
    // in Part 1 -- response_req_o.valid must genuinely auto-track the live
    // condition and clear now that no real nonrecoverable evidence is
    // ACTIVE, exactly like safety_inhibit_o above (SS10.4's own analogous
    // LATCHED_REQUEST[c] equation, cited in dfc_rtl013.sv's own header).
    check_bit("response_req_o.valid (level policy) genuinely auto-clears with the live condition",
              rtl013_response_req[dfc_types_pkg::DFC_SAFETY_RESPONSE_REQ__VALID_HI], 1'b0);

    // DEGRADED_STATUS lifecycle: real entry/recovery bookkeeping from bit
    // 6's own earlier active-then-cleared episode (Parts 3/5).
    dri_read(DFC_ADDR_DEGRADED_STATUS, rdata, code);
    check_bit("DEGRADED_STATUS.ENTRY sticky genuinely latched the real earlier episode",
              rdata[1], 1'b1);
    check_bit("DEGRADED_STATUS.RECOVERY_AVAILABLE genuinely reflects entry-without-current-active",
              rdata[2], 1'b1);
    check_bit("DEGRADED_STATUS.RECOVERED genuinely pulse-latched on the real falling edge",
              rdata[3], 1'b1);

    // ==========================================================================
    // Part 7: real host FAULT_CONTROL.CLEAR_ALL_REQ, now that both real
    // sources are genuinely inactive -- SS10.1's own "clear effective only
    // when ACTIVE is zero" is satisfied for both, so the real clear
    // genuinely succeeds this time (contrast with Part 3's ineffective
    // attempt against a still-active source).
    // ==========================================================================
    protected_write(DFC_ADDR_FAULT_CONTROL, 32'h0000_0003, code);  // ENABLE=1, CLEAR_ALL_REQ=1
    wait_cycles(2);
    dri_read(DFC_ADDR_FAULT_LATCHED_SOURCE, rdata, code);
    check("real CLEAR_ALL_REQ genuinely clears all sticky evidence this time", rdata, 32'h0);
    dri_read(DFC_ADDR_FAULT_CLASS, rdata, code);
    check_bit("FAULT_STATUS.CLASS_VALID genuinely clears once all evidence is gone",
              rtl013_status[dfc_types_pkg::DFC_RTL013_STATUS__FAULT_STATUS__CLASS_VALID_HI], 1'b0);
    check("FAULT_CLASS.CLASS genuinely reads 0x00 (none) with no evidence", rdata[7:0], 8'h00);
    check_bit("faulted_req_o genuinely clears once the real sticky evidence is gone",
              rtl013_faulted_req, 1'b0);

    dri_write(DFC_ADDR_FAULT_STATUS, 32'h0000_000F, code);  // W1C clear FAULT_ACTIVE/MULTI_FAULT/EVENT_PENDING/RESPONSE_PENDING
    wait_cycles(2);
    dri_read(DFC_ADDR_FAULT_STATUS, rdata, code);
    check("real host clear write actually cleared every FAULT_STATUS sticky bit", rdata, 32'h0);

    // ==========================================================================
    // Part 8: the twelfth real instance of this project's own
    // EVENT_OVERFLOW-clear-field gap class (items 2/7/8/12/20/24/28/32/36/
    // 43/49 before it) -- a genuine (not fabricated) overflow forced by
    // withholding the event handshake, then a real host clear.
    // ==========================================================================
    tb_evt_ready = 1'b0;  // withhold handshake
    // HEALTH_FAULT_ENABLE (channel 0) is still real, real-set from Part 4 --
    // no re-write needed.
    tb_health_i[0] = 1'b0;  // re-trigger bit 4 -> a genuine "asserted" event candidate
    wait_cycles(10);  // same real RTL-011 CDC/qualification/aggregate-fault
                       // pipeline latency margin already proven safe in Part 4
    check_bit("a real event candidate is genuinely pending (handshake withheld)",
              rtl013_evt_valid, 1'b1);
    tb_health_i[0] = 1'b1;  // clear -> a genuine "recovered" event candidate, dropped (slot still full)
    wait_cycles(10);
    tb_health_i[0] = 1'b0;  // re-assert -> another genuine drop
    wait_cycles(5);

    dri_read(DFC_ADDR_RTL013_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("RTL013_EVT_OVERFLOW_STATUS.EVENT_OVERFLOW genuinely sets on the real forced overflow",
              rdata[0], 1'b1);
    check("RTL013_EVT_OVERFLOW_STATUS.DROP_COUNT genuinely counted the real dropped candidates",
          rdata[23:8] > 16'd0, 32'h1);

    tb_evt_ready = 1'b1;  // release the handshake so the clear below isn't racing a live overflow
    wait_cycles(3);
    dri_write(DFC_ADDR_RTL013_EVT_OVERFLOW_STATUS, 32'h0000_0001, code);  // W1C clear
    wait_cycles(2);
    dri_read(DFC_ADDR_RTL013_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("the real host clear write above actually cleared EVENT_OVERFLOW",
              rdata[0], 1'b0);

    // Clean up the real health condition left active from Part 8's own
    // forcing, for a tidy end-of-test state.
    tb_health_i[0] = 1'b1;
    wait_cycles(5);
    protected_write(DFC_ADDR_FAULT_CONTROL, 32'h0000_0003, code);
    wait_cycles(2);

    $display("");
    $display("rtl013_integration_tb: %0d checks, %0d failures", checks, errors);
    if (errors != 0) begin
      $display("INTEGRATION TEST FAILED");
      $finish(1);
    end else begin
      $display("INTEGRATION TEST PASSED");
      $finish(0);
    end
  end

