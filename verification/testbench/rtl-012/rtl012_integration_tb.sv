  int errors = 0, checks = 0;
  task automatic check(string what, logic [31:0] got, logic [31:0] expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got 0x%08h, expected 0x%08h", what, got, expected);
    end else $display("PASS: %s -- 0x%08h", what, got);
  endtask
  task automatic check_bit(string what, logic got, logic expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got %b, expected %b", what, got, expected);
    end else $display("PASS: %s", what);
  endtask

  task automatic dri_write(input logic [31:0] addr, input logic [31:0] data,
                            output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_wdata_i = data;
    dri_req_wstrb_i = 4'hF;
    dri_req_write_i = 1'b1;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    code = dri_rsp_code_o;
  endtask

  task automatic dri_read(input logic [31:0] addr, output logic [31:0] data,
                           output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_write_i = 1'b0;
    dri_req_wstrb_i = 4'h0;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    data = dri_rsp_rdata_o;
    code = dri_rsp_code_o;
  endtask

  task automatic wait_cycles(input int n);
    repeat (n) @(posedge core_clk_i);
  endtask

  // See file header TIMING METHODOLOGY note -- a hierarchical reference to
  // the DUT's own live elapsed_us_q, legal and standard for testbench
  // stimulus control.
  task automatic wait_until_elapsed(input int unsigned target);
    wait (u_rtl012.elapsed_us_q == target);
  endtask

  localparam logic [31:0] SERVICE_KEY_VALID = 32'hA5C3_5A3C;
  localparam int unsigned MIN_WINDOW = 5;
  localparam int unsigned MAX_WINDOW = 10;

  // Full WDOG_CONTROL value with ENABLE=en, EVENT_ENABLE=IRQ_ENABLE=
  // FAULT_ENABLE=1, WINDOW_ENABLE=0 (no wired effect, see dfc_rtl012.sv's
  // own header), SAFETY_RESPONSE_MASK=1 (bit 0, the sole legal position).
  function automatic logic [31:0] wdog_control_value(input logic en);
    wdog_control_value = {23'h0, 4'h1 /*mask=bit0*/, 1'b1 /*fault_en*/,
                           1'b1 /*irq_en*/, 1'b1 /*event_en*/, 1'b0 /*window_en*/, en};
  endfunction

  // Protected write (REG-3000) -- real two-key PROTECT_KEY sequence, same
  // discipline as every protected register write in this project.
  task automatic write_wdog_control(input logic en, output logic [2:0] code);
    logic [2:0] c;
    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY1, c);
    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY2, c);
    dri_write(DFC_ADDR_WDOG_CONTROL, wdog_control_value(en), code);
  endtask

  // Disables (resetting elapsed_us_q to 0, per ARCH-RTL012-001), then
  // re-enables -- every window-boundary part starts from this known,
  // fresh baseline. Windows are set once in Part 1 and never change.
  task automatic fresh_window;
    logic [2:0] c;
    write_wdog_control(1'b0, c);
    wait_cycles(3);
    write_wdog_control(1'b1, c);
    wait_cycles(3);
  endtask

  logic [2:0]  code;
  logic [31:0] rdata;

  initial begin
    core_rst_n_i = 0;
    repeat (4) @(posedge core_clk_i);
    core_rst_n_i = 1;
    repeat (2) @(posedge core_clk_i);

    // ==========================================================================
    // Part 1: WDOG_WINDOW_OPEN_US/WDOG_TIMEOUT_US/WDOG_CONTROL configuration
    // writes reach RTL-012's real control_i (bit-exact real register bus,
    // not a fabricated white-box force). MIN_WINDOW=5us, MAX_WINDOW=10us --
    // small, clean integers for the exact boundary tests in Parts 2-6.
    // ==========================================================================
    dri_write(DFC_ADDR_WDOG_WINDOW_OPEN_US, MIN_WINDOW, code);
    check("WDOG_WINDOW_OPEN_US write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_WDOG_WINDOW_OPEN_US, rdata, code);
    check("WDOG_WINDOW_OPEN_US reads back real value just written", rdata, MIN_WINDOW);

    dri_write(DFC_ADDR_WDOG_TIMEOUT_US, MAX_WINDOW, code);
    check("WDOG_TIMEOUT_US write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_WDOG_TIMEOUT_US, rdata, code);
    check("WDOG_TIMEOUT_US reads back real value just written", rdata, MAX_WINDOW);

    write_wdog_control(1'b1, code);
    check("WDOG_CONTROL protected write (ENABLE=1) with valid auth -> OK", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_WDOG_CONTROL, rdata, code);
    check("WDOG_CONTROL reads back the real value just written", rdata, wdog_control_value(1'b1));

    wait_cycles(3);
    dri_read(DFC_ADDR_WDOG_STATUS, rdata, code);
    check_bit("WDOG_STATUS.ENABLED genuinely reflects the real enabled state", rdata[0], 1'b1);
    check_bit("WDOG_STATUS.WINDOW_OPEN is genuinely clear before MIN_WINDOW elapses", rdata[1], 1'b0);

    // ==========================================================================
    // Part 2: EARLY -- exactly at MIN_WINDOW-1 (VP-SAFE-004). A correct-key
    // service before the window opens is rejected as EARLY, does NOT
    // restart the timer, and does NOT set SERVICE_ACCEPTED.
    // ==========================================================================
    fresh_window();
    clear_capture(); clear_irq_seen(); clear_activity_seen();
    wait_until_elapsed(MIN_WINDOW - 1);
    dri_write(DFC_ADDR_WDOG_SERVICE, SERVICE_KEY_VALID, code);
    check("WDOG_SERVICE SPI/DRI write accepted (RSP_OK -- RTL-001 forwards any value)", {29'h0,code}, 32'h0);
    wait_cycles(3);
    dri_read(DFC_ADDR_WDOG_STATUS, rdata, code);
    check_bit("EARLY (MIN-1): EARLY_SERVICE genuinely sets", rdata[3], 1'b1);
    check_bit("EARLY (MIN-1): SERVICE_ACCEPTED genuinely stays clear", rdata[2], 1'b0);
    check_bit("EARLY (MIN-1): TIMEOUT genuinely stays clear", rdata[5], 1'b0);
    check_bit("EARLY (MIN-1): irq_req_o genuinely pulsed", tb_irq_seen, 1'b1);
    check_bit("EARLY (MIN-1): service_activity_o genuinely stays clear (not a qualified acceptance)", tb_activity_seen, 1'b0);
    check("EARLY (MIN-1): captured event subtype is 0 (early, C.7 0x0040)",
          {24'h0, captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO +: 8]}, 32'd0);
    wait_cycles(10);
    dri_read(DFC_ADDR_WDOG_ELAPSED_US, rdata, code);
    check({"EARLY (MIN-1): the timer genuinely did NOT restart -- elapsed_us_q stayed nonzero ",
           "instead of resetting to 0"},
          (rdata != 32'd0), 32'd1);
    dri_write(DFC_ADDR_WDOG_STATUS, 32'h0000_0008, code);  // clear EARLY_SERVICE, tidy

    // ==========================================================================
    // Part 3: legal exactly AT MIN_WINDOW (VP-SAFE-004) -- the half-open
    // window's own lower boundary is legal, not EARLY.
    // ==========================================================================
    fresh_window();
    clear_capture(); clear_irq_seen(); clear_activity_seen();
    wait_until_elapsed(MIN_WINDOW);
    dri_write(DFC_ADDR_WDOG_SERVICE, SERVICE_KEY_VALID, code);
    wait_cycles(3);
    dri_read(DFC_ADDR_WDOG_STATUS, rdata, code);
    check_bit("legal-at-MIN: SERVICE_ACCEPTED genuinely sets (boundary is legal, not EARLY)", rdata[2], 1'b1);
    check_bit("legal-at-MIN: EARLY_SERVICE genuinely stays clear", rdata[3], 1'b0);
    check_bit("legal-at-MIN: service_activity_o genuinely pulsed (a real qualified acceptance)", tb_activity_seen, 1'b1);
    check("legal-at-MIN: captured event subtype is 5 (service accepted, C.7 0x0040)",
          {24'h0, captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO +: 8]}, 32'd5);
    dri_read(DFC_ADDR_WDOG_ELAPSED_US, rdata, code);
    check("legal-at-MIN: the timer genuinely restarted -- elapsed_us_q back at (or very near) 0",
          (rdata <= 32'd1), 32'd1);
    dri_write(DFC_ADDR_WDOG_STATUS, 32'h0000_0004, code);  // clear SERVICE_ACCEPTED, tidy

    // ==========================================================================
    // Part 4: legal at MAX_WINDOW-1 (VP-SAFE-004) -- the half-open window's
    // own upper boundary is still legal.
    // ==========================================================================
    fresh_window();
    clear_capture();
    wait_until_elapsed(MAX_WINDOW - 1);
    dri_write(DFC_ADDR_WDOG_SERVICE, SERVICE_KEY_VALID, code);
    wait_cycles(3);
    dri_read(DFC_ADDR_WDOG_STATUS, rdata, code);
    check_bit("legal-at-MAX-1: SERVICE_ACCEPTED genuinely sets", rdata[2], 1'b1);
    check_bit("legal-at-MAX-1: TIMEOUT genuinely stays clear -- the window never actually closed", rdata[5], 1'b0);
    dri_write(DFC_ADDR_WDOG_STATUS, 32'h0000_0004, code);  // tidy

    // ==========================================================================
    // Part 5: LATE exactly AT MAX_WINDOW -- ARCH-RTL012-001's own explicit
    // "timeout detection precedes same-cycle late service" race, and
    // VP-SAFE-004's own named boundary. Service arrives the SAME cycle the
    // counter first reaches MAX_WINDOW.
    // ==========================================================================
    fresh_window();
    clear_capture(); clear_irq_seen(); clear_activity_seen();
    wait_until_elapsed(MAX_WINDOW);
    dri_write(DFC_ADDR_WDOG_SERVICE, SERVICE_KEY_VALID, code);
    wait_cycles(3);
    dri_read(DFC_ADDR_WDOG_STATUS, rdata, code);
    check_bit({"LATE (=MAX): TIMEOUT genuinely sets -- the timeout is declared regardless of ",
               "the simultaneous late service (timeout detection precedes same-cycle late ",
               "service, ARCH-RTL012-001)"},
              rdata[5], 1'b1);
    check_bit("LATE (=MAX): SERVICE_ACCEPTED genuinely stays clear -- the late service does not retroactively prevent the timeout", rdata[2], 1'b0);
    check_bit("LATE (=MAX): RESPONSE_PENDING genuinely sets (real safety-response request)", rdata[6], 1'b1);
    check_bit("LATE (=MAX): fault_req_o genuinely asserts (FAULT_ENABLE set in Part 1)", rtl012_fault_req, 1'b1);
    check_bit("LATE (=MAX): response_req_o.valid genuinely asserts",
              rtl012_response_req[dfc_types_pkg::DFC_SAFETY_RESPONSE_REQ__VALID_HI], 1'b1);
    check({"LATE (=MAX): response_req_o.response_mask reads back the real configured mask ",
           "(bit 0, the sole legal Appendix C.8 watchdog position)"},
          {28'h0, rtl012_response_req[dfc_types_pkg::DFC_SAFETY_RESPONSE_REQ__RESPONSE_MASK_HI:dfc_types_pkg::DFC_SAFETY_RESPONSE_REQ__RESPONSE_MASK_LO]},
          32'h1);
    check({"LATE (=MAX): response_req_o.source_id is the fixed constant 0 (Appendix C.8 ",
           "'RTL-012 lane 0, source 0')"},
          {29'h0, rtl012_response_req[dfc_types_pkg::DFC_SAFETY_RESPONSE_REQ__SOURCE_ID_HI:dfc_types_pkg::DFC_SAFETY_RESPONSE_REQ__SOURCE_ID_LO]},
          32'h0);

    // ==========================================================================
    // Part 6: RECOVERY. From Part 5's still-live timeout condition: RECOVER
    // is genuinely accepted while timed out (clears the live condition, but
    // NOT the sticky TIMEOUT evidence, NOT RESPONSE_PENDING); exactly one
    // subsequent valid in-window service then genuinely completes recovery.
    // A separate RECOVER issued while NOT timed out is genuinely rejected
    // (ARCH-VAL-012 "invalid timing").
    // ==========================================================================
    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY1, code);
    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY2, code);
    dri_write(DFC_ADDR_WDOG_RECOVERY, 32'h1, code);
    check("WDOG_RECOVERY protected write with valid auth -> OK (RTL-001 forwards any value)", {29'h0,code}, 32'h0);
    wait_cycles(3);
    dri_read(DFC_ADDR_WDOG_STATUS, rdata, code);
    check_bit("RECOVER (accepted, was timed out): TIMEOUT sticky evidence REMAINS SET (RECOVER does not clear it)", rdata[5], 1'b1);
    check_bit("RECOVER (accepted, was timed out): RESPONSE_PENDING REMAINS SET (recovery not yet complete)", rdata[6], 1'b1);
    dri_read(DFC_ADDR_WDOG_ELAPSED_US, rdata, code);
    check("RECOVER (accepted): the timer genuinely restarted (elapsed_us_q back at/near 0)", (rdata <= 32'd1), 32'd1);

    clear_capture();
    wait_until_elapsed(MIN_WINDOW);
    dri_write(DFC_ADDR_WDOG_SERVICE, SERVICE_KEY_VALID, code);
    wait_cycles(3);
    dri_read(DFC_ADDR_WDOG_STATUS, rdata, code);
    check_bit("RECOVERY COMPLETE: the confirming valid in-window service genuinely clears RESPONSE_PENDING", rdata[6], 1'b0);
    check_bit("RECOVERY COMPLETE: SERVICE_ACCEPTED also genuinely sets (an ordinary valid service too)", rdata[2], 1'b1);
    check_bit("RECOVERY COMPLETE: response_req_o.valid genuinely deasserts",
              rtl012_response_req[dfc_types_pkg::DFC_SAFETY_RESPONSE_REQ__VALID_HI], 1'b0);
    check_bit("RECOVERY COMPLETE: fault_req_o genuinely deasserts (timeout_active_q cleared)", rtl012_fault_req, 1'b0);
    check("RECOVERY COMPLETE: captured event subtype is 4 (recovered, C.7 0x0040)",
          {24'h0, captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO +: 8]}, 32'd4);
    dri_write(DFC_ADDR_WDOG_STATUS, 32'h0000_0024, code);  // clear TIMEOUT/SERVICE_ACCEPTED, tidy

    // RECOVER issued while genuinely NOT timed out -- accepted at the
    // RTL-001 level (valid protected write), but genuinely rejected inside
    // RTL-012 itself (ARCH-VAL-012 "invalid timing"): no counter/state
    // effect. Waits for a distinguishable NONZERO elapsed value first --
    // checking merely "!= 0" right after Recovery Complete's own reset
    // could not distinguish "genuinely stayed at 0" from "wrongly reset
    // back to 0", since elapsed_us_q had not yet ticked past 0 either way.
    wait_until_elapsed(3);
    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY1, code);
    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY2, code);
    dri_write(DFC_ADDR_WDOG_RECOVERY, 32'h1, code);
    check("WDOG_RECOVERY protected write with valid auth -> OK (RTL-001-level acceptance)", {29'h0,code}, 32'h0);
    wait_cycles(3);
    dri_read(DFC_ADDR_WDOG_ELAPSED_US, rdata, code);
    check({"RECOVER (rejected inside RTL-012, not timed out): the timer did NOT reset -- ",
           "confirms the command had no effect, per ARCH-VAL-012's own 'invalid timing is ",
           "rejected'"},
          (rdata >= 32'd3), 32'd1);

    // ==========================================================================
    // Part 7: missing/timeout -- no service at all. Distinct real event
    // subtype (2, "missing/timeout") from Part 5's LATE (1) even though
    // both set the same real WDOG_STATUS.TIMEOUT sticky bit.
    // ==========================================================================
    fresh_window();
    clear_capture();
    wait_until_elapsed(MAX_WINDOW);
    wait_cycles(3);
    dri_read(DFC_ADDR_WDOG_STATUS, rdata, code);
    check_bit("MISSING/TIMEOUT (no service): TIMEOUT genuinely sets with no service ever attempted", rdata[5], 1'b1);
    check("MISSING/TIMEOUT: captured event subtype is 2 (missing/timeout, C.7 0x0040) -- distinct from Part 5's LATE (1)",
          {24'h0, captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO +: 8]}, 32'd2);
    // Part 8's own fresh_window() (disable/re-enable via WDOG_CONTROL) is
    // what actually resets state for the next part -- no RECOVER needed
    // here.
    dri_write(DFC_ADDR_WDOG_STATUS, 32'h0000_0020, code);  // clear TIMEOUT sticky, tidy

    // ==========================================================================
    // Part 8: INVALID key -- any wrong 32-bit value, independent of window
    // position (checked here comfortably in-window, confirming key mismatch
    // dominates window classification per ARCH-SAFE-005).
    // ==========================================================================
    fresh_window();
    clear_capture();
    wait_until_elapsed(MIN_WINDOW + 1);
    dri_write(DFC_ADDR_WDOG_SERVICE, 32'hDEAD_BEEF, code);
    wait_cycles(3);
    dri_read(DFC_ADDR_WDOG_STATUS, rdata, code);
    check_bit("INVALID key (in-window): BAD_SERVICE_KEY genuinely sets", rdata[4], 1'b1);
    check_bit("INVALID key (in-window): SERVICE_ACCEPTED genuinely stays clear", rdata[2], 1'b0);
    check("INVALID key: captured event subtype is 3 (invalid key, C.7 0x0040)",
          {24'h0, captured_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO +: 8]}, 32'd3);
    dri_read(DFC_ADDR_WDOG_ELAPSED_US, rdata, code);
    check("INVALID key: the timer genuinely did NOT restart", (rdata != 32'd0), 32'd1);
    dri_write(DFC_ADDR_WDOG_STATUS, 32'h0000_0010, code);  // tidy

    // ==========================================================================
    // Part 9: EVENT_OVERFLOW clear-field -- the eleventh real instance of
    // this project's own gap class (items 2/7/8/12/20/24/28/32/36/43),
    // proven the same way: withhold the event handshake to force a genuine
    // overflow, then a real host CLEAR write.
    // ==========================================================================
    rtl012_evt_ready = 1'b0;
    dri_read(DFC_ADDR_RTL012_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("event_overflow starts clear before this part's own forced overflow", rdata[0], 1'b0);
    dri_write(DFC_ADDR_WDOG_SERVICE, 32'hDEAD_0001, code);  // event #1 -- captured into the one slot
    wait_cycles(5);
    dri_write(DFC_ADDR_WDOG_SERVICE, 32'hDEAD_0002, code);  // event #2 -- slot still occupied, genuinely dropped
    wait_cycles(5);
    dri_read(DFC_ADDR_RTL012_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("a real, genuine overflow (handshake withheld) set EVENT_OVERFLOW", rdata[0], 1'b1);
    dri_write(DFC_ADDR_RTL012_EVT_OVERFLOW_STATUS, 32'h1, code);
    check("RTL012_EVT_OVERFLOW_STATUS clear write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_RTL012_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("the real host write above actually cleared EVENT_OVERFLOW", rdata[0], 1'b0);
    rtl012_evt_ready = 1'b1;
    wait_cycles(3);
    dri_write(DFC_ADDR_WDOG_STATUS, 32'h0000_0010, code);  // clear BAD_SERVICE_KEY evidence from the forced events, tidy

    // ==========================================================================
    // Part 10: illegal configuration / ready / fault (this module's own
    // generic module_status bits, ARCH-VAL-012 -- deliberately distinct
    // from Part 5's fault_req_o, which Part 6's recovery already cleared).
    // ==========================================================================
    check_bit("status_o.ready set before any illegal configuration",
              rtl012_status[dfc_types_pkg::DFC_RTL012_STATUS__READY_HI], 1'b1);
    check_bit("status_o.fault clear before any illegal configuration",
              rtl012_status[dfc_types_pkg::DFC_RTL012_STATUS__FAULT_HI], 1'b0);

    dri_write(DFC_ADDR_WDOG_WINDOW_OPEN_US, 32'd20, code);  // now >= TIMEOUT_US (10) -- illegal while enabled
    wait_cycles(3);
    check_bit("status_o.fault genuinely asserts on a real illegal (MIN>=MAX) configuration",
              rtl012_status[dfc_types_pkg::DFC_RTL012_STATUS__FAULT_HI], 1'b1);
    check_bit("status_o.ready genuinely deasserts on the same illegal configuration",
              rtl012_status[dfc_types_pkg::DFC_RTL012_STATUS__READY_HI], 1'b0);
    dri_write(DFC_ADDR_WDOG_WINDOW_OPEN_US, MIN_WINDOW, code);  // restore legal
    wait_cycles(3);
    check_bit("status_o.fault genuinely clears once the configuration is fixed",
              rtl012_status[dfc_types_pkg::DFC_RTL012_STATUS__FAULT_HI], 1'b0);
    check_bit("status_o.ready genuinely returns once the configuration is fixed",
              rtl012_status[dfc_types_pkg::DFC_RTL012_STATUS__READY_HI], 1'b1);

    // SAFETY_RESPONSE_MASK reserved bits (Appendix C.8: only bit 0 legal).
    write_wdog_control(1'b1, code);  // baseline (mask=bit0 only) re-affirmed
    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY1, code);
    dri_write(DFC_ADDR_PROTECT_KEY, DFC_PROTECT_KEY2, code);
    dri_write(DFC_ADDR_WDOG_CONTROL, {23'h0, 4'hF /*mask=all 4 bits, 3 reserved set*/,
                                       1'b1, 1'b1, 1'b1, 1'b0, 1'b1}, code);
    wait_cycles(3);
    check_bit({"status_o.fault genuinely asserts when SAFETY_RESPONSE_MASK's reserved bits ",
               "[3:1] are set (only bit 0 is a legal watchdog authorization position)"},
              rtl012_status[dfc_types_pkg::DFC_RTL012_STATUS__FAULT_HI], 1'b1);
    write_wdog_control(1'b1, code);  // restore legal mask
    wait_cycles(3);
    check_bit("status_o.fault genuinely clears once the mask is fixed",
              rtl012_status[dfc_types_pkg::DFC_RTL012_STATUS__FAULT_HI], 1'b0);

    $display("");
    $display("rtl012_integration_tb: %0d checks, %0d failures", checks, errors);
    if (errors == 0) $display("TEST PASSED"); else $display("TEST FAILED");
    $finish;
  end

endmodule
