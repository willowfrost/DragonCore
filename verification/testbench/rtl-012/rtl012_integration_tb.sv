// rtl012_integration_tb.sv -- REAL end-to-end round-trip test: real host
// writes through RTL-001's real address-decode path must actually change
// RTL-012's real behavior, and RTL-012's real internal timer/window state
// must actually reach back to a host register read -- same template and
// purpose as rtl002 through rtl011_integration_tb.sv, targeting the
// RTL-001<->RTL-012 register bus specifically (WDOG_CONTROL/
// WDOG_WINDOW_OPEN_US/WDOG_TIMEOUT_US/WDOG_SERVICE/WDOG_STATUS/
// WDOG_RECOVERY/RTL012_EVT_OVERFLOW_STATUS control forwarding;
// WDOG_STATUS/WDOG_ELAPSED_US/RTL012_EVT_OVERFLOW_STATUS status
// forwarding), generated by reggen.py v4 + tools/reggen/rtl012_field_map.json.
//
// ADDITIONALLY (per this module's own real, distinguishing requirements --
// ARCH-SAFE-005, ARCH-RTL012-001, VP-SAFE-004):
//   - Parts 2-6 exercise every named window boundary as its OWN real test
//     vector, not "typical inputs" coverage: EARLY exactly at MIN_WINDOW-1,
//     legal exactly at MIN_WINDOW, legal at MAX_WINDOW-1, LATE exactly at
//     MAX_WINDOW (the genuine simultaneous timeout/late-service race
//     ARCH-RTL012-001 names explicitly), and missing/timeout with no
//     service at all.
//   - Part 7 is INVALID key -- any wrong 32-bit value, independent of
//     window position.
//   - Part 8 is RECOVERY: an accepted RECOVER while timed out clears the
//     live condition (but NOT the sticky TIMEOUT evidence, nor
//     RESPONSE_PENDING) and requires exactly one subsequent valid
//     in-window service to actually complete recovery; a RECOVER issued
//     while NOT timed out is genuinely rejected (ARCH-VAL-012 "invalid
//     timing").
//   - Part 9 is the eleventh real instance of this project's own
//     EVENT_OVERFLOW-clear-field gap class, proven exactly like items 2/7/
//     8/12/20/24/28/32/36/43 before it.
//   - Part 10 is illegal configuration / ready / fault (ARCH-VAL-012:
//     MIN_WINDOW_US < MAX_WINDOW_US, MAX nonzero, response mask reserved
//     bits) -- this module's own generic module_status bits, distinct from
//     fault_req_o (Part 6 already exercises that, gated by FAULT_ENABLE).
//
// TIMING METHODOLOGY, disclosed and deliberate (same discipline as this
// project's own RTL-007 lessons on precise stimulus timing, OPEN_ISSUES.md
// items 26/27): rather than blindly counting CORE_CLK cycles against a
// free-running, testbench-uncontrolled microsecond tick generator (whose
// exact phase depends on when WDOG_CONTROL.ENABLE's own multi-cycle DRI
// round trip happens to land), this file waits on the DUT's own live
// `elapsed_us_q` counter directly via a hierarchical reference
// (`wait (u_rtl012.elapsed_us_q == target)`) -- legal and standard practice
// for testbench stimulus control, not synthesizable production code. Since
// one microsecond tick is 50 CORE_CLK cycles and a full DRI write/read
// round trip is only ~4 cycles, the target value is guaranteed stable for
// the whole round trip once observed -- no race. Each boundary part starts
// from a fresh, known WDOG_CONTROL.ENABLE disable/re-enable cycle (which
// genuinely resets elapsed_us_q to zero per ARCH-RTL012-001's own
// "reset/disable clears the timer" text), so every `wait_until_elapsed`
// target is reached from a known zero baseline, not accumulated drift.
//
// RTL-002 through RTL-011 are out of this test's scope (same isolation
// choice every prior module-specific integration testbench already makes
// for sibling modules not under test): `timestamp_i` is a free-running
// testbench counter, not RTL-004's real broadcast.
//
// CLOCKING-DISCIPLINE NOTE (same lesson as every other testbench in this
// project): every strobe is held for a full clock and deasserted with a
// #1 settle delay after the sampling edge, never in the same delta.

