  int errors = 0, checks = 0;
  task automatic check(string what, logic [31:0] got, logic [31:0] expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got 0x%08h, expected 0x%08h", what, got, expected);
    end else $display("PASS: %s -- 0x%08h", what, got);
  endtask
  task automatic check_bit(string what, logic got, logic expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got %b, expected %b", what, got, expected);
    end else $display("PASS: %s", what);
  endtask

  task automatic dri_write(input logic [31:0] addr, input logic [31:0] data,
                            output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_wdata_i = data;
    dri_req_wstrb_i = 4'hF;
    dri_req_write_i = 1'b1;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    code = dri_rsp_code_o;
  endtask

  task automatic dri_read(input logic [31:0] addr, output logic [31:0] data,
                           output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_write_i = 1'b0;
    dri_req_wstrb_i = 4'h0;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    data = dri_rsp_rdata_o;
    code = dri_rsp_code_o;
  endtask

  // Produces exactly one rising edge on engine_i, then holds low for the
  // remainder of `gap_cycles` CORE_CLK cycles -- same real, hard-won shape
  // as dfc_rtl007.sv's own testbench task (OPEN_ISSUES.md item 26): the
  // edge fires on the FIRST posedge after this task is called, and
  // `gap_cycles` controls the spacing to the NEXT edge. Only a back-to-back
  // PAIR of calls with the same gap_cycles value gives an exact, known
  // period for the SECOND call's edge.
  task automatic engine_pulse(int gap_cycles);
    engine_i = 1'b1;
    @(posedge core_clk_i); #1;
    engine_i = 1'b0;
    repeat (gap_cycles - 1) @(posedge core_clk_i);
    #1;
  endtask

  // Waits exactly `pre_cycles` CORE_CLK cycles, THEN produces one rising
  // edge on engine_i, then returns immediately (no trailing wait) -- see
  // dfc_rtl007.sv's own testbench task (rotor_edge_after) for the full
  // rationale; applied here from the start per OPEN_ISSUES.md item 26.
  task automatic engine_edge_after(int pre_cycles);
    if (pre_cycles > 0) repeat (pre_cycles) @(posedge core_clk_i);
    engine_i = 1'b1;
    @(posedge core_clk_i); #1;
    engine_i = 1'b0;
    #1;
  endtask

  // Same shape, on rotor_i -- Part 11's independence check only.
  task automatic rotor_pulse(int gap_cycles);
    rotor_i = 1'b1;
    @(posedge core_clk_i); #1;
    rotor_i = 1'b0;
    repeat (gap_cycles - 1) @(posedge core_clk_i);
    #1;
  endtask

  // Waits long enough for the real bit-serial divider (64-cycle MEAS_RUN,
  // dfc_rtl008.sv's own header) to genuinely finish and APPLY its result --
  // a generous margin, not a race.
  task automatic wait_for_divide();
    repeat (100) @(posedge core_clk_i);
    #1;
  endtask

  // Same wait, but also captures whether irq_req_o was asserted at any
  // point during the window -- irq_req_o is a real, genuinely registered
  // ONE-CYCLE pulse, not a held level; a plain post-hoc sample 100 cycles
  // later would reliably miss it.
  task automatic wait_for_divide_capture_irq(output logic seen);
    seen = 1'b0;
    repeat (100) begin
      @(posedge core_clk_i);
      if (rtl008_irq_req) seen = 1'b1;
    end
    #1;
  endtask

