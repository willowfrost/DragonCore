// rtl008_integration_tb.sv -- REAL end-to-end round-trip test: a host-style
// register write through RTL-001's real address-decode path must actually
// change RTL-008's real behavior (thresholds/PPR/timeout/edge filter), and
// a real simulated pulse train on `engine_i` must actually produce a real,
// correct RPM measurement readable via ENGINE_RPM, plus real threshold/
// timeout/saturation fault detection. Same template and purpose as
// rtl002/003/004/005/006/007_integration_tb.sv, targeting the
// RTL-001<->RTL-008 register bus specifically (ENGINE_CONTROL/
// ENGINE_THRESH_LOW/ENGINE_THRESH_HIGH/ENGINE_PULSES_PER_REV/
// ENGINE_TIMEOUT_US/ENGINE_EDGE_FILTER/ENGINE_HYSTERESIS/
// RTL008_EVT_OVERFLOW_STATUS control forwarding; ENGINE_STATUS/ENGINE_RPM/
// ENGINE_PERIOD_TICKS/RTL008_EVT_OVERFLOW_STATUS status forwarding),
// generated by reggen.py v4 + tools/reggen/rtl008_field_map.json.
//
// ADDITIONALLY (per this module's own real, distinguishing requirement):
// `engine_i` is driven here as a genuinely simulated external tachometer
// pulse train, not a register write -- real rising edges spaced an exact,
// known number of CORE_CLK cycles apart must reach a real, correct
// ENGINE_RPM value through RTL-008's own real bit-serial divider. Every
// pulse gap chosen below was picked so RPM = 3,000,000,000 /
// (period_ticks * PPR) divides EXACTLY (no rounding), keeping every check
// deterministic. Thresholds are scaled to the engine's own real 0-20000
// range (ARCH-VAL-008), not copied from RTL-007's 0-1000 range.
//
// RTL-002 through RTL-006 are out of this test's scope (same isolation
// choice every prior module-specific integration testbench already makes
// for sibling modules not under test): `module_enable_i` is driven
// directly by this testbench as a plain constant, and `timestamp_i` is a
// free-running testbench counter, not RTL-004's real broadcast.
//
// PER RTL-008_RevA.md SS6 ("directly testable... a cheap, high-value
// regression case worth automating early"): Part 11 below instantiates a
// real dfc_rtl007 ALONGSIDE dfc_rtl008 and drives `rotor_i`/`engine_i`
// with genuinely different, simultaneous edge patterns, confirming neither
// module's real internal state reflects the other's input -- the concrete,
// automated proof of ARCH-RTL008-001's "separate state prevents
// rotor/engine coupling" requirement, not merely an assertion of it.
//
// CLOCKING-DISCIPLINE NOTE (same lesson as every other testbench in this
// project): every strobe is held for a full clock and deasserted with a
// #1 settle delay after the sampling edge, never in the same delta. Every
// engine_i pulse task below waits a generous margin (100 CORE_CLK cycles)
// after the pulse that completes a measurement before reading the result,
// comfortably longer than the real 64-cycle divider latency
// (dfc_rtl008.sv's own MEAS_RUN state) -- not a race against an exact
// cycle count.

