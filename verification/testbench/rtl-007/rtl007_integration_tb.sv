// rtl007_integration_tb.sv -- REAL end-to-end round-trip test: a host-style
// register write through RTL-001's real address-decode path must actually
// change RTL-007's real behavior (thresholds/PPR/timeout/edge filter), and
// a real simulated pulse train on `rotor_i` must actually produce a real,
// correct RPM measurement readable via ROTOR_RPM, plus real threshold/
// timeout/saturation fault detection. Same template and purpose as
// rtl002/003/004/005/006_integration_tb.sv, targeting the RTL-001<->RTL-007
// register bus specifically (ROTOR_CONTROL/ROTOR_THRESH_LOW/
// ROTOR_THRESH_HIGH/ROTOR_PULSES_PER_REV/ROTOR_TIMEOUT_US/
// ROTOR_EDGE_FILTER/ROTOR_HYSTERESIS/RTL007_EVT_OVERFLOW_STATUS control
// forwarding; ROTOR_STATUS/ROTOR_RPM/ROTOR_PERIOD_TICKS/
// RTL007_EVT_OVERFLOW_STATUS status forwarding), generated by reggen.py v4
// + tools/reggen/rtl007_field_map.json.
//
// ADDITIONALLY (per this module's own real, distinguishing requirement):
// `rotor_i` is driven here as a genuinely simulated external tachometer
// pulse train, not a register write -- real rising edges spaced an exact,
// known number of CORE_CLK cycles apart must reach a real, correct
// ROTOR_RPM value through RTL-007's own real bit-serial divider (see
// dfc_rtl007.sv's own header for why a multi-cycle divider is used instead
// of a combinational `/`), not a fabricated one. Every pulse gap chosen
// below was picked so RPM = 3,000,000,000 / (period_ticks * PPR) divides
// EXACTLY (no rounding), keeping every check deterministic.
//
// RTL-002 through RTL-006 are out of this test's scope (same isolation
// choice every prior module-specific integration testbench already makes
// for sibling modules not under test): `module_enable_i` is driven
// directly by this testbench as a plain constant, and `timestamp_i` is a
// free-running testbench counter, not RTL-004's real broadcast.
//
// CLOCKING-DISCIPLINE NOTE (same lesson as every other testbench in this
// project): every strobe is held for a full clock and deasserted with a
// #1 settle delay after the sampling edge, never in the same delta. Every
// rotor_i pulse task below waits a generous margin (100 CORE_CLK cycles)
// after the pulse that completes a measurement before reading the result,
// comfortably longer than the real 64-cycle divider latency
// (dfc_rtl007.sv's own MEAS_RUN state) -- not a race against an exact
// cycle count.

