  int errors = 0, checks = 0;
  task automatic check(string what, logic [31:0] got, logic [31:0] expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got 0x%08h, expected 0x%08h", what, got, expected);
    end else $display("PASS: %s -- 0x%08h", what, got);
  endtask
  task automatic check_bit(string what, logic got, logic expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got %b, expected %b", what, got, expected);
    end else $display("PASS: %s", what);
  endtask

  task automatic dri_write(input logic [31:0] addr, input logic [31:0] data,
                            output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_wdata_i = data;
    dri_req_wstrb_i = 4'hF;
    dri_req_write_i = 1'b1;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    code = dri_rsp_code_o;
  endtask

  task automatic dri_read(input logic [31:0] addr, output logic [31:0] data,
                           output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_write_i = 1'b0;
    dri_req_wstrb_i = 4'h0;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    data = dri_rsp_rdata_o;
    code = dri_rsp_code_o;
  endtask

  // Produces exactly one rising edge on rotor_i, then holds low for the
  // remainder of `gap_cycles` CORE_CLK cycles -- calling this back-to-back
  // with the same gap_cycles value produces rising edges spaced exactly
  // gap_cycles CORE_CLK cycles apart (the 2-flop synchronizer adds a
  // constant latency to every edge equally, so the MEASURED spacing
  // dfc_rtl007.sv's own cycles_since_accepted_q captures is identical to
  // the raw spacing driven here). IMPORTANT, real testbench-side subtlety
  // found during this file's own bring-up: the edge itself fires on the
  // FIRST posedge after this task is called -- `gap_cycles` controls the
  // spacing to the NEXT edge (i.e. it's forward-looking), not the spacing
  // FROM whatever edge preceded this call. Calling this only ONCE after
  // other, unrelated code does NOT produce a known, exact period (the
  // real period is however long it's been since the true previous edge,
  // which depends on unrelated intervening DRI-transaction timing) --
  // only a back-to-back PAIR of calls with the same gap_cycles value gives
  // an exact, known period for the SECOND call's edge. Use
  // rotor_edge_after (below) instead when explicit, one-off control over
  // the gap from whatever edge came before is actually what's needed.
  task automatic rotor_pulse(int gap_cycles);
    rotor_i = 1'b1;
    @(posedge core_clk_i); #1;
    rotor_i = 1'b0;
    repeat (gap_cycles - 1) @(posedge core_clk_i);
    #1;
  endtask

  // Waits exactly `pre_cycles` CORE_CLK cycles, THEN produces one rising
  // edge on rotor_i, then returns immediately (no trailing wait) -- unlike
  // rotor_pulse (tuned for back-to-back exact-period pairs, see its own
  // header), this gives full, explicit, one-off control over the gap from
  // whatever edge preceded this call, which is what Parts 7-9 below
  // actually need (a real, correctly-directional LOW/HIGH crossing or a
  // real, distinct fresh commit) without needing exact numeric precision.
  task automatic rotor_edge_after(int pre_cycles);
    if (pre_cycles > 0) repeat (pre_cycles) @(posedge core_clk_i);
    rotor_i = 1'b1;
    @(posedge core_clk_i); #1;
    rotor_i = 1'b0;
    #1;
  endtask

  // Waits long enough for the real bit-serial divider (64-cycle MEAS_RUN,
  // dfc_rtl007.sv's own header) to genuinely finish and APPLY its result --
  // a generous margin, not a race.
  task automatic wait_for_divide();
    repeat (100) @(posedge core_clk_i);
    #1;
  endtask

  // Same wait, but also captures whether irq_req_o was asserted at any
  // point during the window -- irq_req_o is a real, genuinely registered
  // ONE-CYCLE pulse (fires exactly on the cycle dfc_rtl007.sv's own
  // MEAS_APPLY state commits), not a held level like RTL-006's GPIO irq
  // sources; a plain post-hoc sample 100 cycles later would reliably miss
  // it. This is a real, disclosed testbench-side timing subtlety, not a
  // DUT limitation.
  task automatic wait_for_divide_capture_irq(output logic seen);
    seen = 1'b0;
    repeat (100) begin
      @(posedge core_clk_i);
      if (rtl007_irq_req) seen = 1'b1;
    end
    #1;
  endtask

  logic [2:0]  code;
  logic [31:0] rdata;

  initial begin
    dri_req_valid_i = 1'b0;
    dri_req_write_i = 1'b0;
    dri_req_addr_i  = '0;
    dri_req_wdata_i = '0;
    dri_req_wstrb_i = '0;

    core_rst_n_i = 1'b0;
    repeat (4) @(posedge core_clk_i);
    core_rst_n_i = 1'b1;
    @(posedge core_clk_i); #1;

    // ------------------------------------------------------------------
    // Part 1 (CONTROL direction, RW forwarding): a real host write to
    // ROTOR_CONTROL/ROTOR_PULSES_PER_REV/ROTOR_THRESH_LOW/
    // ROTOR_THRESH_HIGH/ROTOR_HYSTERESIS via RTL-001's real DRI path must
    // actually reach RTL-007's real control_i -- the exact connection that
    // would be disconnected without reggen.py v4 + rtl007_field_map.json.
    // PPR=2000, THRESH_LOW=400, THRESH_HIGH=600, HYSTERESIS=50 chosen so
    // every RPM value used below divides exactly (no rounding ambiguity).
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_ROTOR_CONTROL, 32'h0000_0002, code);  // ENABLE=0, RISING_EDGE=1
    check("ROTOR_CONTROL write accepted (RSP_OK)", {29'h0, code}, 32'h0);

    dri_write(DFC_ADDR_ROTOR_PULSES_PER_REV, 32'd2000, code);
    check("ROTOR_PULSES_PER_REV write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    dri_read(DFC_ADDR_ROTOR_PULSES_PER_REV, rdata, code);
    check("ROTOR_PULSES_PER_REV reads back the real value just written", rdata, 32'd2000);

    dri_write(DFC_ADDR_ROTOR_THRESH_LOW, 32'd400, code);
    check("ROTOR_THRESH_LOW write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    dri_write(DFC_ADDR_ROTOR_THRESH_HIGH, 32'd600, code);
    check("ROTOR_THRESH_HIGH write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    dri_write(DFC_ADDR_ROTOR_HYSTERESIS, 32'd50, code);
    check("ROTOR_HYSTERESIS write accepted (RSP_OK)", {29'h0, code}, 32'h0);

    // Real ENABLE=1 write -- must actually reach control_i and start real
    // measurement.
    dri_write(DFC_ADDR_ROTOR_CONTROL, 32'h0000_0003, code);  // ENABLE=1, RISING_EDGE=1
    check("ROTOR_CONTROL (ENABLE=1) write accepted (RSP_OK)", {29'h0, code}, 32'h0);

    // ------------------------------------------------------------------
    // Part 2 (STATUS direction, real simulated pulse train -> real host
    // read): two real rising edges 3000 CORE_CLK cycles apart must
    // genuinely produce RPM = 3,000,000,000 / (3000 * 2000) = 500 through
    // RTL-007's real bit-serial divider.
    // ------------------------------------------------------------------
    rotor_pulse(3000);  // 1st edge: no period measurable yet
    rotor_pulse(3000);  // 2nd edge: real period_ticks = 3000 committed
    wait_for_divide();

    dri_read(DFC_ADDR_ROTOR_PERIOD_TICKS, rdata, code);
    check("ROTOR_PERIOD_TICKS genuinely reflects the real 3000-cycle gap", rdata, 32'd3000);
    dri_read(DFC_ADDR_ROTOR_RPM, rdata, code);
    check("ROTOR_RPM genuinely computed via the real divider (500)", rdata, 32'd500);
    dri_read(DFC_ADDR_ROTOR_STATUS, rdata, code);
    check_bit("ROTOR_STATUS.VALID genuinely set after a real committed measurement",
              rdata[0], 1'b1);
    check_bit("ROTOR_STATUS.LOW genuinely clear (500 is within [400,600])", rdata[1], 1'b0);
    check_bit("ROTOR_STATUS.HIGH genuinely clear (500 is within [400,600])", rdata[2], 1'b0);
    check_bit("ROTOR_STATUS.UPDATED genuinely set by the real commit", rdata[5], 1'b1);

    dri_write(DFC_ADDR_ROTOR_STATUS, 32'h0000_0020, code);  // W1C clear UPDATED
    @(posedge core_clk_i); #1;
    dri_read(DFC_ADDR_ROTOR_STATUS, rdata, code);
    check_bit("the real host clear write above actually cleared ROTOR_STATUS.UPDATED",
              rdata[5], 1'b0);

    // ------------------------------------------------------------------
    // Part 3 (real LOW threshold enter/exit, ARCH-MON-005): a real 5000-
    // cycle gap gives RPM = 3e9/(5000*2000) = 300 (< THRESH_LOW=400) --
    // LOW must genuinely set. Returning to the 3000-cycle gap (RPM=500 >=
    // LOW+HYST=450) must genuinely clear it. Every gap below is driven as
    // a back-to-back PAIR (no DRI transaction in between the two pulses,
    // only the 2nd pulse's own return delay) -- the 1st pulse of each pair
    // may measure a stale, DRI-overhead-inflated period (harmless: LOW/
    // HIGH are hysteretic latches whose enter/exit test re-evaluates fresh
    // on every commit, so whatever the 1st pulse's commit leaves behind is
    // always overwritten correctly by the 2nd, EXACT commit this test
    // actually inspects) -- this is what keeps every RPM value below
    // exact despite the real DRI reads/writes between test steps.
    // ------------------------------------------------------------------
    rotor_pulse(5000);
    rotor_pulse(5000);
    wait_for_divide();
    dri_read(DFC_ADDR_ROTOR_RPM, rdata, code);
    check("ROTOR_RPM genuinely drops to 300 for the real 5000-cycle gap", rdata, 32'd300);
    dri_read(DFC_ADDR_ROTOR_STATUS, rdata, code);
    check_bit("ROTOR_STATUS.LOW genuinely sets when RPM < THRESH_LOW", rdata[1], 1'b1);

    rotor_pulse(3000);
    rotor_pulse(3000);
    wait_for_divide();
    dri_read(DFC_ADDR_ROTOR_STATUS, rdata, code);
    check_bit({"ROTOR_STATUS.LOW genuinely clears once RPM (500) reaches ",
               "THRESH_LOW+HYST (450)"}, rdata[1], 1'b0);

    // ------------------------------------------------------------------
    // Part 4 (real HIGH threshold enter, ARCH-MON-005): a real 1500-cycle
    // gap gives RPM = 3e9/(1500*2000) = 1000 (> THRESH_HIGH=600). Same
    // back-to-back pair discipline as Part 3.
    // ------------------------------------------------------------------
    rotor_pulse(1500);
    rotor_pulse(1500);
    wait_for_divide();
    dri_read(DFC_ADDR_ROTOR_RPM, rdata, code);
    check("ROTOR_RPM genuinely reaches 1000 for the real 1500-cycle gap", rdata, 32'd1000);
    dri_read(DFC_ADDR_ROTOR_STATUS, rdata, code);
    check_bit("ROTOR_STATUS.HIGH genuinely sets when RPM > THRESH_HIGH", rdata[2], 1'b1);

    rotor_pulse(3000);
    rotor_pulse(3000);
    wait_for_divide();
    dri_read(DFC_ADDR_ROTOR_STATUS, rdata, code);
    check_bit("ROTOR_STATUS.HIGH genuinely clears back at RPM=500", rdata[2], 1'b0);

    // ------------------------------------------------------------------
    // Part 5 (real saturation/RANGE_ERROR, ARCH-MON-003's own "16-bit
    // result saturates" text): PPR temporarily dropped to 1 -- the same
    // real 1500-cycle gap now computes RPM = 3e9/1500 = 2,000,000, far
    // beyond 0xFFFF. Must genuinely saturate to 0xFFFF, not wrap, and set
    // RANGE_ERROR.
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_ROTOR_PULSES_PER_REV, 32'd1, code);
    rotor_pulse(1500);
    rotor_pulse(1500);
    wait_for_divide();
    dri_read(DFC_ADDR_ROTOR_RPM, rdata, code);
    check("ROTOR_RPM genuinely saturates at 0xFFFF, never wraps", rdata, 32'h0000_FFFF);
    dri_read(DFC_ADDR_ROTOR_STATUS, rdata, code);
    check_bit("ROTOR_STATUS.RANGE_ERROR genuinely set by the real saturation event",
              rdata[4], 1'b1);

    dri_write(DFC_ADDR_ROTOR_STATUS, 32'h0000_0010, code);  // W1C clear RANGE_ERROR
    @(posedge core_clk_i); #1;
    dri_read(DFC_ADDR_ROTOR_STATUS, rdata, code);
    check_bit("the real host clear write above actually cleared RANGE_ERROR", rdata[4], 1'b0);

    dri_write(DFC_ADDR_ROTOR_PULSES_PER_REV, 32'd2000, code);  // restore
    rotor_pulse(3000);
    rotor_pulse(3000);
    wait_for_divide();

    // ------------------------------------------------------------------
    // Part 6 (real no-edge TIMEOUT, ARCH-MON-005): TIMEOUT_US set to a
    // real, small, nonzero value (100 us = 5000 CORE_CLK cycles at the
    // nominal 50 MHz); genuinely withholding any further rotor_i edge past
    // that real elapsed time must set TIMEOUT and clear VALID. The wait
    // below is well past the exact 5000-cycle mark (a generous margin over
    // whatever DRI-transaction overhead already elapsed since the last
    // real edge above), not a race against an exact cycle count.
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_ROTOR_TIMEOUT_US, 32'd100, code);
    check("ROTOR_TIMEOUT_US write accepted (RSP_OK)", {29'h0, code}, 32'h0);

    repeat (6000) @(posedge core_clk_i); #1;  // real 100us + generous margin, no edges sent

    dri_read(DFC_ADDR_ROTOR_STATUS, rdata, code);
    check_bit("ROTOR_STATUS.TIMEOUT genuinely sets after the real configured elapsed time",
              rdata[3], 1'b1);
    check_bit("ROTOR_STATUS.VALID genuinely clears once TIMEOUT fires", rdata[0], 1'b0);

    dri_write(DFC_ADDR_ROTOR_STATUS, 32'h0000_0008, code);  // W1C clear TIMEOUT
    @(posedge core_clk_i); #1;
    dri_read(DFC_ADDR_ROTOR_STATUS, rdata, code);
    check_bit("the real host clear write above actually cleared ROTOR_STATUS.TIMEOUT",
              rdata[3], 1'b0);

    dri_write(DFC_ADDR_ROTOR_TIMEOUT_US, 32'd100_000, code);  // restore default
    rotor_pulse(3000);
    rotor_pulse(3000);
    wait_for_divide();

    // ------------------------------------------------------------------
    // Part 7 (real LOW-threshold event generation, event ID 0x0030, source
    // index 6, F.3 condition-mask bit 0): withholding evt_ready keeps the
    // real one-deep pending slot genuinely observable. rotor_edge_after
    // (not rotor_pulse -- see that task's own header for why a back-to-back
    // PAIR is the wrong tool here) is used to add a real, explicit,
    // known-minimum 5000-cycle gap on top of whatever the baseline entering
    // this Part already left behind, guaranteeing a real period well past
    // the 3750-cycle LOW threshold (THRESH_LOW=400, PPR=2000) regardless of
    // the small, real DRI-write overhead already elapsed -- the RPM check
    // is therefore a real inequality (< THRESH_LOW), not an exact value;
    // EVENT_ID/SOURCE_ID/subtype are still checked exactly, since none of
    // those depend on the precise RPM number. A back-to-back rotor_pulse
    // PAIR would be the wrong tool regardless of the timing subtlety: the
    // 1st pulse of such a pair would itself be the genuine LOW-crossing
    // edge (the baseline entering this Part is RPM=500, not low) and would
    // occupy the one-deep slot before evt_ready is ever withheld, leaving
    // nothing observable for the 2nd pulse (which wouldn't re-trigger "low
    // enter" anyway, already being in the low state).
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_ROTOR_CONTROL, 32'h0000_0007, code);  // ENABLE|RISING_EDGE|EVENT_ENABLE
    tb_event_condition_enable = 64'h0000_0000_0000_0001;  // F.3 bit 0 = low

    rtl007_evt_ready = 1'b0;
    rotor_edge_after(5000);  // real LOW-enter commit (RPM well under 400)
    wait_for_divide();

    check_bit("a real, genuinely LOW-crossing measurement asserted evt_valid_o",
              rtl007_evt_valid, 1'b1);
    check({"the real event record's EVENT_ID/SOURCE_ID genuinely match RTL-007's ",
           "own event (0x0030, source index 6) -- not a fabricated value"},
          {rtl007_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__SOURCE_ID_HI:dfc_types_pkg::DFC_EVENT_RECORD__SOURCE_ID_LO],
           rtl007_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_ID_HI:dfc_types_pkg::DFC_EVENT_RECORD__EVENT_ID_LO]},
          32'h0006_0030);
    check_bit("the real event record's event_data genuinely shows subtype=0 (low)",
              (rtl007_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO+16 +: 8] == 8'd0),
              1'b1);
    check_bit("the real event record's event_data RPM field is genuinely under THRESH_LOW (400)",
              (rtl007_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO +: 16] < 16'd400),
              1'b1);

    rtl007_evt_ready = 1'b1;
    @(posedge core_clk_i); #1;
    tb_event_condition_enable = 64'h0;

    // ------------------------------------------------------------------
    // Part 8 (real HIGH-threshold irq generation, F.3 condition-mask
    // bit 1). irq_req_o is a real, genuinely registered ONE-CYCLE pulse
    // (see wait_for_divide_capture_irq's own header) -- captured over the
    // real divider-latency window, not sampled once after an arbitrary
    // delay that would reliably miss it. rotor_edge_after (not
    // rotor_pulse -- see that task's own header) with a deliberately SHORT
    // pre-wait gives a short real period relative to Part 7's own
    // LOW-crossing edge -- whether this genuinely saturates (as the
    // similarly-short Part 5 gap did) or merely reads a large-but-
    // unsaturated value doesn't matter for this check: either outcome is
    // unambiguously > THRESH_HIGH (600), which is all a real HIGH-enter
    // transition needs.
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_ROTOR_CONTROL, 32'h0000_000B, code);  // ENABLE|RISING_EDGE|IRQ_ENABLE
    tb_irq_condition_enable = 64'h0000_0000_0000_0002;  // F.3 bit 1 = high

    begin
      logic irq_seen;
      rotor_edge_after(50);  // real HIGH-enter commit (RPM well over 600)
      wait_for_divide_capture_irq(irq_seen);
      check_bit("a real, genuinely HIGH-crossing measurement asserted RTL-007's real irq_req_o",
                irq_seen, 1'b1);
    end

    tb_irq_condition_enable = 64'h0;
    rotor_edge_after(3000);
    check_bit("irq_req_o genuinely stays deasserted once the condition mask is cleared",
              rtl007_irq_req, 1'b0);

    // ------------------------------------------------------------------
    // Part 9 (RTL007_EVT_OVERFLOW_STATUS -- REAL HOST READ, closing the
    // still-open RTL-002/003/004 readback gap from the start, same
    // discipline rtl006_field_map.json already established -- this is a
    // genuine host REGISTER READ, not a white-box inspection of status_o
    // directly).
    // ------------------------------------------------------------------
    dri_write(DFC_ADDR_ROTOR_CONTROL, 32'h0000_0007, code);  // ENABLE|RISING_EDGE|EVENT_ENABLE
    tb_event_condition_enable = 64'h0000_0000_0000_0008;  // F.3 bit 3 = updated

    dri_read(DFC_ADDR_RTL007_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit({"RTL007_EVT_OVERFLOW_STATUS.EVENT_OVERFLOW reads clear via a real ",
               "host READ before any overflow is forced"}, rdata[0], 1'b0);

    rtl007_evt_ready = 1'b0;
    rotor_pulse(3000);  // 1st UPDATED candidate occupies the one-deep slot
    wait_for_divide();
    rotor_pulse(3000);  // 2nd UPDATED candidate lands on the still-occupied slot
    wait_for_divide();

    dri_read(DFC_ADDR_RTL007_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit({"a real, genuine overflow condition (two real commits, evt_ready ",
               "withheld) is genuinely readable via a real host REGISTER READ of ",
               "RTL007_EVT_OVERFLOW_STATUS.EVENT_OVERFLOW"}, rdata[0], 1'b1);
    check_bit("RTL007_EVT_OVERFLOW_STATUS.DROP_COUNT is genuinely nonzero via the same real host read",
              (rdata[23:8] != 16'h0), 1'b1);

    dri_write(DFC_ADDR_RTL007_EVT_OVERFLOW_STATUS, 32'h0000_0001, code);  // W1C clear
    check("RTL007_EVT_OVERFLOW_STATUS clear write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;
    dri_read(DFC_ADDR_RTL007_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit({"the real host clear write above actually cleared EVENT_OVERFLOW, ",
               "confirmed via a real host READ, not white-box inspection"},
              rdata[0], 1'b0);

    rtl007_evt_ready = 1'b1;
    tb_event_condition_enable = 64'h0;
    @(posedge core_clk_i); #1;

    // ------------------------------------------------------------------
    // Part 10 (real illegal configuration -> fault, ARCH-VAL-007): RTL-001
    // has no per-field range validation yet (OPEN_ISSUES.md item 4), so a
    // genuinely illegal THRESH_LOW > THRESH_HIGH write reaches control_i
    // and RTL-007 must defend itself.
    // ------------------------------------------------------------------
    check_bit("RTL-007 reports ready (no illegal configuration yet)",
              rtl007_status[dfc_types_pkg::DFC_RTL007_STATUS__READY_HI], 1'b1);
    check_bit("RTL-007 reports no fault before any illegal configuration",
              rtl007_status[dfc_types_pkg::DFC_RTL007_STATUS__FAULT_HI], 1'b0);

    dri_write(DFC_ADDR_ROTOR_THRESH_LOW, 32'd700, code);  // > THRESH_HIGH (600), illegal
    @(posedge core_clk_i); #1;

    check_bit({"a genuinely illegal configuration (LOW=700 > HIGH=600, RTL-001 ",
               "does not yet reject it) was detected by RTL-007 itself -- fault set"},
              rtl007_status[dfc_types_pkg::DFC_RTL007_STATUS__FAULT_HI], 1'b1);
    check_bit("RTL-007 correctly reports not-ready while illegal configuration persists",
              rtl007_status[dfc_types_pkg::DFC_RTL007_STATUS__READY_HI], 1'b0);

    dri_write(DFC_ADDR_ROTOR_THRESH_LOW, 32'd400, code);  // restore legal value
    @(posedge core_clk_i); #1;

    check_bit("RTL-007 genuinely returns to ready/no-fault once the illegal value clears",
              rtl007_status[dfc_types_pkg::DFC_RTL007_STATUS__READY_HI], 1'b1);
    check_bit("fault genuinely clears alongside it",
              rtl007_status[dfc_types_pkg::DFC_RTL007_STATUS__FAULT_HI], 1'b0);

    $display("");
    $display("rtl007_integration_tb: %0d checks, %0d failures", checks, errors);
    if (errors != 0) begin
      $display("TEST FAILED");
      $finish(1);
    end else begin
      $display("TEST PASSED");
      $finish(0);
    end
  end

endmodule : rtl007_integration_tb
