// rtl004_integration_tb.sv -- REAL end-to-end round-trip test: a host-style
// register write through RTL-001's real address-decode path must actually
// change RTL-004's real behavior, and RTL-004's real internal state must
// actually reach back to a host register read through RTL-001. Same
// template and purpose as rtl002_integration_tb.sv/rtl003_integration_tb.sv,
// targeting the RTL-001<->RTL-004 register bus specifically (TIME_CONTROL/
// TIME_SNAPSHOT/TIME_SYNC_OFFSET_LO/TIME_SYNC_OFFSET_HI/TIME_SYNC_COMMIT
// control forwarding; TIME_STATUS/TIME_RAW_LO/TIME_RAW_HI/TIME_SYNC_STATUS/
// RTL004_EVT_OVERFLOW_STATUS/TIME_ACTIVE_OFFSET_LO/TIME_ACTIVE_OFFSET_HI
// status forwarding), generated by reggen.py v4 + tools/reggen/rtl004_field_map.json.
//
// ADDITIONALLY (per this module's own real, distinguishing requirement):
// RTL-004 is the sole origin of the raw timestamp every other module
// broadcasts-consumes. This file also instantiates a real RTL-002 alongside
// RTL-001/RTL-004 specifically to prove that broadcast actually reaches a
// real consumer -- RTL-002's own real evt_record_o.TIMESTAMP field (filled
// from its timestamp_i port) must genuinely be nonzero and track RTL-004's
// real, live raw counter, closing the loop that was previously a hard-tied
// 64'h0 stub in dfc_rtl024.sv with an explicit "RTL-004 does not exist yet"
// comment. RTL-003 is out of this test's scope (same isolation choice
// rtl002_integration_tb.sv/rtl003_integration_tb.sv already make for the
// sibling module not under test) -- tied to a disclosed stub.
//
// CLOCKING-DISCIPLINE NOTE (same lesson as every other testbench in this
// project): every strobe is held for a full clock and deasserted with a
// #1 settle delay after the sampling edge, never in the same delta.

`timescale 1ns/1ps

module rtl004_integration_tb;

  import dfc_constants_pkg::*;
  import dfc_registers_pkg::*;

  logic core_clk_i = 0;
  logic core_rst_n_i;

  logic        dri_req_valid_i, dri_req_ready_o, dri_req_write_i;
  logic [31:0] dri_req_addr_i, dri_req_wdata_i;
  logic [3:0]  dri_req_wstrb_i;
  logic        dri_rsp_valid_o, dri_rsp_ready_i = 1'b1;
  logic [31:0] dri_rsp_rdata_o;
  logic [2:0]  dri_rsp_code_o;
  logic        dbg_regbank_write_en_o;

  logic [dfc_types_pkg::DFC_RTL004_CONTROL_WIDTH-1:0] rtl004_control;
  logic [dfc_types_pkg::DFC_RTL004_STATUS_WIDTH-1:0]  rtl004_status;
  logic [dfc_types_pkg::DFC_RTL002_CONTROL_WIDTH-1:0] rtl002_control;
  logic [dfc_types_pkg::DFC_RTL002_STATUS_WIDTH-1:0]  rtl002_status;
  // RTL-003 is not part of this test's scope -- tied to a disclosed stub,
  // same isolation choice already made in rtl002_integration_tb.sv/
  // rtl003_integration_tb.sv for whichever sibling module isn't under test.
  logic [dfc_types_pkg::DFC_RTL003_CONTROL_WIDTH-1:0] rtl003_control_unused;
  logic [dfc_types_pkg::DFC_RTL003_STATUS_WIDTH-1:0]  rtl003_status_stub = '0;
  // RTL-005 is likewise out of this test's scope -- added during RTL-005's
  // own integration session, same disclosed-stub pattern as RTL-003 above.
  logic [dfc_types_pkg::DFC_RTL005_CONTROL_WIDTH-1:0] rtl005_control_unused;
  logic [dfc_types_pkg::DFC_RTL005_STATUS_WIDTH-1:0]  rtl005_status_stub = '0;
  // RTL-006 likewise out of this test's scope -- same disclosed-stub
  // pattern, added during RTL-006's own integration session.
  logic [dfc_types_pkg::DFC_RTL006_CONTROL_WIDTH-1:0] rtl006_control_unused;
  logic [dfc_types_pkg::DFC_RTL006_STATUS_WIDTH-1:0]  rtl006_status_stub = '0;
  // RTL-007 likewise out of this test's scope -- same disclosed-stub
  // pattern, added during RTL-007's own integration session.
  logic [dfc_types_pkg::DFC_RTL007_CONTROL_WIDTH-1:0] rtl007_control_unused;
  logic [dfc_types_pkg::DFC_RTL007_STATUS_WIDTH-1:0]  rtl007_status_stub = '0;
  // RTL-008 likewise out of this test's scope -- same disclosed-stub
  // pattern, added during RTL-008's own integration session.
  logic [dfc_types_pkg::DFC_RTL008_CONTROL_WIDTH-1:0] rtl008_control_unused;
  logic [dfc_types_pkg::DFC_RTL008_STATUS_WIDTH-1:0]  rtl008_status_stub = '0;
  // RTL-009 likewise out of this test's scope -- same disclosed-stub
  // pattern, added during RTL-009's own integration session.
  logic [dfc_types_pkg::DFC_RTL009_CONTROL_WIDTH-1:0] rtl009_control_unused;
  logic [dfc_types_pkg::DFC_RTL009_STATUS_WIDTH-1:0]  rtl009_status_stub = '0;

  // Real RTL-004 timestamp broadcast -- the actual connection under test in
  // Part 5 below.
  logic [63:0] rtl004_timestamp;

  // Real signals (not bare literal ties) so Part 4 can withhold RTL-004's
  // own event handshake to force a genuine overflow condition, and Part 5
  // can withhold RTL-002's event handshake to hold a real event record
  // steady for inspection. rtl002_evt_ready starts HIGH deliberately: RTL-002
  // emits a real, early state-transition event (STARTUP->NORMAL) almost
  // immediately after reset release, well before RTL-004's first real tick
  // -- left free-running (auto-acknowledged) until immediately before Part 5
  // so that unrelated early event doesn't occupy the one-deep pending slot
  // ahead of the event this test actually means to inspect.
  logic rtl004_evt_ready = 1'b1;
  logic rtl002_evt_ready = 1'b1;
  logic rtl002_evt_valid;
  logic [dfc_types_pkg::DFC_EVENT_RECORD_WIDTH-1:0] rtl002_evt_record;

  always #10 core_clk_i = ~core_clk_i;

  dfc_rtl001 u_rtl001 (
    .core_clk_i             (core_clk_i),
    .core_rst_n_i           (core_rst_n_i),
    .dri_req_valid_i        (dri_req_valid_i),
    .dri_req_ready_o        (dri_req_ready_o),
    .dri_req_write_i        (dri_req_write_i),
    .dri_req_addr_i         (dri_req_addr_i),
    .dri_req_wdata_i        (dri_req_wdata_i),
    .dri_req_wstrb_i        (dri_req_wstrb_i),
    .dri_rsp_valid_o        (dri_rsp_valid_o),
    .dri_rsp_ready_i        (dri_rsp_ready_i),
    .dri_rsp_rdata_o        (dri_rsp_rdata_o),
    .dri_rsp_code_o         (dri_rsp_code_o),
    .rtl002_control_o       (rtl002_control),
    .rtl002_status_i        (rtl002_status),
    .rtl003_control_o       (rtl003_control_unused),
    .rtl003_status_i        (rtl003_status_stub),
    .rtl004_control_o       (rtl004_control),
    .rtl004_status_i        (rtl004_status),
    .rtl005_control_o       (rtl005_control_unused),
    .rtl005_status_i        (rtl005_status_stub),
    .rtl006_control_o       (rtl006_control_unused),
    .rtl006_status_i        (rtl006_status_stub),
    .rtl007_control_o       (rtl007_control_unused),
    .rtl007_status_i        (rtl007_status_stub),
    .rtl008_control_o       (rtl008_control_unused),
    .rtl008_status_i        (rtl008_status_stub),
    .rtl009_control_o       (rtl009_control_unused),
    .rtl009_status_i        (rtl009_status_stub),
    .status_o               (),
    .dbg_regbank_write_en_o (dbg_regbank_write_en_o)
  );

  dfc_rtl004 u_rtl004 (
    .core_clk_i               (core_clk_i),
    .core_rst_n_i             (core_rst_n_i),
    .module_reset_i           (1'b0),
    .control_i                (rtl004_control),
    .status_o                 (rtl004_status),
    .evt_valid_o              (),
    .evt_ready_i              (rtl004_evt_ready),
    .evt_record_o             (),
    .timestamp_o              (rtl004_timestamp),
    .operating_state_i        (dfc_types_pkg::NORMAL),
    .observational_mode_i     (1'b0),
    // All bits enabled -- this test targets the RTL-001<->RTL-004 register
    // bus and the real timestamp broadcast specifically, not Appendix F.3's
    // real (not-yet-implemented) per-module condition-mask forwarding
    // mechanism (OPEN_ISSUES.md item 6), same isolation choice already made
    // in rtl003_integration_tb.sv.
    .event_condition_enable_i (64'hFFFF_FFFF_FFFF_FFFF),
    .irq_condition_enable_i   (64'h0)
  );

  // RTL-002, instantiated solely to prove the real timestamp broadcast (see
  // file header, Part 5 below) -- not otherwise this test's subject.
  dfc_rtl002 u_rtl002 (
    .core_clk_i           (core_clk_i),
    .core_rst_n_i         (core_rst_n_i),
    .module_reset_i       (1'b0),
    .control_i            (rtl002_control),
    .status_o             (rtl002_status),
    .timestamp_i          (rtl004_timestamp),  // the real connection under test
    .evt_valid_o          (rtl002_evt_valid),
    .evt_ready_i          (rtl002_evt_ready),
    .evt_record_o         (rtl002_evt_record),
    .irq_req_o            (),
    .module_ready_i       (24'h80F81F),  // all mandatory modules ready --
                                          // isolates RTL-002 to leaving
                                          // STARTUP quickly, same choice
                                          // rtl002_integration_tb.sv makes
    .module_fault_i       (24'h0),
    .module_reset_o       (),
    .operating_state_o    (),
    .observational_mode_o (),
    .test_active_i        (1'b0),
    .global_irq_enable_o       (),
    .global_event_enable_o     (),
    .event_condition_enable_i  (64'h0),
    .irq_condition_enable_i    (64'h0),
    // Real ports added during RTL-006's own integration session -- tied
    // open/unused here since this test targets RTL-004, not RTL-002's
    // own new gates (rtl006_integration_tb.sv covers their real
    // forwarding).
    .module_enable_o                (),
    .effective_operational_enable_o ()
  );

  int errors = 0, checks = 0;
  task automatic check(string what, logic [31:0] got, logic [31:0] expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got 0x%08h, expected 0x%08h", what, got, expected);
    end else $display("PASS: %s -- 0x%08h", what, got);
  endtask
  task automatic check_bit(string what, logic got, logic expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got %b, expected %b", what, got, expected);
    end else $display("PASS: %s", what);
  endtask
  task automatic check_ge(string what, logic [63:0] got, logic [63:0] floor_val);
    checks++;
    if (got < floor_val) begin
      errors++;
      $display("FAIL: %s -- got 0x%016h, expected >= 0x%016h", what, got, floor_val);
    end else $display("PASS: %s -- 0x%016h", what, got);
  endtask

  // ---- real host-style DRI transaction tasks (mirrors dri_transaction_tb.sv) ----
  task automatic dri_write(input logic [31:0] addr, input logic [31:0] data,
                            output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_wdata_i = data;
    dri_req_wstrb_i = 4'hF;
    dri_req_write_i = 1'b1;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    code = dri_rsp_code_o;
  endtask

  task automatic dri_read(input logic [31:0] addr, output logic [31:0] data,
                           output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_write_i = 1'b0;
    dri_req_wstrb_i = 4'h0;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    data = dri_rsp_rdata_o;
    code = dri_rsp_code_o;
  endtask

  // TIME_CONTROL/TIME_SYNC_OFFSET_LO/TIME_SYNC_OFFSET_HI/TIME_SYNC_COMMIT are
  // each protected (REG-002 SS9) -- same real PROTECT_KEY two-key
  // authorization sequence as every other protected register in this
  // project, consumed by exactly one accepted protected write.
  task automatic authorize_protected_write();
    logic [2:0] auth_code;
    dri_write(DFC_ADDR_PROTECT_KEY, dfc_constants_pkg::DFC_PROTECT_KEY1, auth_code);
    dri_write(DFC_ADDR_PROTECT_KEY, dfc_constants_pkg::DFC_PROTECT_KEY2, auth_code);
  endtask

  logic [2:0]  code;
  logic [31:0] rdata, rdata2;
  logic [63:0] snapshot_raw;

  initial begin
    dri_req_valid_i = 1'b0;
    dri_req_write_i = 1'b0;
    dri_req_addr_i  = '0;
    dri_req_wdata_i = '0;
    dri_req_wstrb_i = '0;

    core_rst_n_i = 1'b0;
    repeat (4) @(posedge core_clk_i);
    core_rst_n_i = 1'b1;
    @(posedge core_clk_i); #1;

    // ------------------------------------------------------------------
    // Part 1 (CONTROL direction, protected RW forwarding): a real host
    // write to TIME_CONTROL via RTL-001's real DRI path must actually
    // change RTL-004's real control_i -- the exact connection that would
    // be disconnected without reggen.py v4 + rtl004_field_map.json.
    // ------------------------------------------------------------------
    dri_read(DFC_ADDR_TIME_CONTROL, rdata, code);
    check("TIME_CONTROL reads its real REG-002 reset value before any write",
          rdata, 32'h0000_0001);

    authorize_protected_write();
    dri_write(DFC_ADDR_TIME_CONTROL, 32'h0000_0003, code);  // ENABLE=1, CORRELATION_ENABLE=1
    check("TIME_CONTROL write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    dri_read(DFC_ADDR_TIME_CONTROL, rdata, code);
    check("TIME_CONTROL reads back the real value just written", rdata, 32'h0000_0003);

    // ------------------------------------------------------------------
    // Part 2 (SNAPSHOT, ARCH-TIME-001/002/003): RTL-004's raw timestamp
    // genuinely runs (not a stub) -- wait well past two real ticks (>=100
    // CORE_CLK edges, tick every 50) before snapshotting, so the captured
    // value is real, live evidence, not zero.
    // ------------------------------------------------------------------
    repeat (110) @(posedge core_clk_i);

    dri_write(DFC_ADDR_TIME_SNAPSHOT, 32'h0000_0001, code);  // CAPTURE, unprotected
    check("TIME_SNAPSHOT write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_TIME_STATUS, rdata, code);
    check_bit("host-readable TIME_STATUS.SNAPSHOT_VALID set by the real capture",
              rdata[1], 1'b1);

    dri_read(DFC_ADDR_TIME_RAW_LO, rdata, code);
    dri_read(DFC_ADDR_TIME_RAW_HI, rdata2, code);
    snapshot_raw = {rdata2, rdata};
    check_ge({"host-readable TIME_RAW_LO/HI reflect RTL-004's real, live raw ",
              "counter (at least 2 real ticks after >=100 CORE_CLK edges), ",
              "not a permanent zero-tie"}, snapshot_raw, 64'd2);

    // ------------------------------------------------------------------
    // Part 3 (COMMIT, ARCH-TIME-004): a real staged offset + COMMIT command
    // must actually reach RTL-004's real active-offset state and reach back
    // to a host read -- previously impossible without a real register bus,
    // and TIME_ACTIVE_OFFSET_LO/HI had no real data source at all before
    // this module's own dfc_rtl004_status_t growth fix.
    // ------------------------------------------------------------------
    authorize_protected_write();
    dri_write(DFC_ADDR_TIME_SYNC_OFFSET_LO, 32'h0000_0064, code);  // +100
    check("TIME_SYNC_OFFSET_LO write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    authorize_protected_write();
    dri_write(DFC_ADDR_TIME_SYNC_OFFSET_HI, 32'h0000_0000, code);
    check("TIME_SYNC_OFFSET_HI write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    authorize_protected_write();
    dri_write(DFC_ADDR_TIME_SYNC_COMMIT, 32'h0000_0001, code);  // COMMIT
    check("TIME_SYNC_COMMIT write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    dri_read(DFC_ADDR_TIME_ACTIVE_OFFSET_LO, rdata, code);
    check("host-readable TIME_ACTIVE_OFFSET_LO mirrors the real committed offset (was always zero before this module's own status-struct fix)",
          rdata, 32'h0000_0064);
    dri_read(DFC_ADDR_TIME_ACTIVE_OFFSET_HI, rdata, code);
    check("host-readable TIME_ACTIVE_OFFSET_HI mirrors the real committed offset", rdata, 32'h0000_0000);

    dri_read(DFC_ADDR_TIME_SYNC_STATUS, rdata, code);
    check_bit("host-readable TIME_SYNC_STATUS.ACTIVE_VALID set by the real COMMIT",
              rdata[16], 1'b1);
    check("host-readable TIME_SYNC_STATUS.UPDATE_SEQUENCE incremented by the real COMMIT (first commit -> 1)",
          {16'h0, rdata[15:0]}, 32'h0000_0001);

    dri_read(DFC_ADDR_TIME_STATUS, rdata, code);
    check_bit("host-readable TIME_STATUS.SYNC_VALID set by the real COMMIT", rdata[2], 1'b1);
    check_bit("host-readable TIME_STATUS.SYNC_UPDATED set by the real COMMIT", rdata[3], 1'b1);

    // ------------------------------------------------------------------
    // Part 4 (CONTROL direction, W1C clear-request): a real host write to
    // RTL004_EVT_OVERFLOW_STATUS.EVENT_OVERFLOW must actually clear
    // RTL-004's real, previously-set sticky event_overflow_q. Withholding
    // the event handshake forces a real, genuine overflow condition (two
    // real SNAPSHOT-complete events landing on the still-occupied one-deep
    // pending slot), not a fabricated value.
    // ------------------------------------------------------------------
    rtl004_evt_ready = 1'b0;
    @(posedge core_clk_i); #1;

    check_bit("RTL-004's event_overflow starts clear before any overflow is forced",
              rtl004_status[dfc_types_pkg::DFC_RTL004_STATUS__EVENT_OVERFLOW_HI], 1'b0);

    dri_write(DFC_ADDR_TIME_SNAPSHOT, 32'h0000_0001, code);  // 1st event
    check("first SNAPSHOT write is still RSP_OK", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;  // 1st event now occupies the one-deep pending slot

    dri_write(DFC_ADDR_TIME_SNAPSHOT, 32'h0000_0001, code);  // 2nd event
    check("second SNAPSHOT write is still RSP_OK", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;  // 2nd event lands on the still-occupied slot -- overflow

    check_bit({"a real, genuine overflow condition (two real SNAPSHOT events, ",
              "handshake withheld) actually set RTL-004's sticky ",
              "event_overflow_q -- not a fabricated value"},
              rtl004_status[dfc_types_pkg::DFC_RTL004_STATUS__EVENT_OVERFLOW_HI], 1'b1);

    dri_write(DFC_ADDR_RTL004_EVT_OVERFLOW_STATUS, 32'h0000_0001, code);
    check("RTL004_EVT_OVERFLOW_STATUS clear write accepted (RSP_OK, was write_illegal_o=1 before this module's own control-struct fix)",
          {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    check_bit({"the real host write above actually cleared RTL-004's real, ",
              "previously-set event_overflow_q through the register ",
              "interface"},
              rtl004_status[dfc_types_pkg::DFC_RTL004_STATUS__EVENT_OVERFLOW_HI], 1'b0);

    rtl004_evt_ready = 1'b1;

    // ------------------------------------------------------------------
    // Part 5 (real timestamp broadcast -> real consumer): RTL-002's own
    // real event-record TIMESTAMP field must genuinely be nonzero and track
    // RTL-004's real, live raw counter -- closing the loop that was
    // previously a hard-tied 64'h0 stub in dfc_rtl024.sv (see file header).
    // A real MODULE_RESET command (same template as
    // rtl002_integration_tb.sv's own Part 3) triggers a real RTL-002 event
    // (0x0004 controlled-reset, "requested" subtype). The handshake is
    // closed off right here (not earlier) so the one-deep pending slot is
    // genuinely empty going into this specific trigger -- see the
    // declaration comment above for why it was left free-running until now.
    // ------------------------------------------------------------------
    rtl002_evt_ready = 1'b0;
    @(posedge core_clk_i); #1;

    authorize_protected_write();
    dri_write(DFC_ADDR_RESET_CONTROL, 32'h0000_0002, code);  // MODULE_RESET bit0
    check("RESET_CONTROL write accepted (RSP_OK)", {29'h0, code}, 32'h0);
    @(posedge core_clk_i); #1;

    check_bit("RTL-002's real event genuinely reached the pending slot",
              rtl002_evt_valid, 1'b1);
    check_ge({"RTL-002's own real evt_record_o.TIMESTAMP field is genuinely ",
              "nonzero and tracks RTL-004's real, live raw counter -- not the ",
              "64'h0 stub dfc_rtl024.sv previously hard-tied"},
              rtl002_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__TIMESTAMP_HI:dfc_types_pkg::DFC_EVENT_RECORD__TIMESTAMP_LO],
              snapshot_raw);

    $display("");
    $display("rtl004_integration_tb: %0d checks, %0d failures", checks, errors);
    if (errors != 0) begin
      $display("TEST FAILED");
      $finish(1);
    end else begin
      $display("TEST PASSED");
      $finish(0);
    end
  end

endmodule : rtl004_integration_tb
