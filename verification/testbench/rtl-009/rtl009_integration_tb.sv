  dfc_rtl009 u_rtl009 (
    .core_clk_i               (core_clk_i),
    .core_rst_n_i             (core_rst_n_i),
    .module_reset_i           (1'b0),
    .control_i                (rtl009_control),
    .status_o                 (rtl009_status),
    .timestamp_i              (tb_timestamp),
    .evt_valid_o              (rtl009_evt_valid),
