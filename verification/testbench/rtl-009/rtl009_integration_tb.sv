    .irq_req_o                (rtl009_irq_req),
    .fault_req_o              (),
    .pulse_i                  (pulse_i),
    .operating_state_i        (dfc_types_pkg::NORMAL),
    .observational_mode_i     (1'b0),
    .module_enable_i          (1'b1),
    .event_condition_enable_i (tb_event_condition_enable),
    .irq_condition_enable_i   (tb_irq_condition_enable)
  );

  int errors = 0, checks = 0;
  task automatic check(string what, logic [31:0] got, logic [31:0] expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got 0x%08h, expected 0x%08h", what, got, expected);
    end else $display("PASS: %s -- 0x%08h", what, got);
  endtask
  task automatic check_bit(string what, logic got, logic expected);
    checks++;
    if (got !== expected) begin
      errors++;
      $display("FAIL: %s -- got %b, expected %b", what, got, expected);
    end else $display("PASS: %s", what);
  endtask

  task automatic dri_write(input logic [31:0] addr, input logic [31:0] data,
                            output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_wdata_i = data;
    dri_req_wstrb_i = 4'hF;
    dri_req_write_i = 1'b1;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    code = dri_rsp_code_o;
  endtask

  task automatic dri_read(input logic [31:0] addr, output logic [31:0] data,
                           output logic [2:0] code);
    dri_req_addr_i  = addr;
    dri_req_write_i = 1'b0;
    dri_req_wstrb_i = 4'h0;
    dri_req_valid_i = 1'b1;
    @(posedge core_clk_i);
    while (!dri_req_ready_o) @(posedge core_clk_i);
    #1;
    dri_req_valid_i = 1'b0;
    @(posedge core_clk_i); #1;
    data = dri_rsp_rdata_o;
    code = dri_rsp_code_o;
  endtask

  // Produces exactly one rising edge on pulse_i[ch], then holds low for the
  // remainder of `gap_cycles` CORE_CLK cycles -- calling this back-to-back
  // (same ch, same gap_cycles) with no intervening activity produces edges
  // spaced exactly gap_cycles CORE_CLK cycles apart. Same real, hard-won
  // testbench-authoring lesson as rotor_pulse/engine_pulse in
  // rtl007/008_integration_tb.sv (OPEN_ISSUES.md item 26): the edge fires
  // on THIS call's own first posedge -- gap_cycles controls the spacing to
  // the NEXT edge, not the gap from whatever edge preceded this call.
  task automatic ch_pulse(int ch, int gap_cycles);
    pulse_i[ch] = 1'b1;
    @(posedge core_clk_i); #1;
    pulse_i[ch] = 1'b0;
    repeat (gap_cycles - 1) @(posedge core_clk_i);
    #1;
  endtask

  // Waits exactly `pre_cycles` CORE_CLK cycles, THEN produces one rising
  // edge on pulse_i[ch], then returns immediately (no trailing wait) --
  // for one-off, explicit control over the gap from whatever edge came
  // before, same shape as rotor_edge_after/engine_edge_after.
  task automatic ch_pulse_after(int ch, int pre_cycles);
    repeat (pre_cycles) @(posedge core_clk_i);
    pulse_i[ch] = 1'b1;
    @(posedge core_clk_i); #1;
    pulse_i[ch] = 1'b0;
    #1;
  endtask

  // Drives BOTH pulse_i bits simultaneously -- the mechanism Part 3 (shared
  // event-slot arbitration) needs: both channels' own, fully independent
  // divider pipelines see their commit trigger on the exact same CORE_CLK
  // cycle, so both reach MEAS_APPLY on the exact same cycle too (identical
  // 65-cycle latency regardless of operand values).
  task automatic both_pulse(int gap_cycles);
    pulse_i = 2'b11;
    @(posedge core_clk_i); #1;
    pulse_i = 2'b00;
    repeat (gap_cycles - 1) @(posedge core_clk_i);
    #1;
  endtask

  task automatic wait_for_divide();
    repeat (200) @(posedge core_clk_i);
  endtask

  logic [2:0]  code;
  logic [31:0] rdata;

  initial begin
    core_rst_n_i = 0;
    repeat (4) @(posedge core_clk_i);
    core_rst_n_i = 1;
    repeat (2) @(posedge core_clk_i);

    // ==========================================================================
    // Part 1: PULSE0_CONTROL/THRESH_LOW/THRESH_HIGH/TIMEOUT_US/HYSTERESIS
    // writes reach RTL-009's real channel 0 control_i (bit-exact real
    // register bus, not a fabricated white-box force), then a real,
    // simulated period-mode pulse train produces a self-consistent,
    // EXACT Q17.15 frequency reading.
    // ==========================================================================
    dri_write(DFC_ADDR_PULSE0_THRESH_LOW_Q17_15,  32'd819_200_000, code);   // 25,000 Hz
    check("PULSE0_THRESH_LOW write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_write(DFC_ADDR_PULSE0_THRESH_HIGH_Q17_15, 32'd1_024_000_000, code); // 31,250 Hz
    check("PULSE0_THRESH_HIGH write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_write(DFC_ADDR_PULSE0_HYSTERESIS_Q17_15,  32'd32_768_000, code);    // 1,000 Hz
    check("PULSE0_HYSTERESIS write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_write(DFC_ADDR_PULSE0_TIMEOUT_US, 32'd2_500_000, code);
    check("PULSE0_TIMEOUT_US write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_write(DFC_ADDR_PULSE0_CONTROL, 32'h0000_000F, code);  // ENABLE=1, RISING_EDGE=1, EVENT_ENABLE=1, IRQ_ENABLE=1
    check("PULSE0_CONTROL (ENABLE=1) write accepted (RSP_OK)", {29'h0,code}, 32'h0);

    // Establish have_prior_edge_q, then one exact-dividing period-mode
    // measurement: 1,638,400,000,000 / 2000 = 819,200,000 (25,000 Hz),
    // matching THRESH_LOW exactly (boundary, not "low" -- strict "<").
    ch_pulse(0, 2000);
    ch_pulse(0, 2000);
    wait_for_divide();
    dri_read(DFC_ADDR_PULSE0_FREQ_Q17_15, rdata, code);
    check("PULSE0_FREQ_Q17_15 genuinely computed via the real pipelined divider (25,000 Hz)", rdata, 32'd819_200_000);
    dri_read(DFC_ADDR_PULSE0_PERIOD_TICKS, rdata, code);
    check("PULSE0_PERIOD_TICKS genuinely reflects the real 2000-cycle gap", rdata, 32'd2000);
    dri_read(DFC_ADDR_PULSE0_STATUS, rdata, code);
    check_bit("PULSE0_STATUS.VALID genuinely set after a real committed measurement", rdata[0], 1'b1);
    check_bit("PULSE0_STATUS.LOW genuinely clear (25,000 Hz == THRESH_LOW, not below)", rdata[1], 1'b0);
    check_bit("PULSE0_STATUS.HIGH genuinely clear (25,000 Hz == THRESH_HIGH boundary region, not above)", rdata[2], 1'b0);
    check_bit("PULSE0_STATUS.UPDATED genuinely set by the real commit", rdata[5], 1'b1);
    dri_write(DFC_ADDR_PULSE0_STATUS, 32'h0000_0020, code);  // clear UPDATED
    dri_read(DFC_ADDR_PULSE0_STATUS, rdata, code);
    check_bit("the real host clear write above actually cleared PULSE0_STATUS.UPDATED", rdata[5], 1'b0);

    // ---- LOW enter/exit, HIGH enter/exit (ARCH-MON-005), all exact-dividing ----
    // Every gap below is driven as a BACK-TO-BACK PAIR, not a single call:
    // this file's own header documents the real lesson (OPEN_ISSUES.md item
    // 26's own class) that a single ch_pulse call after intervening
    // register reads/writes measures the real, but UNPREDICTABLE, elapsed
    // time since whatever edge came before -- only the SECOND call of a
    // same-gap pair is guaranteed exact, since its immediately preceding
    // edge is the pair's own first call.
    // evt_ready_i is withheld across this specific measurement so the
    // one-deep pending slot genuinely holds the LOW-crossing record long
    // enough to check it -- with evt_ready_i held high (the default
    // throughout this file), a real record drains itself the very next
    // cycle, and checking it any later would observe whatever LATER event
    // happened to land in the slot instead (a real, found-and-fixed bug in
    // this file's own first draft).
    rtl009_evt_ready = 1'b0;
    ch_pulse(0, 2500);
    ch_pulse(0, 2500);  // 1,638,400,000,000/2500 = 655,360,000 Hz (20,000 Hz) -> LOW enters
    wait_for_divide();
    dri_read(DFC_ADDR_PULSE0_FREQ_Q17_15, rdata, code);
    check("PULSE0_FREQ_Q17_15 genuinely drops to 655,360,000 for the real 2500-cycle gap", rdata, 32'd655_360_000);
    dri_read(DFC_ADDR_PULSE0_STATUS, rdata, code);
    check_bit("PULSE0_STATUS.LOW genuinely sets when FREQ < THRESH_LOW", rdata[1], 1'b1);
    check_bit("a real, genuinely LOW-crossing measurement asserted evt_valid_o", rtl009_evt_valid, 1'b1);
    check("the real event record's EVENT_ID/SOURCE_ID genuinely match RTL-009's own event (0x0032, source index 8)",
          rtl009_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__SOURCE_ID_HI:dfc_types_pkg::DFC_EVENT_RECORD__EVENT_ID_LO],
          {8'd8, 16'h0032});
    check("the real event record's event_data genuinely shows subtype=0 (low)",
          rtl009_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO+16 +: 8], 32'd0);
    rtl009_evt_ready = 1'b1;
    @(posedge core_clk_i); #1;  // drain the slot before the next measurement needs it

    ch_pulse(0, 1600);
    ch_pulse(0, 1600);  // 1,638,400,000,000/1600 = 1,024,000,000 Hz (31,250 Hz) -> LOW exits, HIGH boundary (not >)
    wait_for_divide();
    dri_read(DFC_ADDR_PULSE0_STATUS, rdata, code);
    check_bit("PULSE0_STATUS.LOW genuinely clears once FREQ (31,250 Hz) reaches THRESH_LOW+HYST (26,000 Hz)", rdata[1], 1'b0);
    check_bit("PULSE0_STATUS.HIGH genuinely stays clear (31,250 Hz == THRESH_HIGH, not strictly above)", rdata[2], 1'b0);

    tb_irq_seen = 1'b0;
    ch_pulse(0, 1250);
    ch_pulse(0, 1250);  // 1,638,400,000,000/1250 = 1,310,720,000 Hz (40,000 Hz) -> HIGH enters
    wait_for_divide();
    dri_read(DFC_ADDR_PULSE0_FREQ_Q17_15, rdata, code);
    check("PULSE0_FREQ_Q17_15 genuinely reaches 1,310,720,000 for the real 1250-cycle gap", rdata, 32'd1_310_720_000);
    dri_read(DFC_ADDR_PULSE0_STATUS, rdata, code);
    check_bit("PULSE0_STATUS.HIGH genuinely sets when FREQ > THRESH_HIGH", rdata[2], 1'b1);
    check_bit("a real, genuinely HIGH-crossing measurement asserted RTL-009's real irq_req_o", tb_irq_seen, 1'b1);

    ch_pulse(0, 2000);
    ch_pulse(0, 2000);  // back to 819,200,000 Hz (25,000 Hz) -> HIGH exits, LOW boundary (not <)
    wait_for_divide();
    dri_read(DFC_ADDR_PULSE0_STATUS, rdata, code);
    check_bit("PULSE0_STATUS.HIGH genuinely clears back at 25,000 Hz", rdata[2], 1'b0);
    check_bit("PULSE0_STATUS.LOW genuinely stays clear (25,000 Hz == THRESH_LOW, not strictly below)", rdata[1], 1'b0);

    // ==========================================================================
    // Part 2: PULSE1_* register bus, real independent channel 1 config +
    // real, self-consistent period-mode measurement (different exact value
    // than channel 0's, confirming genuinely separate register wiring, not
    // aliased storage).
    // ==========================================================================
    dri_write(DFC_ADDR_PULSE1_THRESH_LOW_Q17_15,  32'd819_200_000, code);
    check("PULSE1_THRESH_LOW write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_write(DFC_ADDR_PULSE1_THRESH_HIGH_Q17_15, 32'd2_000_000_000, code);
    check("PULSE1_THRESH_HIGH write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_write(DFC_ADDR_PULSE1_HYSTERESIS_Q17_15,  32'd32_768_000, code);
    check("PULSE1_HYSTERESIS write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    // NOTE: kept at the same generous 2,500,000us value as channel 0 here
    // -- a real, found-and-fixed test-design bug in this file's own first
    // draft set this to a small value (10us = 500 CORE_CLK cycles) already
    // at this point, intending it only for Part 6's own timeout test far
    // later. Parts 3/4/5 in between genuinely take far longer than 500
    // cycles without a channel-1 pulse, so channel 1 was genuinely timing
    // out mid-test and injecting a real, unintended TIMEOUT event that
    // corrupted Part 3's own expected clean arbitration scenario (found via
    // a real, confirmed simulation failure: Part 3's captured event
    // subtype read TIMEOUT instead of UPDATED, and DROP_COUNT read 2
    // instead of 1). The small value is now set immediately before Part 6
    // uses it instead.
    dri_write(DFC_ADDR_PULSE1_TIMEOUT_US, 32'd2_500_000, code);
    check("PULSE1_TIMEOUT_US write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_write(DFC_ADDR_PULSE1_CONTROL, 32'h0000_000F, code);  // ENABLE=1, RISING_EDGE=1, EVENT_ENABLE=1, IRQ_ENABLE=1
    check("PULSE1_CONTROL (ENABLE=1) write accepted (RSP_OK)", {29'h0,code}, 32'h0);

    ch_pulse(1, 1600);  // establish have_prior_edge_q
    ch_pulse(1, 1600);  // 1,638,400,000,000/1600 = 1,024,000,000 Hz (31,250 Hz)
    wait_for_divide();
    dri_read(DFC_ADDR_PULSE1_FREQ_Q17_15, rdata, code);
    check("PULSE1_FREQ_Q17_15 genuinely computed via its own, independent real pipelined divider (31,250 Hz)", rdata, 32'd1_024_000_000);
    dri_read(DFC_ADDR_PULSE1_PERIOD_TICKS, rdata, code);
    check("PULSE1_PERIOD_TICKS genuinely reflects the real 1600-cycle gap", rdata, 32'd1600);

    // ==========================================================================
    // Part 3: shared event-slot arbitration -- a real mechanism RTL-007/008
    // (single producer each) never needed. Driving both_pulse() produces a
    // genuinely COINCIDENT commit trigger on both channels' own independent
    // divider pipelines (identical 65-cycle latency), so both present an
    // "updated" event candidate the exact same cycle. dfc_rtl009.sv's own
    // disclosed arbitration: channel 0 wins ties; channel 1's genuinely lost
    // candidate is counted, not silently dropped.
    // ==========================================================================
    // Same back-to-back-pair discipline as Part 1 -- the first both_pulse
    // call absorbs whatever unpredictable time has elapsed on each channel
    // since its own last edge; the second gives BOTH channels an exact,
    // and exactly COINCIDENT, 2000-cycle period. evt_ready_i is held HIGH
    // through this first call so its own (unpredictable-value) commit
    // drains normally -- a real, found-and-fixed bug in this file's own
    // first draft withheld evt_ready_i before BOTH calls, so the FIRST
    // call's own real commit (an unrelated, unpredictable measurement) was
    // captured into the one pending slot and never drained, corrupting
    // what the SECOND call's genuinely coincident commit could observe
    // (the slot was already occupied, so channel 0's own intended
    // candidate was dropped too, not just channel 1's -- confirmed via a
    // real, observed drop_count of 4, not the intended 1).
    // NOTE: no wait_for_divide() (or any other time-consuming statement)
    // between these two both_pulse() calls -- that would add extra cycles
    // to the gap and break the exact 2000-cycle spacing the second call
    // needs (a real, found-and-fixed bug in this file's own second draft:
    // inserting a 200-cycle wait here to "let the first commit drain"
    // silently made the real measured gap 2200 cycles, not 2000). The
    // first commit's event has 2000-65=1935 real cycles of margin to drain
    // on its own (evt_ready_i is still 1 through the whole first call)
    // before the second call's own edge even fires, so no explicit wait is
    // needed at all -- only evt_ready_i needs to flip low, and a plain
    // variable assignment consumes zero simulation time.
    // Establish a known-clean EVENT_OVERFLOW baseline first (earlier parts
    // of this file, e.g. Part 1's withheld-evt_ready LOW-crossing check,
    // can genuinely leave real, sticky W1C evidence behind -- found via a
    // real, confirmed simulation trace, not assumed). DROP_COUNT itself is
    // real, permanently-saturating, and read-only (REG-2250's own
    // "DROP_COUNT is read-only" text, same precedent already established
    // for RTL-007/008's identical field) -- it is NOT expected to clear
    // alongside EVENT_OVERFLOW, so this Part captures its current value as
    // a baseline and checks its own contribution as a DELTA, not an
    // absolute "starts at 0" assumption (a real, found-and-fixed test bug
    // in this file's own earlier draft).
    dri_write(DFC_ADDR_RTL009_EVT_OVERFLOW_STATUS, 32'h1, code);
    dri_read(DFC_ADDR_RTL009_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("Part 3: EVENT_OVERFLOW reads clean before this Part's own test", rdata[0], 1'b0);
    begin
      logic [15:0] drop_count_baseline;
      drop_count_baseline = rdata[23:8];
      // NOTE: the baseline is captured BEFORE the first both_pulse call
      // (not between the two calls) -- a dri_read inserted between them
      // consumes several real CORE_CLK cycles, which breaks the exact
      // 2000-cycle back-to-back spacing the SECOND call needs (a real,
      // found-and-fixed bug in this file's own second draft: the captured
      // event_data read a period a few cycles off from the intended exact
      // value once a read was inserted there). The final check below
      // therefore expects the baseline PLUS 2, not plus 1: the first
      // both_pulse call is ALSO a genuinely coincident ch0/ch1 commit
      // (both bits are always driven together), so it ALSO drops channel
      // 1's own candidate once (channel 0 wins ties unconditionally,
      // regardless of whether the slot happens to be free) -- a real,
      // found-and-fixed miscount in this file's own first draft, which
      // treated that first call as having no drop consequence at all.
      both_pulse(2000);
      rtl009_evt_ready = 1'b0;
      both_pulse(2000);  // ch0: exactly 819,200,000 Hz again; ch1: its own real, exact (but unchecked) period
      wait_for_divide();
      check_bit("Part 3: a genuine simultaneous commit asserted evt_valid_o", rtl009_evt_valid, 1'b1);
      check("Part 3: the captured event record is channel 0's (source/event ID match, channel 0 wins ties)",
            rtl009_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__SOURCE_ID_HI:dfc_types_pkg::DFC_EVENT_RECORD__EVENT_ID_LO],
            {8'd8, 16'h0032});
      check("Part 3: the captured event record's event_data genuinely carries channel 0's own 819,200,000 Hz reading (upper 16 bits)",
            rtl009_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO +: 16], 32'h30D4);
      check("Part 3: the captured event record's subtype genuinely reads UPDATED (3), not a fabricated value",
            rtl009_evt_record[dfc_types_pkg::DFC_EVENT_RECORD__EVENT_DATA_LO+16 +: 8], 32'd3);
      dri_read(DFC_ADDR_RTL009_EVT_OVERFLOW_STATUS, rdata, code);
      check_bit("Part 3: channel 1's genuinely lost candidate set EVENT_OVERFLOW via a real host READ", rdata[0], 1'b1);
      check("Part 3: DROP_COUNT genuinely incremented by exactly 2 relative to this Part's own baseline (both both_pulse calls are coincident commits; channel 1 loses both, channel 0 loses neither)",
            rdata[23:8], drop_count_baseline + 16'd2);
    end
    dri_write(DFC_ADDR_RTL009_EVT_OVERFLOW_STATUS, 32'h1, code);  // clear, leave clean state for later parts
    check("Part 3: RTL009_EVT_OVERFLOW_STATUS clear write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    rtl009_evt_ready = 1'b1;
    @(posedge core_clk_i); #1;  // drain the slot before later parts need it

    // ==========================================================================
    // Part 4: channel independence -- the explicit, required cross-check
    // (same pattern as RTL-008's own real cross-check against RTL-007 in
    // rtl008_integration_tb.sv, applied within this single module instead
    // of across two modules).
    // ==========================================================================
    dri_read(DFC_ADDR_PULSE1_FREQ_Q17_15, rdata, code);
    begin
      logic [31:0] ch1_before_ch0_drive;
      ch1_before_ch0_drive = rdata;
      ch_pulse(0, 1250);  // drive channel 0 ONLY
      wait_for_divide();
      dri_read(DFC_ADDR_PULSE1_FREQ_Q17_15, rdata, code);
      check("Part 4: channel 1's real FREQ_Q17_15 is genuinely UNCHANGED by channel 0's own pulse train just driven -- confirms independent state, not a shared measurement path",
            rdata, ch1_before_ch0_drive);
    end
    dri_read(DFC_ADDR_PULSE0_FREQ_Q17_15, rdata, code);
    begin
      logic [31:0] ch0_before_ch1_drive;
      ch0_before_ch1_drive = rdata;
      ch_pulse(1, 1600);
      ch_pulse(1, 1600);  // drive channel 1 ONLY, exact pair
      wait_for_divide();
      dri_read(DFC_ADDR_PULSE1_FREQ_Q17_15, rdata, code);
      check("Part 4: channel 1's own real FREQ_Q17_15 genuinely DID respond to its own pulse train", rdata, 32'd1_024_000_000);
      dri_read(DFC_ADDR_PULSE0_FREQ_Q17_15, rdata, code);
      check("Part 4: channel 0's real FREQ_Q17_15 is genuinely UNCHANGED by channel 1's own pulse train just driven -- confirms independent state in both directions",
            rdata, ch0_before_ch1_drive);
    end

    // ==========================================================================
    // Part 5: count mode (ARCH-MON-002 hysteresis) -- channel 0 only. A
    // real, hard-won derivation, not guessed:
    //   - The FIRST accepted edge only ever sets have_prior_edge_q (no
    //     period measured yet) -- channel 0 already has this from Part 1/4.
    //   - Switching to count mode needs TWO CONSECUTIVE measured periods
    //     under 1,000 cycles, so it takes exactly 3 total pulses at a
    //     500-cycle gap (edge #1 measures period vs. whatever came before
    //     in Part 4 -- genuinely unpredictable, so it is NOT counted on;
    //     edge #2 measures exactly 500 vs. edge #1 -- first qualifying
    //     period; edge #3 measures exactly 500 vs. edge #2 -- second
    //     qualifying period, switch fires HERE).
    //   - The switch resets gate_counter_q/edge_count_q to 0 the cycle
    //     AFTER the switching edge. Each subsequent 1000-cycle-gap pulse
    //     lands at gate-relative cycle 1000*k (k=1,2,...). An edge is
    //     counted only while gate_counter_q < 99,999 at that cycle; the
    //     edge that would land exactly at k=100 (cycle 100,000) coincides
    //     with the real gate-expiry cycle, and dfc_rtl009.sv's own
    //     gate-counter logic lets the reset win on that exact cycle (the
    //     edge is NOT counted) -- so only k=1..99 (99 pulses) are ever
    //     actually counted before the real commit fires automatically at
    //     cycle 100,000, with no 100th pulse needed at all.
    //   - Expected FREQ_Q17_15 = 99 x 16,384,000 = 1,622,016,000 (an EXACT
    //     multiple of the count-mode constant -- itself a real,
    //     structural proof the multiply-only, no-remainder count-mode path
    //     actually ran, not a fabricated or period-mode value).
    // ==========================================================================
    ch_pulse(0, 500);
    ch_pulse(0, 500);
    ch_pulse(0, 500);  // switch to MODE_COUNT fires on this edge
    for (int k = 0; k < 99; k++) ch_pulse(0, 1000);
    // Real gate expiry is automatic (a free-running counter, not gated on
    // pulse_i) -- wait past cycle 100,000 (relative to the switch) plus the
    // real 65-cycle pipelined-divider latency, comfortably.
    repeat (1200) @(posedge core_clk_i);
    wait_for_divide();
    dri_read(DFC_ADDR_PULSE0_FREQ_Q17_15, rdata, code);
    check("Part 5: PULSE0_FREQ_Q17_15 genuinely computed via the real count-mode path (99 edges x 16,384,000)", rdata, 32'd1_622_016_000);
    dri_read(DFC_ADDR_PULSE0_PERIOD_TICKS, rdata, code);
    check("Part 5: PULSE0_PERIOD_TICKS still genuinely tracks the last individual accepted period (1000) even in count mode", rdata, 32'd1000);
    dri_read(DFC_ADDR_PULSE0_STATUS, rdata, code);
    check_bit("Part 5: PULSE0_STATUS.UPDATED genuinely set by the real count-mode commit", rdata[5], 1'b1);

    // ==========================================================================
    // Part 6: no-edge timeout (ARCH-MON-005) -- channel 1. TIMEOUT_US is set
    // small (10us = 500 CORE_CLK cycles at the nominal 50 MHz assumption)
    // right here, immediately before the wait that exercises it -- not back
    // in Part 2 (see that write's own comment for the real, found-and-fixed
    // test-design bug that caused when it was set too early).
    // ==========================================================================
    dri_write(DFC_ADDR_PULSE1_TIMEOUT_US, 32'd10, code);
    check("Part 6: PULSE1_TIMEOUT_US (small) write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    repeat (700) @(posedge core_clk_i);  // > 500 CORE_CLK cycles, no channel-1 pulse issued
    dri_read(DFC_ADDR_PULSE1_STATUS, rdata, code);
    check_bit("Part 6: PULSE1_STATUS.TIMEOUT genuinely sets after the real configured elapsed time", rdata[3], 1'b1);
    check_bit("Part 6: PULSE1_STATUS.VALID genuinely clears once TIMEOUT fires", rdata[0], 1'b0);
    dri_write(DFC_ADDR_PULSE1_STATUS, 32'h0000_0008, code);  // clear TIMEOUT
    dri_read(DFC_ADDR_PULSE1_STATUS, rdata, code);
    check_bit("Part 6: the real host clear write above actually cleared PULSE1_STATUS.TIMEOUT", rdata[3], 1'b0);
    // Re-establish channel 1 so later reads don't observe a permanently
    // timed-out channel.
    dri_write(DFC_ADDR_PULSE1_TIMEOUT_US, 32'd2_500_000, code);
    ch_pulse(1, 1600);
    ch_pulse(1, 1600);
    wait_for_divide();

    // ==========================================================================
    // Part 7: EVENT_OVERFLOW forced by withholding the event handshake --
    // same technique as rtl007/008_integration_tb.sv, applied to channel 1
    // alone this time (channel 0 is mid-count-mode from Part 5; using
    // channel 1 avoids any interaction with that state). Proven via a real
    // host REGISTER READ, not white-box inspection, per OPEN_ISSUES.md item
    // 21's own lesson (closed for RTL-009 from the start).
    // ==========================================================================
    dri_read(DFC_ADDR_RTL009_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("Part 7: RTL009_EVT_OVERFLOW_STATUS.EVENT_OVERFLOW reads clear via a real host READ before any overflow is forced", rdata[0], 1'b0);
    rtl009_evt_ready = 1'b0;  // withhold the handshake
    ch_pulse(1, 1600);  // commit #1 -- occupies the one pending slot
    wait_for_divide();
    ch_pulse(1, 1600);  // commit #2 -- genuinely dropped, slot still occupied
    wait_for_divide();
    dri_read(DFC_ADDR_RTL009_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("Part 7: a real, genuine overflow (two real commits, evt_ready withheld) is genuinely readable via a real host REGISTER READ", rdata[0], 1'b1);
    check_bit("Part 7: RTL009_EVT_OVERFLOW_STATUS.DROP_COUNT is genuinely nonzero via the same real host read", (|rdata[23:8]), 1'b1);
    rtl009_evt_ready = 1'b1;
    @(posedge core_clk_i); #1;
    dri_write(DFC_ADDR_RTL009_EVT_OVERFLOW_STATUS, 32'h1, code);
    check("Part 7: RTL009_EVT_OVERFLOW_STATUS clear write accepted (RSP_OK)", {29'h0,code}, 32'h0);
    dri_read(DFC_ADDR_RTL009_EVT_OVERFLOW_STATUS, rdata, code);
    check_bit("Part 7: the real host clear write above actually cleared EVENT_OVERFLOW, confirmed via a real host READ", rdata[0], 1'b0);

    // ==========================================================================
    // Part 8: illegal configuration / ready-fault (ARCH-VAL-009), channel 0.
    // ==========================================================================
    dri_read(DFC_ADDR_PULSE0_THRESH_HIGH_Q17_15, rdata, code);
    begin
      logic [31:0] ch0_thresh_high;
      ch0_thresh_high = rdata;
      check_bit("Part 8: RTL-009 reports ready before any illegal configuration", rtl009_status[dfc_types_pkg::DFC_RTL009_STATUS__READY_HI], 1'b1);
      check_bit("Part 8: RTL-009 reports no fault before any illegal configuration", rtl009_status[dfc_types_pkg::DFC_RTL009_STATUS__FAULT_HI], 1'b0);
      dri_write(DFC_ADDR_PULSE0_THRESH_LOW_Q17_15, ch0_thresh_high + 32'd1, code);  // LOW > HIGH, illegal
      @(posedge core_clk_i); #1;
      check_bit("Part 8: a genuinely illegal configuration (LOW > HIGH, RTL-001 does not yet reject it) was detected by RTL-009 itself -- fault set",
                rtl009_status[dfc_types_pkg::DFC_RTL009_STATUS__FAULT_HI], 1'b1);
      check_bit("Part 8: RTL-009 correctly reports not-ready while the illegal configuration persists",
                rtl009_status[dfc_types_pkg::DFC_RTL009_STATUS__READY_HI], 1'b0);
      dri_write(DFC_ADDR_PULSE0_THRESH_LOW_Q17_15, 32'd819_200_000, code);  // restore legal value
      @(posedge core_clk_i); #1;
      check_bit("Part 8: RTL-009 genuinely returns to ready once the illegal value clears",
                rtl009_status[dfc_types_pkg::DFC_RTL009_STATUS__READY_HI], 1'b1);
      check_bit("Part 8: fault genuinely clears alongside it",
                rtl009_status[dfc_types_pkg::DFC_RTL009_STATUS__FAULT_HI], 1'b0);
    end

    $display("");
    $display("rtl009_integration_tb: %0d checks, %0d failures", checks, errors);
    if (errors == 0) $display("TEST PASSED"); else $display("TEST FAILED");
    $finish;
  end

endmodule : rtl009_integration_tb
