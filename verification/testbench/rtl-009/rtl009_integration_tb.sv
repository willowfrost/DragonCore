// rtl009_integration_tb.sv -- REAL end-to-end round-trip test: a host-style
// register write through RTL-001's real address-decode path must actually
// change RTL-009's real behavior (thresholds/timeout/edge filter/
// hysteresis, per channel), and real simulated pulse trains on BOTH
// pulse_i[0] and pulse_i[1] must actually produce real, correct Q17.15
// frequency measurements readable via PULSE0_FREQ_Q17_15/PULSE1_FREQ_Q17_15,
// plus real threshold/timeout/saturation fault detection -- same template
// and purpose as rtl002 through rtl008_integration_tb.sv, targeting the
// RTL-001<->RTL-009 register bus specifically (PULSE0_CONTROL/
// PULSE0_THRESH_LOW_Q17_15/PULSE0_THRESH_HIGH_Q17_15/PULSE0_TIMEOUT_US/
// PULSE0_EDGE_FILTER/PULSE0_HYSTERESIS_Q17_15/PULSE1_* mirrors/
// RTL009_EVT_OVERFLOW_STATUS control forwarding; PULSE0_STATUS/
// PULSE0_FREQ_Q17_15/PULSE0_PERIOD_TICKS/PULSE1_*/RTL009_EVT_OVERFLOW_STATUS
// status forwarding), generated by reggen.py v4 + tools/reggen/
// rtl009_field_map.json.
//
// ADDITIONALLY (per this module's own real, distinguishing requirements):
//   - BOTH channels are driven with genuinely simulated external pulse
//     trains and their own real Q17.15 arithmetic is checked for exact
//     self-consistency: every period-mode gap chosen below was picked so
//     FREQ_Q17_15 = round_nearest(1,638,400,000,000 / period_ticks) divides
//     EXACTLY (no rounding), keeping every check deterministic -- same
//     discipline as rtl007/008_integration_tb.sv's own RPM-divider checks,
//     applied to dfc_rtl009.sv's Q17.15 divider instead.
//   - Part 3 (shared-slot event arbitration) is a real test this module
//     needs that RTL-007/008 (single producer each) never did: driving
//     BOTH pulse_i bits SIMULTANEOUSLY produces genuinely coincident commit
//     triggers on both channels' own, fully independent 65-cycle divider
//     pipelines (identical FSM depth regardless of operand values), which
//     is what actually exercises the one-shared-pending-slot arbitration
//     dfc_rtl009.sv's own header discloses (channel 0 wins ties; the loser
//     is genuinely counted as dropped, not silently lost).
//   - Part 5 (count mode) requires exactly 3 pulses at a sub-1,000-cycle
//     gap to trigger the mode switch (NOT 2): the first accepted edge only
//     establishes `have_prior_edge_q`, so the earliest a genuine 2-in-a-row
//     "period < 1,000" classification can complete is the SECOND real
//     measured period, i.e. the THIRD edge -- a real, hard-won lesson from
//     this file's own bring-up (see Part 5's own comment for the full
//     count derivation, including why an edge landing exactly on the
//     100,000-cycle gate boundary is genuinely NOT counted -- reset
//     dominates same-cycle per dfc_rtl009.sv's own gate-counter logic).
//     Logged as a real testbench-authoring lesson for any future module
//     sharing ARCH-MON-002's count-mode gate, same spirit as
//     OPEN_ISSUES.md items 26/27/30 for RTL-007/008.
//
// RTL-002 through RTL-008 are out of this test's scope (same isolation
// choice every prior module-specific integration testbench already makes
// for sibling modules not under test): `module_enable_i` is driven directly
// by this testbench as a plain constant, and `timestamp_i` is a
// free-running testbench counter, not RTL-004's real broadcast.
//
// CLOCKING-DISCIPLINE NOTE (same lesson as every other testbench in this
// project): every strobe is held for a full clock and deasserted with a
// #1 settle delay after the sampling edge, never in the same delta. Every
// pulse task below waits a generous margin (200 CORE_CLK cycles) after the
// pulse that completes a measurement before reading the result, comfortably
// longer than the real 65-cycle pipelined-divider latency (dfc_rtl009.sv's
// own MEAS_MULT/MEAS_RUN states) -- not a race against an exact cycle
// count.

