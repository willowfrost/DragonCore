#!/usr/bin/env python3
"""
split_irqfault.py -- splits extract_irqfault.py's combined output into the
two separate package files pkggen.py actually needs: dfc_events_pkg.json
and dfc_interrupt_pkg.json.

WHY THIS EXISTS: extract_irqfault.py (unmodified) extracts all four
ARCH-002 Appendix C matrices (C.4 irq, C.5 event, C.6 fault, C.7 event
registry) correctly and mechanically, but writes them into ONE combined
file under the single package name "dfc_interrupt_pkg". Prior to this
script, splitting that combined data into the two actual per-package
files was a manual step -- exactly the kind of hand-assembly this
project's own "no hand-edited files" rule was meant to rule out, one
step removed from the final .sv output. This script closes that gap
mechanically: no manual judgment, just picking the same two fixed key
groupings that were always used (confirmed by inspecting this project's
prior dfc_events_pkg.json / dfc_interrupt_pkg.json directly):

  dfc_events_pkg.json    = event_sources (C.5) + event_registry (C.7)
  dfc_interrupt_pkg.json = irq_sources (C.4) + fault_sources (C.6)

Usage: split_irqfault.py <dfc_irqfault.json> <events_out.json> <interrupt_out.json>
"""
import sys, json


def main():
    if len(sys.argv) != 4:
        print("usage: split_irqfault.py <dfc_irqfault.json> <events_out.json> "
              "<interrupt_out.json>", file=sys.stderr)
        sys.exit(2)
    combined_path, events_out, interrupt_out = sys.argv[1], sys.argv[2], sys.argv[3]

    try:
        combined = json.load(open(combined_path, encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        print(f"EXTRACTION FAILED: could not read {combined_path}: {e}", file=sys.stderr)
        sys.exit(1)

    required_keys = ["event_sources", "event_registry", "irq_sources", "fault_sources"]
    missing = [k for k in required_keys if k not in combined]
    if missing:
        print(f"EXTRACTION FAILED: {combined_path} is missing expected key(s) "
              f"{missing} -- has extract_irqfault.py's output shape changed?",
              file=sys.stderr)
        sys.exit(1)

    events_spec = {
        "package": "dfc_events_pkg",
        "_source": ("GENERATED by split_irqfault.py from dfc_irqfault.json's "
                    "event_sources (ARCH-002 C.5) and event_registry "
                    "(ARCH-002 C.7), both mechanically extracted and verified "
                    "by extract_irqfault.py. No manual splitting step -- this "
                    "script performs the same fixed key grouping every time."),
        "imports": [],
        "event_sources": combined["event_sources"],
        "event_registry": combined["event_registry"],
    }
    interrupt_spec = {
        "package": "dfc_interrupt_pkg",
        "_source": ("GENERATED by split_irqfault.py from dfc_irqfault.json's "
                    "irq_sources (ARCH-002 C.4) and fault_sources "
                    "(ARCH-002 C.6), both mechanically extracted and verified "
                    "by extract_irqfault.py. No manual splitting step -- this "
                    "script performs the same fixed key grouping every time."),
        "imports": [],
        "irq_sources": combined["irq_sources"],
        "fault_sources": combined["fault_sources"],
    }

    json.dump(events_spec, open(events_out, "w", encoding="utf-8"), indent=2)
    json.dump(interrupt_spec, open(interrupt_out, "w", encoding="utf-8"), indent=2)
    print(f"OK: split {combined_path} -> {events_out} "
          f"({len(combined['event_sources'])} event sources, "
          f"{len(combined['event_registry'])} registry entries)")
    print(f"    -> {interrupt_out} "
          f"({len(combined['irq_sources'])} irq sources, "
          f"{len(combined['fault_sources'])} fault sources)")


if __name__ == "__main__":
    main()
