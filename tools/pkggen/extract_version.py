#!/usr/bin/env python3
"""
extract_version.py -- extractor for dfc_version_pkg.json.

Unlike every other extractor in this project, this one does NOT parse a
source .md document directly. It reads dfc_registers_pkg.json -- the
ALREADY-extracted, already-verified output of extract_registers.py -- and
picks out specific sub-fields of specific CONST-class Identification-
block registers that dfc_version_pkg.sv needs as standalone constants.

This is a deliberate, correct design, not a shortcut: every value here
already went through extract_registers.py's own real verification (32-bit
tiling, unique addresses, recognized access classes) when THAT file was
generated. Re-deriving these same values from raw REG-002.md prose again
here would just be a second, redundant, and strictly less reliable path
to the exact same numbers extract_registers.py already confirmed
correctly.

Confirmed via a real diff against this project's history that this
matters: an old, hand-assembled dfc_version_pkg.json recorded
DFC_REGMAP_REV_MINOR as 0x0001; the actual, current REG-002.md has it at
0x0002. The hand-assembled file had silently drifted. This extractor
cannot drift the same way, because it always reads whatever
dfc_registers_pkg.json most recently, really contains.

VERIFICATION (fail-loud; nothing written on any failure):
  * dfc_registers_pkg.json must exist and be readable
  * every specific struct/field this package needs must actually be
    present in it, by exact name -- if REG-002's Identification block
    is ever restructured (a field renamed, a register removed), this
    fails loud rather than silently emitting a stale or invented value
"""
import sys, json

# Each entry: (output constant name, output width, source struct name,
# source field name within that struct)
NEEDED = [
    ("DFC_DEVICE_ID",         32, "dfc_reg_dfc_device_id_t",   "DEVICE_ID"),
    ("DFC_PRODUCT_REV_MAJOR", 16, "dfc_reg_dfc_product_rev_t", "MAJOR"),
    ("DFC_PRODUCT_REV_MINOR", 16, "dfc_reg_dfc_product_rev_t", "MINOR"),
    ("DFC_REGMAP_REV_MAJOR",  16, "dfc_reg_dfc_regmap_rev_t",  "MAJOR"),
    ("DFC_REGMAP_REV_MINOR",  16, "dfc_reg_dfc_regmap_rev_t",  "MINOR"),
    ("DFC_CAPABILITY0_RESET", 24, "dfc_reg_dfc_capability0_t", "MODULE_PRESENT"),
]


def main():
    if len(sys.argv) != 3:
        print("usage: extract_version.py <dfc_registers_pkg.json> <out.json>", file=sys.stderr)
        sys.exit(2)
    regs_path, out_path = sys.argv[1], sys.argv[2]

    try:
        regs_spec = json.load(open(regs_path, encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        print(f"EXTRACTION FAILED: could not read {regs_path}: {e}", file=sys.stderr)
        sys.exit(1)

    struct_by_name = {s["name"]: s for s in regs_spec.get("structs", [])}

    params, errors = [], []
    for const_name, width, struct_name, field_name in NEEDED:
        struct = struct_by_name.get(struct_name)
        if struct is None:
            errors.append(f"{const_name}: struct '{struct_name}' not found in "
                          f"{regs_path} -- has REG-002's Identification block "
                          f"been restructured?")
            continue
        field = next((f for f in struct["fields"] if f["name"] == field_name), None)
        if field is None:
            errors.append(f"{const_name}: field '{field_name}' not found in "
                          f"struct '{struct_name}'")
            continue
        params.append({"name": const_name, "width": width, "value": field["reset"],
                       "trace": f"derived from {struct_name}.{field_name} "
                                f"(itself extracted from REG-002 by "
                                f"extract_registers.py)"})

    # DFC_BUILD_ID is deliberately NOT emitted: REG-002 defines it as a
    # generated build parameter (default 0x00000000), not a fixed,
    # document-derived constant. Inventing a literal here would fabricate
    # a value the document itself does not fix -- same discipline as
    # extract_registers.py's own non-numeric-reset handling.

    if errors:
        print(f"EXTRACTION FAILED ({len(errors)} error(s); nothing written):", file=sys.stderr)
        for e in errors:
            print("  " + e, file=sys.stderr)
        sys.exit(1)

    spec = {
        "package": "dfc_version_pkg",
        "_source": ("GENERATED by extract_version.py, deriving every value from "
                    "dfc_registers_pkg.json's already-extracted, already-verified "
                    "CONST-class Identification-block register fields (REG-002 "
                    "0x0000-0x0010). No raw document parsing performed here -- "
                    "extract_registers.py already did that verification. "
                    "DFC_BUILD_ID intentionally omitted: REG-002 defines it as "
                    "the generated build parameter BUILD_ID (default "
                    "0x00000000), not a fixed constant."),
        "imports": [],
        "params": params,
    }
    json.dump(spec, open(out_path, "w", encoding="utf-8"), indent=2)
    print(f"OK: {len(params)} version constants derived from "
          f"{regs_path}'s Identification-block fields -> {out_path}")


if __name__ == "__main__":
    main()
