#!/usr/bin/env python3
"""
pkggen.py -- generic SystemVerilog package emitter.

Takes any dfc_*_pkg.json (produced by extract_registers.py, extract_types.py,
extract_irqfault.py, or hand-assembled from their verified output, as with
dfc_version_pkg.json / dfc_constants_pkg.json / dfc_events_pkg.json /
dfc_interrupt_pkg.json) and emits the corresponding dfc_*_pkg.sv.

This file has NO document-specific data of any kind -- every literal it emits
comes from the input JSON's "params"/"structs"/"*_sources"/"event_registry"
fields. It recognizes four JSON shapes and emits accordingly:

  1. params only               (dfc_version_pkg, dfc_constants_pkg)
  2. params + structs          (dfc_registers_pkg)
  3. structs only              (dfc_types_pkg)
  4. source-matrix arrays      (dfc_events_pkg, dfc_interrupt_pkg)

Usage: pkggen.py <input.json> <output.sv>
"""
import sys, json, re

HEADER_TMPL = """\
// {pkg}.sv -- GENERATED by pkggen.py. Do not hand-edit; regenerate from the
// source JSON instead.
//
// {source}
"""


