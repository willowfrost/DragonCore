def sv_ident(name):
    ident = re.sub(r'[^A-Za-z0-9_]', '_', name)
    # SystemVerilog escaped identifier: \name<whitespace>. Prevents reserved-keyword
    # collisions (e.g. a field literally named "sequence" in ARCH-002 Appendix B)
    # from producing a syntax error, without renaming the source-derived name.
    if ident in SV_KEYWORDS:
        return "\\" + ident + " "
    return ident


def emit_params(params):
    if not params:
        return ""
    lines = []
    for p in params:
        w = p.get("width")
        val = p["value"]
        trace = p.get("trace", "")
        if trace:
            lines.append(f"  // {trace}")
        if isinstance(val, str) and val.lower().startswith("0x"):
            lit = f"{w}'h{val[2:]}" if w else val
        elif isinstance(val, str) and "_" in val and val.replace("_", "").isdigit():
            lit = f"{w}'d{val.replace('_','')}" if w else val
        elif isinstance(val, str) and val.isdigit():
            lit = f"{w}'d{val}" if w else val
        else:
            # non-numeric (e.g. a build-parameter description) -- emit as a comment-only
            # entry, never invent a literal value the source doc didn't fix.
            lines.append(f"  // NOTE: {p['name']} has no fixed literal in source ({val}); "
                         f"omitted from emission, not invented.")
            continue
        lines.append(f"  localparam logic [{ (w or 32) -1}:0] {sv_ident(p['name'])} = {lit};")
    return "\n".join(lines) + "\n"


def emit_struct(s):
    name = sv_ident(s["name"])
    width = s.get("width")
    fields = s["fields"]
    if width is None:
        width = max(f["hi"] for f in fields) + 1
    lines = [f"  // {s.get('trace','')}", f"  typedef struct packed {{"]
    # packed structs declare MSB-first; sort fields by hi descending
    for f in sorted(fields, key=lambda f: -f["hi"]):
        w = f["hi"] - f["lo"] + 1
        fname = sv_ident(f["name"])
        extra = ""
        if "access" in f:
            extra = f"  // access={f['access']} reset={f.get('reset','?')}"
        elif "semantic" in f:
            sign = "signed" if f.get("signed") else ""
            extra = f"  // {sign} reset={f.get('reset','?')} :: {f['semantic']}"
        if w == 1:
            lines.append(f"    logic {fname};{extra}")
        else:
            lines.append(f"    logic [{w-1}:0] {fname};{extra}")
    lines.append(f"  }} {name};")
    lines.append(f"  // total width: {width} bits")
    return "\n".join(lines) + "\n"


def emit_matrix_array(pkg_name, key, rows):
    """Emit a source-matrix (irq/event/fault/event_registry) as a localparam array of
    packed struct entries, one const struct type + one array constant."""
    if not rows:
        return ""
    sample = rows[0]
    fields = list(sample.keys())
    type_name = f"{sv_ident(pkg_name)}_{key}_entry_t"
    lines = [f"  typedef struct packed {{"]
    # Represent every column as a fixed-width string-like byte array is overkill for RTL;
    # matrices here are metadata/documentation tables (producer names, semantics, clear
    # policy), not synthesizable datapath fields -- emit as a comment-annotated array of
    # localparam string associative content instead of a packed struct, since several
    # columns are free text (e.g. "Semantics", "Clear/reassert") rather than encodings.
    lines = [f"  // {key}: {len(rows)} entries (see accompanying .json for full text fields)"]
    for i, r in enumerate(rows):
        vals = ", ".join(f'{k}="{v}"' if isinstance(v, str) else f"{k}={v}" for k, v in r.items())
        lines.append(f"  // [{i}] {vals}")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 3:
        print("usage: pkggen.py <input.json> <output.sv>", file=sys.stderr)
        sys.exit(2)
    in_path, out_path = sys.argv[1], sys.argv[2]
    spec = json.load(open(in_path))
    pkg = spec["package"]
    source = spec.get("_source", "")

    body = []
    imports = spec.get("imports", [])
    import_lines = "".join(f"import {sv_ident(i)}::*;\n" for i in imports)

    if spec.get("params"):
        body.append(emit_params(spec["params"]))
    if spec.get("structs"):
        for s in spec["structs"]:
            body.append(emit_struct(s))
    for key in ("irq_sources", "event_sources", "fault_sources", "event_registry"):
        if spec.get(key):
            body.append(emit_matrix_array(pkg, key, spec[key]))

    if not body:
        print(f"EXTRACTION FAILED: {in_path} has no params/structs/source-matrix content "
              f"to emit; nothing written.", file=sys.stderr)
        sys.exit(1)

    out = [HEADER_TMPL.format(pkg=pkg, source=source)]
    out.append(f"package {sv_ident(pkg)};\n")
    # RTLSTD-LANG-008 prohibits wildcard package imports in functional RTL.
    # Confirmed via real Yosys synthesis (both the apt-packaged 0.33 and a
    # current 0.68 build) that `import <pkg>::*;` fails to parse in either
    # a package or module body -- not a version-specific bug, a persistent
    # frontend limitation. No package this generator has produced actually
    # needs a cross-package import (checked directly against every "imports"
    # entry in the source JSON before removing this), so pkggen.py never
    # emits an import statement at all; a package needing another's symbols
    # must reference them fully-qualified (pkgname::SYMBOL) at the use site.
    out.append("\n".join(body))
    out.append(f"\nendpackage : {sv_ident(pkg)}\n")

    open(out_path, "w").write("\n".join(out))
    n_params = len(spec.get("params", []))
    n_structs = len(spec.get("structs", []))
    n_matrix = sum(len(spec.get(k, [])) for k in
                   ("irq_sources", "event_sources", "fault_sources", "event_registry"))
    print(f"OK: {pkg} -> {out_path}  "
          f"({n_params} params, {n_structs} structs, {n_matrix} matrix rows)")


if __name__ == "__main__":
    main()
