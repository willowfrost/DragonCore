// ulx3s_dfc_top.sv -- ULX3S (ECP5 LFE5U-85F-6BG381C) platform wrapper for
// Dragon Core skeleton HIL bring-up.
//
// Per ARCH-TECH-001/002: platform wrappers own pad cells, clock/reset
// resources, and physical constraints; they preserve dfc_rtl024's logical
// contract exactly. This file contains NO Dragon Core functional logic --
// only board-specific clock generation, reset qualification, and pin
// mapping. dfc_rtl024 already implements ARCH-RST-001's internal
// core_rst_n synchronizer from a por_n_i input; this wrapper only needs to
// supply a clean 50 MHz clock and a clean POR pulse, then map dfc_rtl024's
// logical ports onto real board pins.
//
// ============================================================================
// SCOPE OF THIS BRING-UP WRAPPER:
//
// REAL:
//   - Clock: ULX3S's onboard 25 MHz oscillator (clk_25mhz, pin G2) is
//     multiplied to the ARCH-CLK-001-required 50 MHz via a real ECP5 PLL
//     (EHXPLLL primitive), generated by Project Trellis's ecppll utility
//     -- not hand-written primitive parameters. See dfc_ecp5_pll.v.
//   - POR: a startup counter (16 core_clk cycles) generates a clean por_n
//     pulse independent of any board button -- the board has no dedicated
//     hardware POR pin exposed to user logic, so this is the platform-
//     appropriate substitute for ARCH-RST-001's "external/platform reset"
//     source. Uses FF initial-value support, a standard, well-supported
//     ECP5/Trellis idiom.
//   - SPI pins: mapped to J1 header gp[0:3] (confirmed free, general-
//     purpose pins in the real board constraint file -- not shared with
//     configuration flash, SDRAM, or the onboard WiFi module).
//     gp0=SCLK(in), gp1=CS_N(in), gp2=MOSI(in), gp3=MISO(tristate out).
//   - host_irq_n_o: mapped to gp4.
//   - GPIO: mapped to J1 gp[5:7] and J2 gp[22:26] (8 single-ended-only
//     positions, confirmed free per the real board constraint file --
//     see ULX3S_CONNECTION_MAP.md's own new GPIO section for exactly how
//     each site was confirmed). Each pin is a real ECP5 tristate, driven
//     by dfc_rtl024's own gpio_o/gpio_oe_o and read back via gpio_i,
//     the same tristate idiom already used for gp3 (SPI MISO).
//   - Debug LEDs: PLL-locked and POR-released status only, using signals
//     this wrapper itself generates -- no hierarchical reference into
//     dfc_rtl024's internals.
//   - Rotor RPM Monitor (RTL-007): mapped to J2 gp27, the last remaining
//     single-ended-only position (confirmed free per the real board
//     constraint file -- see ULX3S_CONNECTION_MAP.md's own new Section 6
//     for exactly how the site was confirmed). A plain single-ended input
//     -- no tristate needed, unlike gp3/the GPIO channels above --
//     dfc_rtl007.sv itself owns the real CDC-PULSE synchronizer.
//   - Engine RPM Monitor (RTL-008): mapped to J1 gp8, the first position of
//     the differential-capable range (the single-ended-only range having
//     been fully exhausted by RTL-007 -- confirmed free per the real board
//     constraint file, see ULX3S_CONNECTION_MAP.md's own new Section 7).
//     A plain single-ended input, same idiom as gp27 above -- used as an
//     ordinary single-ended pin per ULX3S's own manual (differential pairs
//     can be used single-ended when not paired for LVDS) -- dfc_rtl008.sv
//     itself owns its own, independent CDC-PULSE synchronizer instance (no
//     sharing with dfc_rtl007.sv's).
//
// NOT WIRED (tied safe, matching dfc_rtl024's own disclosed skeleton
// scope -- RTL-009 through RTL-023 don't exist yet):
//   ARINC, CAN, UART, pulse/health monitoring inputs, user I/O,
//   production-test pins, safety outputs. See dfc_rtl024.sv's own header
//   for exactly what's stubbed and why.
// ============================================================================

module ulx3s_dfc_top (
  input  logic clk_25mhz,
  inout  wire  gp0,   // SPI SCLK (host-driven input)
  inout  wire  gp1,   // SPI CS_N (host-driven input)
  inout  wire  gp2,   // SPI MOSI (host-driven input)
  inout  wire  gp3,   // SPI MISO (ECP5-driven tristate output)
  inout  wire  gp4,   // host_irq_n_o (ECP5-driven output)
  inout  wire  gp5,   // GPIO channel 0
  inout  wire  gp6,   // GPIO channel 1
  inout  wire  gp7,   // GPIO channel 2
  inout  wire  gp22,  // GPIO channel 3
  inout  wire  gp23,  // GPIO channel 4
  inout  wire  gp24,  // GPIO channel 5
  inout  wire  gp25,  // GPIO channel 6
  inout  wire  gp26,  // GPIO channel 7
  input  logic gp27,  // Rotor RPM tachometer pulse input (RTL-007)
  input  logic gp8,   // Engine RPM tachometer pulse input (RTL-008)
  output logic [7:0] led
);

  // ---- Clock generation: real PLL, 25 MHz -> 50 MHz ----
  logic core_clk;
  logic pll_locked;

  dfc_ecp5_pll u_pll (
    .clk_25mhz (clk_25mhz),
    .core_clk  (core_clk),
    .locked    (pll_locked)
  );

  // ---- POR generation: 16-cycle startup counter, no board button ----
  logic [3:0] por_count_q;
  logic       por_n;

  always_ff @(posedge core_clk) begin
    if (por_count_q != 4'hF) por_count_q <= por_count_q + 4'd1;
  end
  initial por_count_q = 4'h0;  // FF initial-value support (ECP5/Trellis-safe)

  assign por_n = pll_locked && (por_count_q == 4'hF);

  // ---- SPI pin mapping: gp0/1/2 are pure inputs from the host; gp3 is a
  // real tristate driven by the bridge's own output-enable ----
  logic spi_sclk, spi_cs_n, spi_mosi, spi_miso, spi_miso_oe;

  assign spi_sclk = gp0;
  assign spi_cs_n = gp1;
  assign spi_mosi = gp2;
  assign gp3      = spi_miso_oe ? spi_miso : 1'bz;

  // ---- host_irq_n_o: real ECP5-driven output, no host driving in ----
  logic host_irq_n;
  assign gp4 = host_irq_n;

  // ---- GPIO: 8 real bidirectional channels, same tristate idiom as
  // gp3 (SPI MISO) above -- gpio_i always reads the pad; gpio_o only
  // actually drives the pad while the corresponding gpio_oe_o bit is
  // asserted, high-Z otherwise. See ULX3S_CONNECTION_MAP.md's new GPIO
  // section for the real gp<N>-to-channel mapping and site confirmation. ----
  logic [7:0] gpio_i, gpio_o, gpio_oe_o;

  assign gpio_i[0] = gp5;
  assign gpio_i[1] = gp6;
  assign gpio_i[2] = gp7;
  assign gpio_i[3] = gp22;
  assign gpio_i[4] = gp23;
  assign gpio_i[5] = gp24;
  assign gpio_i[6] = gp25;
  assign gpio_i[7] = gp26;

  assign gp5  = gpio_oe_o[0] ? gpio_o[0] : 1'bz;
  assign gp6  = gpio_oe_o[1] ? gpio_o[1] : 1'bz;
  assign gp7  = gpio_oe_o[2] ? gpio_o[2] : 1'bz;
  assign gp22 = gpio_oe_o[3] ? gpio_o[3] : 1'bz;
  assign gp23 = gpio_oe_o[4] ? gpio_o[4] : 1'bz;
  assign gp24 = gpio_oe_o[5] ? gpio_o[5] : 1'bz;
  assign gp25 = gpio_oe_o[6] ? gpio_o[6] : 1'bz;
  assign gp26 = gpio_oe_o[7] ? gpio_o[7] : 1'bz;

  // ---- Dragon Core top-level: real instantiation, no functional logic
  // added in this wrapper ----
  dfc_rtl024 u_dragon_core (
    .core_clk_i    (core_clk),
    .por_n_i       (por_n),

    .spi_sclk_i    (spi_sclk),
    .spi_cs_n_i    (spi_cs_n),
    .spi_mosi_i    (spi_mosi),
    .spi_miso_o    (spi_miso),
    .spi_miso_oe_o (spi_miso_oe),

    .host_irq_n_o  (host_irq_n),

    .gpio_i        (gpio_i),
    .gpio_o        (gpio_o),
    .gpio_oe_o     (gpio_oe_o),

    .arinc_rx_i                 (1'b0),
    .arinc_tx_ctrl_o            (),
    .arinc_rx_adapter_error_i   (1'b0),
    .arinc_tx_adapter_error_i   (1'b0),

    .can_rx_i                (1'b1),  // recessive idle
    .can_tx_o                (),
    .can_transceiver_error_i (1'b0),

    .uart_rx_i (1'b1),  // idle high
    .uart_tx_o (),

    .rotor_i   (gp27),
    .engine_i  (gp8),
    .pulse_i   (2'b00),
    .health_i  (8'h00),

    .safety_out_o (),

    .user_i    (4'h0),
    .user_o    (),
    .user_oe_o (),

    .test_enable_i  (1'b0),
    .test_clock_i   (1'b0),
    .test_data_i    (1'b0),
    .test_data_o    (),
    .test_data_oe_o ()
  );

  // ---- Debug LEDs: bring-up status only, wrapper-generated signals only ----
  assign led[0] = pll_locked;
  assign led[1] = por_n;
  assign led[7:2] = 6'b0;

endmodule : ulx3s_dfc_top
